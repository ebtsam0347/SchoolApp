package com.forward.hrms.employee.entity.travel;


import com.forward.hrms.commons.core.jpa.AuditedEntity;
import com.forward.hrms.employee.enums.travel.TravelRequestStatus;
import jakarta.persistence.*;
import lombok.Getter;
import lombok.Setter;

import java.math.BigDecimal;
import java.time.LocalDateTime;

/**
 * Root transaction of the Travel / Factory Tour module.
 * <p>
 * A Travel Request represents one overall company travel request.
 * <p>
 * A request may later contain:
 * <p>
 * - multiple participants
 * - multiple travel legs
 * - applicable entitlements
 * - expense claims
 * - advances
 * - final settlement
 * <p>
 * Employee-specific information belongs to
 * TravelRequestParticipant.
 * <p>
 * Origin/destination information belongs to
 * TravelRequestLeg.
 * <p>
 * Policy-derived limits belong to
 * TravelRequestEntitlement.
 * <p>
 * The request intentionally stores only information that belongs
 * to the overall trip.
 */
@Entity
@Table(name = "travel_requests")
@Getter
@Setter
public class TravelRequest extends AuditedEntity {

    /**
     * Human-readable business request number.
     * <p>
     * Examples:
     * <p>
     * TR-2026-000001
     * TR-2026-000002
     * <p>
     * Generated by the application/service.
     */
    @Column(name = "request_no", nullable = false, length = 30, unique = true)
    private String requestNo;

    /**
     * Employee who initiated/submitted the Travel Request.
     * <p>
     * This is intentionally stored as an employee ID rather than
     * a JPA relationship because the Employee is part of the
     * Employee domain and the schema does not define a foreign key.
     */
    @Column(name = "requester_employee_id", nullable = false)
    private Long requesterEmployeeId;

    /**
     * Business code identifying the type of travel. One of
     * {@link com.forward.hrms.employee.enums.travel.TravelType}:
     * <p>
     * LOCAL
     * INTERNATIONAL
     * <p>
     * This is the selector for the request's entitlement policy —
     * {@code LOCAL -> LOCAL_FACTORY_TRAVEL},
     * {@code INTERNATIONAL -> INTERNATIONAL_FACTORY_TRAVEL} — so it is stored as
     * the enum's name rather than a free-form master-data code.
     */
    @Column(name = "travel_type_code", nullable = false, length = 50)
    private String travelTypeCode;

    /**
     * Currency used for monetary values associated with this
     * Travel Request.
     * <p>
     * Examples:
     * <p>
     * PKR
     * USD
     * AED
     */
    @Column(name = "currency_code", nullable = false, length = 3)
    private String currencyCode;

    /**
     * Overall business purpose/reason for the travel.
     * <p>
     * Example:
     * <p>
     * Visit Lahore factory for production inspection and
     * coordination with the manufacturing team.
     */
    @Column(name = "purpose", nullable = false, columnDefinition = "TEXT")
    private String purpose;

    /**
     * Overall planned departure/start date and time.
     */
    @Column(name = "start_datetime", nullable = false)
    private LocalDateTime startDatetime;

    /**
     * Overall planned return/end date and time.
     */
    @Column(name = "end_datetime", nullable = false)
    private LocalDateTime endDatetime;

    /**
     * Travel policy version selected for this request.
     * <p>
     * Stored as a plain {@code Long} FK (project convention); the DB
     * foreign key {@code fk_travel_requests_policy_version} lives in the
     * migration. Retaining the id ensures historical requests keep
     * pointing at the policy version applicable when they were created,
     * even after a newer policy is introduced.
     */
    @Column(name = "policy_version_id", nullable = false)
    private Long policyVersionId;

    /**
     * Overall lifecycle state of the Travel Request.
     * <p>
     * DRAFT
     * SUBMITTED
     * APPROVED
     * REJECTED
     * CANCELLED
     * IN_PROGRESS
     * COMPLETED
     * SETTLEMENT_PENDING
     * SETTLED
     */
    @Enumerated(EnumType.STRING)
    @Column(name = "status", nullable = false, length = 30)
    private TravelRequestStatus status = TravelRequestStatus.DRAFT;

    /**
     * Reference returned by the shared Approval module.
     * <p>
     * This is intentionally NOT a JPA relationship and NOT a
     * database foreign key because Approval is an external/shared
     * module.
     * <p>
     * Example:
     * <p>
     * APR-2026-000458
     */
    @Column(name = "approval_reference", length = 100)
    private String approvalReference;

    /**
     * Estimated total cost of the trip at request time.
     * <p>
     * This is an estimate used for planning and approval.
     * <p>
     * It is not the final expense/settlement amount.
     * <p>
     * The backend should calculate this value rather than
     * trusting an amount supplied directly by the frontend.
     */
    @Column(
            name = "estimated_amount",
            precision = 15,
            scale = 2
    )
    private BigDecimal estimatedAmount;

    /**
     * Timestamp when the request was submitted to the approval
     * workflow.
     */
    @Column(name = "submitted_at")
    private LocalDateTime submittedAt;

    /**
     * Timestamp when the request reached the approved state.
     */
    @Column(name = "approved_at")
    private LocalDateTime approvedAt;

    /**
     * Timestamp when actual travel started.
     */
    @Column(name = "started_at")
    private LocalDateTime startedAt;

    /**
     * Timestamp when the travel was marked as completed.
     */
    @Column(name = "completed_at")
    private LocalDateTime completedAt;

    /**
     * Timestamp when the request was canceled.
     */
    @Column(name = "cancelled_at")
    private LocalDateTime cancelledAt;

    /**
     * Explanation/reason for cancellation.
     */
    @Column(name = "cancellation_reason", columnDefinition = "TEXT")
    private String cancellationReason;

    /**
     * JPA/Hibernate optimistic-locking version.
     * <p>
     * This is a technical record version and is unrelated to
     * TravelPolicyVersion.versionNo.
     */
    @Version
    @Column(name = "version", nullable = false)
    private Long version;

    /**
     * Fuel policy applicable to the overall request: the single policy
     * shared by every leg that has one, or {@code null} when legs carry
     * different fuel policies. {@link TravelRequestLeg#getTravelFuelPolicyId()}
     * is the per-leg source of truth.
     */
    @Column(name = "travel_fuel_policy_id")
    private Long travelFuelPolicyId;

    /**
     * Sum of {@link TravelRequestLeg#getPetrolIssued()} across every leg of
     * this request, maintained by Transport verification.
     */
    @Column(
            name = "petrol_issued",
            precision = 12,
            scale = 2,
            nullable = false
    )
    private BigDecimal petrolIssued = BigDecimal.ZERO;

    /**
     * Pure summary column: sum of {@link TravelRequestLeg#getActualDistanceKm()}
     * across every leg of this request, maintained by Transport verification.
     * {@link TravelRequestLeg#getActualDistanceKm()} remains the sole
     * authoritative Transport-approved distance — this field never
     * independently recalculates it.
     */
    @Column(
            name = "total_distance_km",
            precision = 12,
            scale = 2,
            nullable = false
    )
    private BigDecimal totalDistanceKm = BigDecimal.ZERO;
}