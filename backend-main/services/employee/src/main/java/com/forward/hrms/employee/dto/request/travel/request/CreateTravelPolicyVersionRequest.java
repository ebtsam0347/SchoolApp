package com.forward.hrms.employee.dto.request.travel.request;

import jakarta.validation.constraints.AssertTrue;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Size;

import java.time.LocalDate;

/**
 * Request payload used to create a new Travel Policy Version.
 *
 * <p>
 * A Travel Policy is versioned so that historical Travel Requests
 * continue to reference the exact policy version that was applicable
 * when the request was created.
 *
 * <p>
 * Example endpoint:
 *
 * <pre>
 * POST /travel/policies
 * </pre>
 *
 * <p>
 * Example payload:
 *
 * <pre>
 * {
 *     "policyCode": "LOCAL_FACTORY_TRAVEL",
 *     "policyName": "Local Factory Travel Policy",
 *     "effectiveFrom": "2026-09-01",
 *     "effectiveTo": "2027-06-30",
 *     "description": "Travel policy applicable to factory visits."
 * }
 * </pre>
 *
 * <p>
 * The following values are intentionally not supplied by the client:
 *
 * <ul>
 *     <li>versionNo - generated by the backend</li>
 *     <li>status - newly created policies start as DRAFT</li>
 *     <li>JPA version - managed by Hibernate</li>
 * </ul>
 */
public record CreateTravelPolicyVersionRequest(

        /*
         * Business identifier of the Travel Policy, e.g.
         * "LOCAL_FACTORY_TRAVEL". Multiple versions of the same policy use the same policy code
         * but have different business version numbers.
         */
        @NotBlank(message = "Policy code is required")
        @Size(max = 50, message = "Policy code must not exceed 50 characters")
        String policyCode,

        /*
         * Human-readable name of the policy, e.g. "Factory Travel Policy".
         */
        @NotBlank(message = "Policy name is required")
        @Size(max = 200, message = "Policy name must not exceed 200 characters")
        String policyName,

        /* Date from which this policy version becomes applicable. */
        @NotNull(message = "Effective from date is required")
        LocalDate effectiveFrom,

        /*
         * Optional date until which this policy version remains applicable.
         * NULL means that no end date has been defined.
         */
        LocalDate effectiveTo,

        /* Optional administrative/business description. */
        String description
) {

    /**
     * Validates that the policy effective end date, when supplied, is
     * not before the effective start date.
     */
    @AssertTrue(
            message = "Effective to date must be after or equal to effective from date"
    )
    public boolean isEffectiveDateRangeValid() {
        if (effectiveFrom == null || effectiveTo == null) {
            return true;
        }
        return !effectiveTo.isBefore(effectiveFrom);
    }
}
