-- ============================================================
-- Travel Module
-- Table: travel_request_settlements
--
-- Purpose:
-- Stores the financial settlement of a Travel Request.
--
-- A settlement reconciles:
--
--      Eligible / approved expenses
--                  +
--      Advances paid
--                  +
--      Adjustments
--                  =
--      Final settlement balance
--
--
-- Possible outcomes:
--
-- 1. COMPANY_PAYABLE
--
--    Employee spent more than the advance.
--
--    Expenses = 42,000
--    Advance  = 35,000
--
--    Company owes employee = 7,000
--
--
-- 2. EMPLOYEE_RECEIVABLE
--
--    Employee received more advance than the eligible
--    expenses.
--
--    Expenses = 31,000
--    Advance  = 35,000
--
--    Employee owes company = 4,000
--
--
-- The actual supporting advances and expenses are linked through
-- travel_settlement_items.
--
-- This table represents the SETTLEMENT HEADER.
-- ============================================================


CREATE TABLE travel_request_settlements
(
    id                            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,


    -- ========================================================
    -- Travel Request relationship
    -- ========================================================

    -- Travel Request being settled.
    travel_request_id             BIGINT         NOT NULL,


    -- Participant whose financial responsibility is being
    -- settled.
    --
    -- Important for multi-employee Travel Requests.
    travel_request_participant_id BIGINT         NOT NULL,


    -- ========================================================
    -- Settlement identification
    -- ========================================================

    -- Human-readable settlement reference.
    --
    -- Example:
    --
    -- SET-2026-000125
    settlement_number             VARCHAR(50)    NOT NULL,


    -- ========================================================
    -- Settlement type
    -- ========================================================

    -- FINAL:
    -- Complete settlement after the trip.
    --
    -- INTERIM:
    -- Partial settlement where the trip/process is not yet
    -- completely closed.
    --
    -- ADJUSTMENT:
    -- Subsequent correction/adjustment to an existing settlement.
    settlement_type_code          VARCHAR(30)    NOT NULL,


    -- ========================================================
    -- Settlement lifecycle
    -- ========================================================

    -- DRAFT
    -- SUBMITTED
    -- UNDER_REVIEW
    -- APPROVED
    -- PARTIALLY_APPROVED
    -- REJECTED
    -- PAYMENT_PENDING
    -- RECOVERY_PENDING
    -- PAID
    -- RECOVERED
    -- SETTLED
    -- CANCELLED
    status                        VARCHAR(30)    NOT NULL DEFAULT 'DRAFT',


    -- ========================================================
    -- Expense totals
    -- ========================================================

    -- Total amount claimed through expense records included
    -- in this settlement.
    total_claimed_expenses        NUMERIC(15, 2) NOT NULL DEFAULT 0,


    -- Total amount eligible according to Travel Policy.
    total_eligible_expenses       NUMERIC(15, 2) NOT NULL DEFAULT 0,


    -- Total amount finally approved by the reviewer.
    total_approved_expenses       NUMERIC(15, 2) NOT NULL DEFAULT 0,


    -- ========================================================
    -- Advance totals
    -- ========================================================

    -- Total amount actually paid to the employee as travel
    -- advance and included in this settlement.
    total_advances_paid           NUMERIC(15, 2) NOT NULL DEFAULT 0,


    -- ========================================================
    -- Adjustment totals
    -- ========================================================

    -- Positive/negative business adjustments applied during
    -- settlement.
    --
    -- Example:
    --
    -- Approved special expense not represented by normal
    -- entitlement.
    total_adjustments             NUMERIC(15, 2) NOT NULL DEFAULT 0,


    -- ========================================================
    -- Final settlement
    -- ========================================================

    -- Final amount after reconciliation.
    --
    -- The sign/direction is represented by settlement_direction.
    final_settlement_amount       NUMERIC(15, 2) NOT NULL DEFAULT 0,


    -- COMPANY_PAYABLE:
    -- Company owes employee.
    --
    -- EMPLOYEE_RECEIVABLE:
    -- Employee owes company.
    --
    -- NO_BALANCE:
    -- Everything is exactly reconciled.
    settlement_direction          VARCHAR(30)    NOT NULL,


    -- ========================================================
    -- Currency
    -- ========================================================

    settlement_currency_code      VARCHAR(3)        NOT NULL,


    -- ========================================================
    -- Explanation
    -- ========================================================

    -- Human-readable explanation of the final settlement.
    settlement_summary            TEXT,


    -- ========================================================
    -- Approval / review
    -- ========================================================

    -- Approval workflow request from the existing Approval
    -- Module.
    approval_request_id           BIGINT,


    approved_at                   TIMESTAMP,


    approved_by                   BIGINT,


    -- ========================================================
    -- Payment / recovery
    -- ========================================================

    -- Reference of the final company payment OR employee
    -- recovery transaction.
    settlement_payment_reference  VARCHAR(100),


    -- External transaction identifier from Payroll/Finance.
    external_transaction_id       VARCHAR(150),


    -- Date on which final settlement payment/recovery happened.
    settled_at                    TIMESTAMP,


    -- ========================================================
    -- Finalization
    -- ========================================================

    -- Indicates that this settlement has been finalized and
    -- should no longer be modified as a normal draft record.
    is_finalized                  BOOLEAN        NOT NULL DEFAULT FALSE,


    finalized_at                  TIMESTAMP,


    finalized_by                  BIGINT,


    -- ========================================================
    -- Remarks
    -- ========================================================

    remarks                       TEXT,


    -- ========================================================
    -- Audit fields
    -- ========================================================

    created_at                    TIMESTAMP    NOT NULL DEFAULT now(),

    created_by                    VARCHAR(64)         NOT NULL,

    updated_at                    TIMESTAMP    NOT NULL DEFAULT now(),

    updated_by                    VARCHAR(64)         NOT NULL,
    ip_address                    INET,


    -- ========================================================
    -- Optimistic locking
    -- ========================================================

    version                       BIGINT         NOT NULL DEFAULT 0,


    -- ========================================================
    -- Foreign keys
    -- ========================================================

    CONSTRAINT fk_travel_settlements_request
        FOREIGN KEY (travel_request_id)
            REFERENCES travel_requests (id)
            ON DELETE RESTRICT,


    CONSTRAINT fk_travel_settlements_participant
        FOREIGN KEY (travel_request_participant_id)
            REFERENCES travel_request_participants (id)
            ON DELETE RESTRICT,


    -- ========================================================
    -- Amount constraints
    -- ========================================================

    CONSTRAINT ck_travel_settlements_claimed_expenses
        CHECK (
            total_claimed_expenses >= 0
            ),


    CONSTRAINT ck_travel_settlements_eligible_expenses
        CHECK (
            total_eligible_expenses >= 0
            ),


    CONSTRAINT ck_travel_settlements_approved_expenses
        CHECK (
            total_approved_expenses >= 0
            ),


    CONSTRAINT ck_travel_settlements_advances
        CHECK (
            total_advances_paid >= 0
            ),


    CONSTRAINT ck_travel_settlements_final_amount
        CHECK (
            final_settlement_amount >= 0
            ),


    -- ========================================================
    -- Logical expense validation
    -- ========================================================

    CONSTRAINT ck_travel_settlements_eligible_not_over_claimed
        CHECK (
            total_eligible_expenses <= total_claimed_expenses
            ),


    CONSTRAINT ck_travel_settlements_approved_not_over_eligible
        CHECK (
            total_approved_expenses <= total_eligible_expenses
            ),


    -- ========================================================
    -- Type constraints
    -- ========================================================

    CONSTRAINT ck_travel_settlements_type
        CHECK (
            settlement_type_code IN (
                                     'FINAL',
                                     'INTERIM',
                                     'ADJUSTMENT'
                )
            ),


    CONSTRAINT ck_travel_settlements_direction
        CHECK (
            settlement_direction IN (
                                     'COMPANY_PAYABLE',
                                     'EMPLOYEE_RECEIVABLE',
                                     'NO_BALANCE'
                )
            ),


    -- ========================================================
    -- Status constraints
    -- ========================================================

    CONSTRAINT ck_travel_settlements_status
        CHECK (
            status IN (
                       'DRAFT',
                       'SUBMITTED',
                       'UNDER_REVIEW',
                       'APPROVED',
                       'PARTIALLY_APPROVED',
                       'REJECTED',
                       'PAYMENT_PENDING',
                       'RECOVERY_PENDING',
                       'PAID',
                       'RECOVERED',
                       'SETTLED',
                       'CANCELLED'
                )
            ),


    -- ========================================================
    -- Approval consistency
    -- ========================================================

    CONSTRAINT ck_travel_settlements_approval
        CHECK (
            approved_at IS NULL
                OR approved_by IS NOT NULL
            ),


    -- ========================================================
    -- Finalization consistency
    -- ========================================================

    CONSTRAINT ck_travel_settlements_finalization
        CHECK (
            is_finalized = FALSE
                OR finalized_at IS NOT NULL
            ),


    -- ========================================================
    -- Version
    -- ========================================================

    CONSTRAINT ck_travel_settlements_version
        CHECK (
            version >= 0
            )
);


-- ============================================================
-- Unique settlement reference
-- ============================================================

CREATE UNIQUE INDEX uq_travel_settlements_number
    ON travel_request_settlements (
                                   settlement_number
        );


-- ============================================================
-- Indexes
-- ============================================================


-- All settlements for a Travel Request.
CREATE INDEX idx_travel_settlements_request
    ON travel_request_settlements (
                                   travel_request_id
        );


-- All settlements for a participant.
CREATE INDEX idx_travel_settlements_participant
    ON travel_request_settlements (
                                   travel_request_participant_id
        );


-- Settlement processing queue.
CREATE INDEX idx_travel_settlements_status
    ON travel_request_settlements (
                                   status
        );


-- Find settlements requiring payment/recovery.
CREATE INDEX idx_travel_settlements_direction_status
    ON travel_request_settlements (
                                   settlement_direction,
                                   status
        );


-- Approval lookup.
CREATE INDEX idx_travel_settlements_approval
    ON travel_request_settlements (
                                   approval_request_id
        );


-- Finance reconciliation.
CREATE INDEX idx_travel_settlements_transaction
    ON travel_request_settlements (
                                   external_transaction_id
        );


-- Finalized settlement lookup.
CREATE INDEX idx_travel_settlements_finalized
    ON travel_request_settlements (
                                   is_finalized,
                                   settled_at
        );


