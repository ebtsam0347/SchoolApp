-- Approval workflow stages for employee requisitions.
-- The approval_workflow_stage table is normally created by commons-approval V0510,
-- but V0013 < V0510 so we create it here (IF NOT EXISTS). V0510 uses
-- CREATE TABLE IF NOT EXISTS throughout and is idempotent when the table exists.
create table if not exists approval_workflow_stage (
    id                 bigint generated by default as identity primary key,
    request_type       varchar(24) not null,
    stage_no           int         not null,
    resolver_kind      varchar(16) not null,
    approve_permission varchar(64),
    label              varchar(48) not null,
    active             boolean     not null default true,
    created_at         timestamp   not null default now(),
    updated_at         timestamp   not null default now(),
    created_by         varchar(64) not null,
    updated_by         varchar(64) not null,
    ip_address         inet
);

create unique index if not exists uq_workflow_stage_active
    on approval_workflow_stage (request_type, stage_no) where active;

-- 2-stage chain: HOD review (submitter's manager) then HR Admin final sign-off.
insert into approval_workflow_stage
    (request_type, stage_no, resolver_kind, approve_permission, label, created_by, updated_by)
values
    ('REQUISITION', 1, 'MANAGER',    null,             'HOD Review',  'system', 'system'),
    ('REQUISITION', 2, 'PERMISSION', 'employee.admin', 'HR Approval', 'system', 'system');
