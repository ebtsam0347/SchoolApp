-- ============================================================
-- Travel Module
-- Table: travel_policy_versions
--
-- Purpose:
-- Stores versioned company travel policies.
--
-- A policy must be versioned because travel requests and
-- expenses must continue to use the policy that was applicable
-- when the transaction was created/submitted.
--
-- Example:
--   FACTORY_TRAVEL / Version 1
--   Effective: 2025-07-01 -> 2026-06-30
--
--   FACTORY_TRAVEL / Version 2
--   Effective: 2026-07-01 -> 2027-06-30
--
-- Historical requests must continue referring to the applicable
-- policy version even after a newer policy becomes active.
-- ============================================================


CREATE TABLE travel_policy_versions
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Business identifier for the policy.
    -- Example: FACTORY_TRAVEL
    policy_code    VARCHAR(50)  NOT NULL,

    -- Human-readable policy name.
    -- Example: Factory Travel Policy
    policy_name    VARCHAR(200) NOT NULL,

    -- Sequential version number within a policy.
    -- Example: 1, 2, 3...
    version_no     INTEGER      NOT NULL,

    -- Date from which this policy version becomes applicable.
    effective_from DATE         NOT NULL,

    -- Date until which this policy version is applicable.
    -- NULL means there is currently no defined end date.
    effective_to   DATE,

    -- Lifecycle state of this policy version.
    --
    -- DRAFT   = being prepared and not yet applicable
    -- ACTIVE  = currently applicable
    -- INACTIVE = disabled before retirement
    -- RETIRED = historical policy no longer applicable
    status         VARCHAR(20)  NOT NULL DEFAULT 'DRAFT',

    -- Optional explanation or administrative notes.
    description    TEXT,

    -- Standard audit fields.
    created_at     TIMESTAMP  NOT NULL DEFAULT now(),
    created_by     VARCHAR(64)       NOT NULL,

    updated_at     TIMESTAMP  NOT NULL DEFAULT now(),
    updated_by     VARCHAR(64)       NOT NULL,
    ip_address     INET,

    -- Optimistic locking version.
    --
    -- This is intentionally different from version_no.
    --
    -- version_no:
    --   Business version of the travel policy.
    --
    -- version:
    --   Number of modifications to this database record.
    version        BIGINT       NOT NULL DEFAULT 0,

    -- --------------------------------------------------------
    -- Constraints
    -- --------------------------------------------------------

    CONSTRAINT uq_travel_policy_versions_code_version
        UNIQUE (policy_code, version_no),

    CONSTRAINT ck_travel_policy_versions_policy_code
        CHECK (BTRIM(policy_code) <> ''),

    CONSTRAINT ck_travel_policy_versions_policy_name
        CHECK (BTRIM(policy_name) <> ''),

    CONSTRAINT ck_travel_policy_versions_version_no
        CHECK (version_no > 0),

    CONSTRAINT ck_travel_policy_versions_effective_dates
        CHECK (
            effective_to IS NULL
                OR effective_to >= effective_from
            ),

    CONSTRAINT ck_travel_policy_versions_status
        CHECK (
            status IN (
                       'DRAFT',
                       'ACTIVE',
                       'INACTIVE',
                       'RETIRED'
                )
            ),

    CONSTRAINT ck_travel_policy_versions_version
        CHECK (version >= 0)
);


-- ============================================================
-- Indexes
-- ============================================================

-- Used when finding the policy for a particular effective date
-- or displaying policy versions chronologically.
CREATE INDEX idx_travel_policy_versions_effective_from
    ON travel_policy_versions (effective_from);


-- Used when filtering policies by lifecycle status.
CREATE INDEX idx_travel_policy_versions_status
    ON travel_policy_versions (status);


-- Useful for finding policies by business code and effective period.
CREATE INDEX idx_travel_policy_versions_code_effective
    ON travel_policy_versions (policy_code, effective_from);


