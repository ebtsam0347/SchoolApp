-- ============================================================
-- Travel Module
-- Table: travel_requests
--
-- Purpose:
-- Stores the main/root transaction for a company-approved
-- travel or factory tour request.
--
-- One row represents one Travel Request.
--
-- A Travel Request can contain:
--
--   - One requester
--   - One or more travel participants
--   - One or more travel legs
--   - Policy/grade-based entitlements
--   - Expense claims
--   - Advances
--   - Final settlement
--
-- This table intentionally stores only information that belongs
-- to the overall trip/request.
--
-- Employee-specific information belongs to:
--   travel_request_participants
--
-- Origin/destination/vehicle information belongs to:
--   travel_request_legs
--
-- Grade-based policy limits belong to:
--   travel_policy_grade_limits
--
-- Actual applicable limits for a particular trip belong to:
--   travel_request_entitlements
-- ============================================================


CREATE TABLE travel_requests
(
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- ========================================================
    -- Business identification
    -- ========================================================

    -- Human-readable business request number.
    --
    -- Example:
    --   TR-2026-000001
    --   TR-2026-000002
    --
    -- This should be generated by the application/service and
    -- should be the number shown to HR, employees and managers.
    request_no            VARCHAR(30) NOT NULL,

    -- Employee who initiated/submitted the Travel Request.
    --
    -- This is an Employee Service reference.
    -- No database FK is intentionally created because the
    -- employee entity is owned by the Employee domain.
    requester_employee_id BIGINT      NOT NULL,

    -- ========================================================
    -- Travel classification
    -- ========================================================

    -- Business code of the travel type.
    --
    -- Examples:
    --   FACTORY_DUTY
    --   FACTORY_VISIT
    --   BUSINESS_TRAVEL
    --   TRAINING
    --
    -- Travel types should be managed through the existing
    -- Master Data architecture rather than duplicated as a
    -- local travel_types table.
    travel_type_code      VARCHAR(50) NOT NULL,

    -- Currency used for the monetary values of this request.
    --
    -- Example:
    --   PKR
    --   USD
    --   AED
    --
    -- Currency is represented by a business code rather than
    -- a cross-service database FK.
    currency_code         VARCHAR(3)     NOT NULL,

    -- ========================================================
    -- Trip information
    -- ========================================================

    -- Overall reason/purpose for the travel.
    --
    -- Example:
    --   Visit Lahore factory for production inspection and
    --   coordination with the manufacturing team.
    purpose               TEXT        NOT NULL,

    -- Overall planned departure/start datetime of the trip.
    start_datetime        TIMESTAMP NOT NULL,

    -- Overall planned return/end datetime of the trip.
    end_datetime          TIMESTAMP NOT NULL,

    -- ========================================================
    -- Policy
    -- ========================================================

    -- Travel policy version selected for this request.
    --
    -- This is extremely important for historical consistency.
    --
    -- Example:
    --   policy_version_id = 2
    --
    -- If the company later changes:
    --   Dinner limit from PKR 1,500 to PKR 2,000
    --
    -- an existing request referencing policy version 2 must
    -- continue to use the rules applicable to version 2.
    policy_version_id     BIGINT      NOT NULL,

    -- ========================================================
    -- Request lifecycle
    -- ========================================================

    -- Overall lifecycle state of the Travel Request.
    --
    -- DRAFT
    -- SUBMITTED
    -- APPROVED
    -- REJECTED
    -- CANCELLED
    -- IN_PROGRESS
    -- COMPLETED
    -- SETTLEMENT_PENDING
    -- SETTLED
    --
    -- Approval-specific details remain owned by the existing
    -- shared Approval module.
    status                VARCHAR(30) NOT NULL DEFAULT 'DRAFT',

    -- Reference/identifier returned by the shared Approval
    -- module after an approval workflow is created.
    --
    -- This is NOT a database FK.
    --
    -- Example:
    --   APR-2026-000458
    approval_reference    VARCHAR(100),

    -- ========================================================
    -- Financial estimate
    -- ========================================================

    -- Estimated total cost of the complete trip at request time.
    --
    -- This is used for planning/approval and is NOT the final
    -- expense amount.
    --
    -- The backend should calculate this value rather than
    -- trusting a value sent directly by the frontend.
    estimated_amount      NUMERIC(15, 2),

    -- ========================================================
    -- Lifecycle timestamps
    -- ========================================================

    -- When the request was submitted to the approval workflow.
    submitted_at          TIMESTAMP,

    -- When the request reached an approved state.
    approved_at           TIMESTAMP,

    -- When the actual travel started.
    started_at            TIMESTAMP,

    -- When the travel was marked completed.
    completed_at          TIMESTAMP,

    -- When the request was canceled.
    cancelled_at          TIMESTAMP,

    -- Explanation when a request is canceled.
    cancellation_reason   TEXT,

    -- ========================================================
    -- Standard audit fields
    -- ========================================================

    created_at            TIMESTAMP NOT NULL DEFAULT now(),

    created_by            VARCHAR(64)      NOT NULL,

    updated_at            TIMESTAMP NOT NULL DEFAULT now(),

    updated_by            VARCHAR(64)      NOT NULL,
    ip_address            INET,

    -- ========================================================
    -- Optimistic locking
    -- ========================================================

    -- Technical version used by JPA/Hibernate optimistic locking.
    --
    -- This is different from:
    --
    --   travel_policy_versions.version_no
    --
    -- because that is the business version of a policy.
    version               BIGINT      NOT NULL DEFAULT 0,


    -- ========================================================
    -- Constraints
    -- ========================================================

    -- Every Travel Request must reference a valid policy version
    -- within the same Employee Service database.
    CONSTRAINT fk_travel_requests_policy_version
        FOREIGN KEY (policy_version_id)
            REFERENCES travel_policy_versions (id),


    -- Business request number must be unique.
    CONSTRAINT uq_travel_requests_request_no
        UNIQUE (request_no),


    -- Request number cannot be empty.
    CONSTRAINT ck_travel_requests_request_no
        CHECK (
            BTRIM(request_no) <> ''
            ),


    -- Travel type must contain a valid non-empty business code.
    CONSTRAINT ck_travel_requests_travel_type
        CHECK (
            BTRIM(travel_type_code) <> ''
            ),


    -- Currency must contain a valid non-empty code.
    CONSTRAINT ck_travel_requests_currency
        CHECK (
            BTRIM(currency_code) <> ''
            ),


    -- Purpose must contain actual text.
    CONSTRAINT ck_travel_requests_purpose
        CHECK (
            BTRIM(purpose) <> ''
            ),


    -- End of travel cannot occur before the beginning.
    CONSTRAINT ck_travel_requests_datetime_range
        CHECK (
            end_datetime >= start_datetime
            ),


    -- Estimated amount cannot be negative.
    CONSTRAINT ck_travel_requests_estimated_amount
        CHECK (
            estimated_amount IS NULL
                OR estimated_amount >= 0
            ),


    -- Only supported lifecycle states may be stored.
    CONSTRAINT ck_travel_requests_status
        CHECK (
            status IN (
                       'DRAFT',
                       'SUBMITTED',
                       'APPROVED',
                       'REJECTED',
                       'CANCELLED',
                       'IN_PROGRESS',
                       'COMPLETED',
                       'SETTLEMENT_PENDING',
                       'SETTLED'
                )
            ),


    -- Optimistic-locking version cannot be negative.
    CONSTRAINT ck_travel_requests_version
        CHECK (
            version >= 0
            )
);


-- ============================================================
-- Indexes
-- ============================================================


-- Main lookup:
-- Find requests created by a particular employee.
CREATE INDEX idx_travel_requests_requester
    ON travel_requests (requester_employee_id);


-- Find requests by lifecycle state.
--
-- Useful for:
--   Pending requests
--   Approved requests
--   In-progress trips
--   Settlement-pending trips
CREATE INDEX idx_travel_requests_status
    ON travel_requests (status);


-- Find requests by travel type.
CREATE INDEX idx_travel_requests_travel_type
    ON travel_requests (travel_type_code);


-- Find requests under a particular policy version.
CREATE INDEX idx_travel_requests_policy_version
    ON travel_requests (policy_version_id);


-- Useful for date-based HR reports and travel dashboards.
CREATE INDEX idx_travel_requests_start_datetime
    ON travel_requests (start_datetime);


-- Useful for date-range reporting and operational queries.
CREATE INDEX idx_travel_requests_end_datetime
    ON travel_requests (end_datetime);


-- Useful when displaying requests chronologically for HR.
CREATE INDEX idx_travel_requests_created_at
    ON travel_requests (created_at);


-- Useful for finding requests by approval workflow reference.
CREATE INDEX idx_travel_requests_approval_reference
    ON travel_requests (approval_reference);


