drop table if exists employee_requisitions;
create table employee_requisitions (
       id                      bigint generated by default as identity primary key,
       type                    varchar(16)  not null check ( type in('NEW_HIRE', 'REPLACEMENT') ),
       status                  varchar(20)  not null default 'DRAFT',
       department_id           bigint       not null,
       minimum_education       text,
       minimum_experience      int,
       minimum_skill           text,
       job_description         text,
       total_positions_hod     int not null, --sum of totals in employee_requisition_detail
       total_positions_lean    int, --sum of totals in employee_requisition_detail where is_lean_removed = false
       request_reason          text,
       hod_notes               text,

       requested_by_user_id    bigint,
       approved_by_user_id     bigint,
       approved_at             timestamp,
       reject_reason           text,
       created_at              timestamp    not null default now(),
       updated_at              timestamp    not null default now(),
       created_by              varchar(64)  not null,
       updated_by              varchar(64)  not null,
       ip_address              inet
);
create index idx_requisitions_type     on employee_requisitions (type);
create index idx_requisitions_status     on employee_requisitions (status);
create index idx_requisitions_department on employee_requisitions (department_id);



create table employee_requisition_detail (
    id                              bigint generated by default as identity primary key,
    requisition_head_id             bigint not null references employee_requisitions(id) on delete cascade,
    replacing_employee_id           bigint,
    new_employee_code               varchar(64),
    temporary_employee_reference    varchar(64),
    section_id                      bigint,
    designation_id                  bigint,
    grade_id                        bigint,
    employment_type                 varchar(16) check ( employment_type in('PERMANENT', 'CONTRACT', 'INTERN') ),
    employee_category               varchar(16) check ( employee_category in('DIRECT', 'INDIRECT') ),
    required_until                  date,
    gender                          varchar(16) check ( gender in('MALE', 'FEMALE', 'ANY') ),
    shift_id                        bigint,
    is_lean_removed                 boolean not null default false,
    lean_removed_remarks            varchar(64),
    lean_removed_by                 bigint,

    created_at                      timestamp    not null default now(),
    updated_at                      timestamp    not null default now(),
    created_by                      varchar(64)  not null,
    updated_by                      varchar(64)  not null,
    ip_address                      inet
);

create index idx_requisition_detail_head
    on employee_requisition_detail (requisition_head_id);

create index idx_requisition_detail_replacing_employee
    on employee_requisition_detail (replacing_employee_id);