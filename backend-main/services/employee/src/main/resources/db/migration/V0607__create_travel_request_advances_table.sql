-- ============================================================
-- Travel Module
-- Table: travel_request_advances
--
-- Purpose:
-- Stores advance requests associated with a Travel Request.
--
-- An advance represents money requested/approved before or
-- during official company travel.
--
-- This table tracks the BUSINESS lifecycle of the advance.
--
-- It does not replace Payroll/Finance payment/accounting
-- functionality.
--
--
-- Example:
--
-- Travel Request:
--   TR-2026-000125
--
-- Advance:
--   Requested = PKR 40,000
--   Approved  = PKR 35,000
--   Paid      = PKR 35,000
--
-- Later:
--
-- Actual eligible expenses = PKR 31,000
-- Advance paid             = PKR 35,000
--
-- Settlement:
--   Employee owes company = PKR 4,000
--
--
-- One Travel Request can have multiple advance records.
--
-- Example:
--
--   Advance #1 = PKR 30,000
--   Advance #2 = PKR 10,000
--
-- This allows future support for additional/emergency advances
-- without changing the Travel Request table.
-- ============================================================


CREATE TABLE travel_request_advances
(
    id                            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,


    -- ========================================================
    -- Travel Request relationship
    -- ========================================================

    -- Travel Request for which this advance is requested.
    travel_request_id             BIGINT         NOT NULL,


    -- Employee participant who will receive/be responsible
    -- for the advance.
    --
    -- This is important when multiple employees travel under
    -- the same Travel Request.
    travel_request_participant_id BIGINT         NOT NULL,


    -- ========================================================
    -- Advance identification
    -- ========================================================

    -- Human-readable advance reference.
    --
    -- Example:
    --
    -- ADV-2026-000125
    --
    -- This should be generated by the backend.
    advance_number                VARCHAR(50)    NOT NULL,


    -- Type/purpose of advance.
    --
    -- INITIAL
    -- ADDITIONAL
    -- EMERGENCY
    -- ADJUSTMENT
    --
    -- INITIAL:
    --   First advance for the trip.
    --
    -- ADDITIONAL:
    --   Additional approved amount after the initial advance.
    --
    -- EMERGENCY:
    --   Additional amount required during travel.
    --
    -- ADJUSTMENT:
    --   Administrative financial adjustment.
    advance_type_code             VARCHAR(30)    NOT NULL,


    -- ========================================================
    -- Requested amount
    -- ========================================================

    -- Amount requested by the employee/requester.
    requested_amount              NUMERIC(15, 2) NOT NULL,


    -- Currency of the requested amount.
    requested_currency_code       VARCHAR(3)        NOT NULL,


    -- ========================================================
    -- Approved amount
    -- ========================================================

    -- Amount approved by the authorized approval process.
    --
    -- This can be lower than requested_amount.
    approved_amount               NUMERIC(15, 2),


    -- Currency in which the advance is approved.
    approved_currency_code        VARCHAR(3),


    -- ========================================================
    -- Payment amount
    -- ========================================================

    -- Amount actually paid/released to the employee.
    --
    -- This should normally be populated from the Payroll/
    -- Finance/payment process.
    paid_amount                   NUMERIC(15, 2),


    -- Currency in which the payment was made.
    paid_currency_code            VARCHAR(3),


    -- ========================================================
    -- Lifecycle
    -- ========================================================

    -- Current lifecycle status.
    --
    -- DRAFT
    -- SUBMITTED
    -- UNDER_REVIEW
    -- APPROVED
    -- PARTIALLY_APPROVED
    -- REJECTED
    -- PAYMENT_PENDING
    -- PAID
    -- CANCELLED
    -- SETTLED
    status                        VARCHAR(30)    NOT NULL DEFAULT 'DRAFT',


    -- ========================================================
    -- Purpose / justification
    -- ========================================================

    -- Reason why the advance is required.
    --
    -- Example:
    --
    -- "Advance required for hotel, meals and local transport
    -- during Lahore factory visit."
    purpose                       TEXT           NOT NULL,


    -- Optional employee/requester remarks.
    remarks                       TEXT,


    -- ========================================================
    -- Approval information
    -- ========================================================

    -- Identifier of the approval request/process in the
    -- existing Approval Module.
    --
    -- Travel Service should not duplicate the complete approval
    -- workflow here.
    approval_request_id           BIGINT,


    -- Timestamp when the advance was approved.
    approved_at                   TIMESTAMP,


    -- User/employee who approved the advance.
    approved_by                   BIGINT,


    -- ========================================================
    -- Payment / Finance integration
    -- ========================================================

    -- Reference returned by Payroll/Finance/payment system.
    --
    -- Example:
    --
    -- PAY-2026-008921
    payment_reference             VARCHAR(100),


    -- External payment/finance transaction identifier.
    external_payment_id           VARCHAR(150),


    -- Timestamp when payment was actually released.
    paid_at                       TIMESTAMP,


    -- ========================================================
    -- Settlement tracking
    -- ========================================================

    -- Amount from this particular advance that has been
    -- consumed/settled against eligible travel expenses.
    settled_amount                NUMERIC(15, 2) NOT NULL DEFAULT 0,


    -- Amount returned by employee against this advance.
    --
    -- Example:
    --
    -- Advance = 35,000
    -- Expenses = 31,000
    -- Returned = 4,000
    returned_amount               NUMERIC(15, 2) NOT NULL DEFAULT 0,


    -- ========================================================
    -- Settlement currency
    -- ========================================================

    settlement_currency_code      VARCHAR(3)        NOT NULL,


    -- ========================================================
    -- Additional payment metadata
    -- ========================================================

    -- Payment channel used by Payroll/Finance.
    --
    -- Examples:
    --
    -- PAYROLL
    -- BANK_TRANSFER
    -- CASH
    -- OTHER
    payment_method_code           VARCHAR(30),


    -- Optional reference to the employee's bank/payment account
    -- record in the external financial system.
    --
    -- Do not store sensitive bank account details here.
    payment_account_reference     VARCHAR(150),


    -- ========================================================
    -- Reconciliation
    -- ========================================================

    -- Indicates that the advance payment has been reconciled
    -- with the payment/finance system.
    is_payment_reconciled         BOOLEAN        NOT NULL DEFAULT FALSE,


    -- Timestamp when payment reconciliation occurred.
    payment_reconciled_at         TIMESTAMP,


    -- User/system actor that performed the reconciliation.
    payment_reconciled_by         BIGINT,


    -- ========================================================
    -- Audit fields
    -- ========================================================

    created_at                    TIMESTAMP    NOT NULL DEFAULT now(),

    created_by                    VARCHAR(64)         NOT NULL,

    updated_at                    TIMESTAMP    NOT NULL DEFAULT now(),

    updated_by                    VARCHAR(64)         NOT NULL,
    ip_address                    INET,


    -- ========================================================
    -- Optimistic locking
    -- ========================================================

    version                       BIGINT         NOT NULL DEFAULT 0,


    -- ========================================================
    -- Foreign keys
    -- ========================================================

    CONSTRAINT fk_travel_request_advances_request
        FOREIGN KEY (travel_request_id)
            REFERENCES travel_requests (id)
            ON DELETE RESTRICT,


    CONSTRAINT fk_travel_request_advances_participant
        FOREIGN KEY (travel_request_participant_id)
            REFERENCES travel_request_participants (id)
            ON DELETE RESTRICT,


    -- ========================================================
    -- Amount constraints
    -- ========================================================

    CONSTRAINT ck_travel_request_advances_requested_amount
        CHECK (
            requested_amount > 0
            ),


    CONSTRAINT ck_travel_request_advances_approved_amount
        CHECK (
            approved_amount IS NULL
                OR approved_amount >= 0
            ),


    CONSTRAINT ck_travel_request_advances_paid_amount
        CHECK (
            paid_amount IS NULL
                OR paid_amount >= 0
            ),


    CONSTRAINT ck_travel_request_advances_settled_amount
        CHECK (
            settled_amount >= 0
            ),


    CONSTRAINT ck_travel_request_advances_returned_amount
        CHECK (
            returned_amount >= 0
            ),


    -- ========================================================
    -- Logical amount validation
    -- ========================================================

    -- Approved amount cannot exceed requested amount.
    CONSTRAINT ck_travel_request_advances_approved_not_over_requested
        CHECK (
            approved_amount IS NULL
                OR approved_amount <= requested_amount
            ),


    -- Paid amount cannot exceed approved amount.
    CONSTRAINT ck_travel_request_advances_paid_not_over_approved
        CHECK (
            paid_amount IS NULL
                OR approved_amount IS NULL
                OR paid_amount <= approved_amount
            ),


    -- Settled + returned cannot exceed paid amount.
    CONSTRAINT ck_travel_request_advances_settlement_not_over_paid
        CHECK (
            (
                paid_amount IS NULL
                    AND settled_amount = 0
                    AND returned_amount = 0
                )
                OR
            (
                paid_amount IS NOT NULL
                    AND settled_amount + returned_amount <= paid_amount
                )
            ),


    -- ========================================================
    -- Currency constraints
    -- ========================================================

    CONSTRAINT ck_travel_request_advances_requested_currency
        CHECK (
            BTRIM(requested_currency_code) <> ''
            ),


    CONSTRAINT ck_travel_request_advances_settlement_currency
        CHECK (
            BTRIM(settlement_currency_code) <> ''
            ),


    -- ========================================================
    -- Type/status constraints
    -- ========================================================

    CONSTRAINT ck_travel_request_advances_type
        CHECK (
            advance_type_code IN (
                                  'INITIAL',
                                  'ADDITIONAL',
                                  'EMERGENCY',
                                  'ADJUSTMENT'
                )
            ),


    CONSTRAINT ck_travel_request_advances_status
        CHECK (
            status IN (
                       'DRAFT',
                       'SUBMITTED',
                       'UNDER_REVIEW',
                       'APPROVED',
                       'PARTIALLY_APPROVED',
                       'REJECTED',
                       'PAYMENT_PENDING',
                       'PAID',
                       'CANCELED',
                       'SETTLED'
                )
            ),


    -- ========================================================
    -- Approval consistency
    -- ========================================================

    CONSTRAINT ck_travel_request_advances_approval
        CHECK (
            approved_at IS NULL
                OR approved_by IS NOT NULL
            ),


    -- ========================================================
    -- Payment consistency
    -- ========================================================

    CONSTRAINT ck_travel_request_advances_payment
        CHECK (
            paid_at IS NULL
                OR paid_amount IS NOT NULL
            ),


    -- ========================================================
    -- Reconciliation consistency
    -- ========================================================

    CONSTRAINT ck_travel_request_advances_reconciliation
        CHECK (
            is_payment_reconciled = FALSE
                OR payment_reconciled_at IS NOT NULL
            ),


    -- ========================================================
    -- Version
    -- ========================================================

    CONSTRAINT ck_travel_request_advances_version
        CHECK (
            version >= 0
            )
);


-- ============================================================
-- Unique advance number
-- ============================================================

CREATE UNIQUE INDEX uq_travel_request_advances_number
    ON travel_request_advances (
                                advance_number
        );


-- ============================================================
-- Indexes
-- ============================================================


-- Get all advances for a Travel Request.
CREATE INDEX idx_travel_request_advances_request
    ON travel_request_advances (
                                travel_request_id
        );


-- Get all advances for a participant.
CREATE INDEX idx_travel_request_advances_participant
    ON travel_request_advances (
                                travel_request_participant_id
        );


-- Find advances by status.
CREATE INDEX idx_travel_request_advances_status
    ON travel_request_advances (
                                status
        );


-- Find advances awaiting payment.
CREATE INDEX idx_travel_request_advances_payment_status
    ON travel_request_advances (
                                status,
                                paid_at
        );


-- Finance reconciliation.
CREATE INDEX idx_travel_request_advances_payment_reference
    ON travel_request_advances (
                                payment_reference
        );


-- External finance transaction lookup.
CREATE INDEX idx_travel_request_advances_external_payment
    ON travel_request_advances (
                                external_payment_id
        );


-- Approval lookup.
CREATE INDEX idx_travel_request_advances_approval
    ON travel_request_advances (
                                approval_request_id
        );


-- Settlement reporting.
CREATE INDEX idx_travel_request_advances_settlement
    ON travel_request_advances (
                                travel_request_id,
                                status
        );


-- Payment reconciliation queue.
CREATE INDEX idx_travel_request_advances_reconciliation
    ON travel_request_advances (
                                is_payment_reconciled,
                                paid_at
        );


