-- Pulls in the missing employee profile fields surfaced by the legacy
-- WebHRMS migration. Kept narrow: family names + religion + blood group
-- on the central row; disability is a 1:N side table backed by a small
-- catalog (PWD Act compliance — multiple impairments per employee).
--
-- Out of scope for this migration:
--   - bank account / payment method  -> payroll-service
--   - gratuity / senior-allowance start dates -> payroll-service
-- The legacy `cardno` (RFID/punch card) maps to the existing
-- `employees.employee_code` — there is no separate card_number column.

-- ---------------------------------------------------------------------
-- Family + identity fields on the central row.
-- ---------------------------------------------------------------------

alter table employees
    add column father_name  varchar(128),
    add column mother_name  varchar(128),
    add column spouse_name  varchar(128),
    add column religion     varchar(32),
    add column blood_group  varchar(8);

-- ---------------------------------------------------------------------
-- Disability catalog + per-employee link table. The catalog is a flat
-- list of impairment categories used for compliance reporting under the
-- Persons with Disabilities (Employment & Rehabilitation) ordinance.
-- The link row carries the specific description (legacy WebHRMS stored
-- 78 distinct descriptions like "Right Arm Polio" — those land in
-- `description` rather than as catalog entries).
-- ---------------------------------------------------------------------

create table disabilities (
    id          bigint generated by default as identity primary key,
    code        varchar(32)  not null unique,
    name        varchar(128) not null,
    active      boolean      not null default true,
    created_at  timestamptz  not null default now(),
    updated_at  timestamptz  not null default now(),
    created_by  varchar(64)  not null,
    updated_by  varchar(64)  not null,
    ip_address  inet
);

create table employee_disabilities (
    id              bigint generated by default as identity primary key,
    employee_id     bigint       not null references employees(id),
    disability_id   bigint       not null references disabilities(id),
    description     varchar(255),
    severity        varchar(16),
    document_key    varchar(512),
    created_at      timestamptz  not null default now(),
    updated_at      timestamptz  not null default now(),
    created_by      varchar(64)  not null,
    updated_by      varchar(64)  not null,
    ip_address      inet,
    constraint uq_employee_disability unique (employee_id, disability_id),
    constraint chk_disability_severity check (
        severity is null or severity in ('MILD','MODERATE','SEVERE')
    )
);

create index idx_emp_disability_employee on employee_disabilities (employee_id);

-- Seed the catalog. WHO ICF-aligned categories — broad enough to bucket
-- the legacy 78 specific descriptions, narrow enough for compliance
-- reporting. HR can soft-deactivate or add more.
insert into disabilities (code, name, created_by, updated_by) values
    ('PHYSICAL',      'Physical / orthopedic impairment', 'system', 'system'),
    ('VISUAL',        'Visual impairment',                'system', 'system'),
    ('HEARING',       'Hearing impairment',               'system', 'system'),
    ('SPEECH',        'Speech impairment',                'system', 'system'),
    ('INTELLECTUAL',  'Intellectual disability',          'system', 'system'),
    ('PSYCHOSOCIAL',  'Psychosocial / mental health',     'system', 'system'),
    ('MULTIPLE',      'Multiple disabilities',            'system', 'system'),
    ('OTHER',         'Other',                            'system', 'system');
