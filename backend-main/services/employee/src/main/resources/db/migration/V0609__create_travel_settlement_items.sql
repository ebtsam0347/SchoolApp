-- ============================================================
-- Travel Module
-- Table: travel_settlement_items
--
-- Purpose:
-- Stores the individual financial records included in a
-- Travel Request settlement.
--
-- A settlement can contain:
--
--   EXPENSE
--   ADVANCE
--   ADJUSTMENT
--
--
-- Example:
--
-- Settlement:
--   SET-2026-000125
--
-- Items:
--
--   EXPENSE   Hotel       18,000
--   EXPENSE   Lunch        3,000
--   EXPENSE   Dinner       4,500
--   ADVANCE   Advance    -35,000
--
-- Final:
--
--   25,500 - 35,000
--   = Employee Receivable 9,500
--
--
-- This table provides a permanent audit trail of exactly
-- which records were included in a settlement.
-- ============================================================


CREATE TABLE travel_settlement_items
(
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,


    -- ========================================================
    -- Settlement relationship
    -- ========================================================

    -- Settlement to which this item belongs.
    travel_settlement_id BIGINT         NOT NULL,


    -- ========================================================
    -- Source record
    -- ========================================================

    -- Type of financial record being included.
    --
    -- EXPENSE
    -- ADVANCE
    -- ADJUSTMENT
    source_type_code     VARCHAR(30)    NOT NULL,


    -- Primary key of the source record.
    --
    -- If source_type_code = EXPENSE:
    --   travel_expense_items.id
    --
    -- If source_type_code = ADVANCE:
    --   travel_request_advances.id
    --
    -- If source_type_code = ADJUSTMENT:
    --   approved adjustment reference.
    --
    -- This is intentionally not a normal FK because one column
    -- can reference multiple entity types.
    source_record_id     BIGINT         NOT NULL,


    -- ========================================================
    -- Financial values
    -- ========================================================

    -- Original/source amount.
    source_amount        NUMERIC(15, 2) NOT NULL,


    -- Amount actually included in this settlement.
    settlement_amount    NUMERIC(15, 2) NOT NULL,


    -- Currency of the settlement item.
    currency_code        VARCHAR(3)        NOT NULL,


    -- ========================================================
    -- Direction
    -- ========================================================

    -- Indicates how this item affects the final settlement.
    --
    -- PAYABLE:
    --   Adds amount payable to employee.
    --
    -- RECEIVABLE:
    --   Adds amount recoverable from employee.
    direction_code       VARCHAR(20)    NOT NULL,


    -- ========================================================
    -- Explanation
    -- ========================================================

    -- Optional snapshot/description explaining why this item
    -- was included.
    description          TEXT,


    -- ========================================================
    -- Audit
    -- ========================================================

    created_at           TIMESTAMP    NOT NULL DEFAULT now(),

    created_by           VARCHAR(64)  NOT NULL,

    updated_at           TIMESTAMP    NOT NULL DEFAULT now(),

    updated_by           VARCHAR(64)  NOT NULL,

    ip_address           INET,


    -- ========================================================
    -- Optimistic locking
    -- ========================================================

    version              BIGINT         NOT NULL DEFAULT 0,


    -- ========================================================
    -- Foreign key
    -- ========================================================

    CONSTRAINT fk_travel_settlement_items_settlement
        FOREIGN KEY (travel_settlement_id)
            REFERENCES travel_request_settlements (id)
            ON DELETE RESTRICT,


    -- ========================================================
    -- Amount constraints
    -- ========================================================

    CONSTRAINT ck_travel_settlement_items_source_amount
        CHECK (
            source_amount >= 0
            ),


    CONSTRAINT ck_travel_settlement_items_settlement_amount
        CHECK (
            settlement_amount >= 0
            ),


    CONSTRAINT ck_travel_settlement_items_settlement_not_over_source
        CHECK (
            settlement_amount <= source_amount
            ),


    -- ========================================================
    -- Type constraints
    -- ========================================================

    CONSTRAINT ck_travel_settlement_items_source_type
        CHECK (
            source_type_code IN (
                                 'EXPENSE',
                                 'ADVANCE',
                                 'ADJUSTMENT'
                )
            ),


    CONSTRAINT ck_travel_settlement_items_direction
        CHECK (
            direction_code IN (
                               'PAYABLE',
                               'RECEIVABLE'
                )
            ),


    -- ========================================================
    -- Currency
    -- ========================================================

    CONSTRAINT ck_travel_settlement_items_currency
        CHECK (
            BTRIM(currency_code) <> ''
            ),


    -- ========================================================
    -- Version
    -- ========================================================

    CONSTRAINT ck_travel_settlement_items_version
        CHECK (
            version >= 0
            )
);


-- ============================================================
-- Indexes
-- ============================================================


-- All items belonging to a settlement.
CREATE INDEX idx_travel_settlement_items_settlement
    ON travel_settlement_items (
                                travel_settlement_id
        );


-- Find items by source type.
CREATE INDEX idx_travel_settlement_items_source_type
    ON travel_settlement_items (
                                source_type_code
        );


-- Find a particular source record.
CREATE INDEX idx_travel_settlement_items_source
    ON travel_settlement_items (
                                source_type_code,
                                source_record_id
        );


-- Useful for settlement calculation/reporting.
CREATE INDEX idx_travel_settlement_items_direction
    ON travel_settlement_items (
                                direction_code
        );


-- ============================================================
-- Documentation
-- ============================================================


COMMENT
ON TABLE travel_settlement_items IS
    'Stores the individual expenses, advances and approved adjustments included in a Travel Request settlement, providing a permanent audit trail of the records used to calculate the final settlement.';


COMMENT
ON COLUMN travel_settlement_items.id IS
    'Internal primary key of the settlement item.';


COMMENT
ON COLUMN travel_settlement_items.travel_settlement_id IS
    'Reference to the settlement containing this financial item.';


COMMENT
ON COLUMN travel_settlement_items.source_type_code IS
    'Identifies whether the source record is an EXPENSE, ADVANCE or approved ADJUSTMENT.';


COMMENT
ON COLUMN travel_settlement_items.source_record_id IS
    'Identifier of the source record included in the settlement. The referenced table depends on source_type_code.';


COMMENT
ON COLUMN travel_settlement_items.source_amount IS
    'Original amount of the source financial record at the time it was included in the settlement.';


COMMENT
ON COLUMN travel_settlement_items.settlement_amount IS
    'Amount of the source record actually included in this settlement.';


COMMENT
ON COLUMN travel_settlement_items.currency_code IS
    'Currency of the settlement item.';


COMMENT
ON COLUMN travel_settlement_items.direction_code IS
    'Indicates whether the item contributes to an amount payable to the employee or recoverable from the employee.';


COMMENT
ON COLUMN travel_settlement_items.description IS
    'Description or snapshot explaining why this financial record was included in the settlement.';


COMMENT
ON COLUMN travel_settlement_items.created_at IS
    'Timestamp when the settlement item was created.';


COMMENT
ON COLUMN travel_settlement_items.created_by IS
    'Employee/user identifier that created the settlement item.';


COMMENT
ON COLUMN travel_settlement_items.updated_at IS
    'Timestamp when the settlement item was last updated.';


COMMENT
ON COLUMN travel_settlement_items.updated_by IS
    'Employee/user identifier that last updated the settlement item.';


COMMENT
ON COLUMN travel_settlement_items.ip_address IS
    'IP address of the client that last modified the settlement item.';


COMMENT
ON COLUMN travel_settlement_items.version IS
    'Optimistic-locking version used to prevent concurrent updates from overwriting each other.';