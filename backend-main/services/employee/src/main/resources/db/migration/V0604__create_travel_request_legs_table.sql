-- ============================================================
-- Travel Module
-- Table: travel_request_legs
--
-- Purpose:
-- Stores individual journey segments belonging to a Travel
-- Request.
--
-- One Travel Request may contain one or multiple legs.
--
-- Example:
--
-- Travel Request:
--   TR-2026-000125
--
-- Leg 1:
--   Sialkot -> Lahore
--
-- Leg 2:
--   Lahore -> Faisalabad
--
-- Leg 3:
--   Faisalabad -> Lahore
--
-- Leg 4:
--   Lahore -> Sialkot
--
--
-- This table replaces the old single-value fields:
--
--   City
--   Origin
--   Destination
--   Vehicle Source
--   Transportation Type
--   Vehicle Number
--   Total Distance
--
-- Those values are route/leg information and therefore belong
-- to this table rather than the root travel_requests table.
-- ============================================================


CREATE TABLE travel_request_legs
(
    id                                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,


    -- ========================================================
    -- Travel Request relationship
    -- ========================================================

    -- Travel Request to which this journey leg belongs.
    travel_request_id                  BIGINT       NOT NULL,


    -- Sequential order of this leg within the Travel Request.
    --
    -- Example:
    --
    -- 1 = Sialkot -> Lahore
    -- 2 = Lahore -> Faisalabad
    -- 3 = Faisalabad -> Lahore
    -- 4 = Lahore -> Sialkot
    --
    -- This allows the complete journey to be reconstructed in
    -- the correct order.
    leg_sequence                       INTEGER      NOT NULL,


    -- ========================================================
    -- Location information
    -- ========================================================

    -- Origin location/city code.
    --
    -- Example:
    --   SIALKOT
    --   LAHORE
    --   FAISALABAD
    --
    -- This is a business/location code, not a local database FK.
    origin_location_code               VARCHAR(100) NOT NULL,

    -- Human-readable origin name captured for historical
    -- reporting.
    --
    -- Example:
    --   Sialkot Factory
    origin_location_name_snapshot      VARCHAR(200) NOT NULL,


    -- Destination location/city code.
    destination_location_code          VARCHAR(100) NOT NULL,

    -- Human-readable destination captured for historical
    -- reporting.
    --
    -- Example:
    --   Lahore Factory
    destination_location_name_snapshot VARCHAR(200) NOT NULL,


    -- ========================================================
    -- Journey timing
    -- ========================================================

    -- Planned departure date/time for this specific leg.
    planned_departure_at               TIMESTAMP  NOT NULL,

    -- Planned arrival date/time for this specific leg.
    planned_arrival_at                 TIMESTAMP,


    -- Actual departure date/time.
    --
    -- NULL before the journey starts.
    actual_departure_at                TIMESTAMP,

    -- Actual arrival date/time.
    --
    -- NULL before the journey completes.
    actual_arrival_at                  TIMESTAMP,


    -- ========================================================
    -- Transportation
    -- ========================================================

    -- Business code identifying how this leg will be traveled.
    --
    -- Examples:
    --   COMPANY_VEHICLE
    --   PERSONAL_VEHICLE
    --   HIRED_VEHICLE
    --   PUBLIC_TRANSPORT
    --   AIR
    --   TRAIN
    --
    -- The exact list should be managed consistently with the
    -- Travel/Master Data configuration.
    transportation_type_code           VARCHAR(50)  NOT NULL,


    -- Business code describing who/what provides the vehicle.
    --
    -- Examples:
    --   COMPANY
    --   EMPLOYEE
    --   RENTAL
    --   PUBLIC
    --   OTHER
    --
    -- This is separate from transportation_type because:
    --
    -- Transportation:
    --   ROAD
    --
    -- Vehicle Source:
    --   COMPANY
    --
    -- can both be true at the same time.
    vehicle_source_code                VARCHAR(50),


    -- Vehicle number/registration number when applicable.
    --
    -- Example:
    --   LEB-1234
    --
    -- NULL for air/train/public transport where a vehicle
    -- registration number does not apply.
    vehicle_number                     VARCHAR(100),


    -- Optional vehicle/transport descriptive information.
    --
    -- Example:
    --   Toyota Corolla
    --   Company Coaster
    --   PIA Flight
    --   Train 16DN
    vehicle_description                VARCHAR(250),


    -- ========================================================
    -- Distance
    -- ========================================================

    -- Planned distance for this journey leg in kilometres.
    planned_distance_km                NUMERIC(12, 2),

    -- Actual distance traveled in kilometres.
    --
    -- Useful when the actual route differs from the planned
    -- route.
    actual_distance_km                 NUMERIC(12, 2),


    -- ========================================================
    -- Journey status
    -- ========================================================

    -- Status of this particular journey leg.
    --
    -- PLANNED
    -- IN_PROGRESS
    -- COMPLETED
    -- CANCELLED
    leg_status                         VARCHAR(20)  NOT NULL DEFAULT 'PLANNED',


    -- ========================================================
    -- Additional information
    -- ========================================================

    -- Optional reason/instruction for this particular leg.
    --
    -- Example:
    --   Pickup from Lahore office at 07:00 AM.
    remarks                            TEXT,


    -- ========================================================
    -- Audit fields
    -- ========================================================

    created_at                         TIMESTAMP  NOT NULL DEFAULT now(),

    created_by                         VARCHAR(64)       NOT NULL,

    updated_at                         TIMESTAMP  NOT NULL DEFAULT now(),

    updated_by                         VARCHAR(64)       NOT NULL,
    ip_address                         INET,


    -- ========================================================
    -- Optimistic locking
    -- ========================================================

    version                            BIGINT       NOT NULL DEFAULT 0,


    -- ========================================================
    -- Constraints
    -- ========================================================

    CONSTRAINT fk_travel_request_legs_request
        FOREIGN KEY (travel_request_id)
            REFERENCES travel_requests (id)
            ON DELETE RESTRICT,


    -- Every leg must have a unique sequence within a request.
    CONSTRAINT uq_travel_request_legs_sequence
        UNIQUE (
                travel_request_id,
                leg_sequence
            ),


    CONSTRAINT ck_travel_request_legs_sequence
        CHECK (
            leg_sequence > 0
            ),


    CONSTRAINT ck_travel_request_legs_origin_code
        CHECK (
            BTRIM(origin_location_code) <> ''
            ),


    CONSTRAINT ck_travel_request_legs_origin_name
        CHECK (
            BTRIM(origin_location_name_snapshot) <> ''
            ),


    CONSTRAINT ck_travel_request_legs_destination_code
        CHECK (
            BTRIM(destination_location_code) <> ''
            ),


    CONSTRAINT ck_travel_request_legs_destination_name
        CHECK (
            BTRIM(destination_location_name_snapshot) <> ''
            ),


    -- A journey leg cannot arrive before it departs.
    CONSTRAINT ck_travel_request_legs_planned_datetime
        CHECK (
            planned_arrival_at IS NULL
                OR planned_arrival_at >= planned_departure_at
            ),


    -- Actual arrival cannot occur before actual departure.
    CONSTRAINT ck_travel_request_legs_actual_datetime
        CHECK (
            actual_departure_at IS NULL
                OR actual_arrival_at IS NULL
                OR actual_arrival_at >= actual_departure_at
            ),


    CONSTRAINT ck_travel_request_legs_transportation
        CHECK (
            BTRIM(transportation_type_code) <> ''
            ),


    -- Distance cannot be negative.
    CONSTRAINT ck_travel_request_legs_planned_distance
        CHECK (
            planned_distance_km IS NULL
                OR planned_distance_km >= 0
            ),


    CONSTRAINT ck_travel_request_legs_actual_distance
        CHECK (
            actual_distance_km IS NULL
                OR actual_distance_km >= 0
            ),


    CONSTRAINT ck_travel_request_legs_status
        CHECK (
            leg_status IN (
                           'PLANNED',
                           'IN_PROGRESS',
                           'COMPLETED',
                           'CANCELLED'
                )
            ),


    CONSTRAINT ck_travel_request_legs_version
        CHECK (
            version >= 0
            )
);


-- ============================================================
-- Indexes
-- ============================================================


-- Main lookup:
-- Get all journey legs belonging to a Travel Request.
CREATE INDEX idx_travel_request_legs_request
    ON travel_request_legs (
                            travel_request_id
        );


-- Frequently needed together when reconstructing the route.
CREATE INDEX idx_travel_request_legs_request_sequence
    ON travel_request_legs (
                            travel_request_id,
                            leg_sequence
        );


-- Useful for operational queries involving journey status.
CREATE INDEX idx_travel_request_legs_status
    ON travel_request_legs (
                            leg_status
        );


-- Useful for date/time based travel reports.
CREATE INDEX idx_travel_request_legs_departure
    ON travel_request_legs (
                            planned_departure_at
        );


-- Useful for destination-based reports.
CREATE INDEX idx_travel_request_legs_destination
    ON travel_request_legs (
                            destination_location_code
        );


-- Useful for vehicle tracking/reporting.
CREATE INDEX idx_travel_request_legs_vehicle
    ON travel_request_legs (
                            vehicle_number
        );


