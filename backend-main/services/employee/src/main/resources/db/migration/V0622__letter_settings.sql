-- ---------------------------------------------------------------------
-- Letter settings + clause templates for HR letters (appointment, service,
-- experience). HR owns the wording: the appointment paragraph and the
-- signature titles are rows in letter_clauses, not Java code.
--
-- letter_settings holds exactly one row (company letterhead, default
-- signatory for service/experience letters, default probation). HR edits it
-- directly until an admin endpoint exists.
--
-- letter_clauses.section:
--   OPENING    paragraph printed under the title bar. body may use
--              {placeholders} (AppointmentLetterService lists them); unknown
--              ones print verbatim so a typo shows in the preview.
--   SIGNATORY  one signature column, left to right by seq (max 3):
--              title = first line, body = second line ('' for none).
-- ---------------------------------------------------------------------

create table letter_settings (
    id                       bigint generated by default as identity primary key,
    company_legal_name       varchar(160) not null,
    company_address          varchar(300) not null,
    company_phone            varchar(64),
    company_email            varchar(128),
    logo_object_key          varchar(300),
    ref_prefix               varchar(32)  not null,
    signatory_name           varchar(128) not null,
    signatory_designation    varchar(128) not null,
    default_probation_months int          not null check (default_probation_months between 0 and 24),
    created_at               timestamp    not null default now(),
    updated_at               timestamp    not null default now(),
    created_by               varchar(64)  not null,
    updated_by               varchar(64)  not null,
    ip_address               inet
);

create table letter_clauses (
    id            bigint generated by default as identity primary key,
    letter_type   varchar(32)  not null check (letter_type in ('APPOINTMENT')),
    section       varchar(16)  not null check (section in ('OPENING', 'SIGNATORY')),
    seq           int          not null,
    title         varchar(128),
    body          text         not null,
    active        boolean      not null default true,
    created_at    timestamp    not null default now(),
    updated_at    timestamp    not null default now(),
    created_by    varchar(64)  not null,
    updated_by    varchar(64)  not null,
    ip_address    inet,
    constraint uq_letter_clauses_type_section_seq unique (letter_type, section, seq)
);

