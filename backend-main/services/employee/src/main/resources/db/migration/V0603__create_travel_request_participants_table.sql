-- ============================================================
-- Travel Module
-- Table: travel_request_participants
--
-- Purpose:
-- Stores all employees who are associated with a particular
-- Travel Request.
--
-- One Travel Request can contain multiple participants.
--
-- Example:
--
-- TR-2026-000125
--
--   Farhan Ali   -> REQUESTER
--   Ahmed Khan   -> PARTICIPANT
--   Usman Ali    -> PARTICIPANT
--
-- The employee information is obtained from the Employee
-- Service when the participant is added.
--
-- Important:
-- Current employee/master-data information remains owned by
-- the Employee Service.
--
-- Snapshot fields are intentionally stored here because the
-- Travel Request is a historical business transaction.
--
-- Example:
--
-- Employee currently:
--   Grade: E-4
--   Designation: Manager
--
-- At the time of travel:
--   Grade: E-3
--   Designation: Assistant Manager
--
-- The Travel Request must preserve what was applicable when
-- the request was created/submitted.
--
-- This table therefore stores both:
--
--   employee_id
--       -> current Employee Service identity
--
-- and
--
--   *_snapshot
--       -> historical transaction information
-- ============================================================


CREATE TABLE travel_request_participants
(
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,


    -- ========================================================
    -- Travel Request relationship
    -- ========================================================

    -- Travel Request to which this participant belongs.
    travel_request_id         BIGINT       NOT NULL,


    -- ========================================================
    -- Employee identity
    -- ========================================================

    -- Employee identifier from Employee Service.
    --
    -- This is intentionally NOT a database foreign key because
    -- employee information is owned by the Employee domain.
    employee_id               BIGINT       NOT NULL,

    -- Employee/card number captured at the time the participant
    -- was added to the Travel Request.
    --
    -- Example:
    --   100245
    employee_no_snapshot      VARCHAR(50)  NOT NULL,

    -- Employee name captured at the time of the request.
    employee_name_snapshot    VARCHAR(200) NOT NULL,


    -- ========================================================
    -- Participant role
    -- ========================================================

    -- Defines the person's role in the Travel Request.
    --
    -- REQUESTER:
    --   Employee who created/initiated the Travel Request.
    --
    -- PARTICIPANT:
    --   Other employee traveling as part of the request.
    --
    -- This allows the requester to travel himself while also
    -- adding other employees.
    participant_role          VARCHAR(20)  NOT NULL,


    -- ========================================================
    -- Employee organization snapshots
    -- ========================================================

    -- Employee grade identifier at the time of the request.
    grade_id_snapshot         BIGINT,

    -- Employee grade business code.
    --
    -- Example:
    --   E-4
    grade_code_snapshot       VARCHAR(50),

    -- Human-readable grade name.
    --
    -- Example:
    --   Manager
    grade_name_snapshot       VARCHAR(150),


    -- Designation identifier at the time of the request.
    designation_id_snapshot   BIGINT,

    -- Human-readable designation.
    designation_name_snapshot VARCHAR(200),


    -- Department identifier at the time of the request.
    department_id_snapshot    BIGINT,

    -- Department name at the time of the request.
    department_name_snapshot  VARCHAR(200),


    -- Section identifier at the time of the request.
    section_id_snapshot       BIGINT,

    -- Section name at the time of the request.
    section_name_snapshot     VARCHAR(200),


    -- ========================================================
    -- Participant travel information
    -- ========================================================

    -- Indicates whether this employee is actually expected to
    -- travel on this request.
    --
    -- Normally TRUE.
    --
    -- Keeping this separate from record deletion allows the
    -- system to preserve the participant history.
    is_travelling             BOOLEAN      NOT NULL DEFAULT TRUE,


    -- Optional reason if the employee is removed from the trip
    -- after being added.
    removal_reason            TEXT,


    -- Timestamp when the employee was removed from the trip.
    removed_at                TIMESTAMP,


    -- User/employee who removed the participant.
    removed_by                BIGINT,


    -- ========================================================
    -- Financial participation
    -- ========================================================

    -- Whether this participant is eligible for travel
    -- entitlements under the applicable policy.
    --
    -- This is useful because not every person associated with
    -- a request necessarily has the same financial treatment.
    entitlement_eligible      BOOLEAN      NOT NULL DEFAULT TRUE,


    -- ========================================================
    -- Audit fields
    -- ========================================================

    created_at                TIMESTAMP  NOT NULL DEFAULT now(),

    created_by                VARCHAR(64)       NOT NULL,

    updated_at                TIMESTAMP  NOT NULL DEFAULT now(),

    updated_by                VARCHAR(64)       NOT NULL,
    ip_address                INET,


    -- ========================================================
    -- Optimistic locking
    -- ========================================================

    -- Technical version used by JPA/Hibernate optimistic locking.
    version                   BIGINT       NOT NULL DEFAULT 0,


    -- ========================================================
    -- Constraints
    -- ========================================================

    CONSTRAINT fk_travel_request_participants_request
        FOREIGN KEY (travel_request_id)
            REFERENCES travel_requests (id)
            ON DELETE RESTRICT,


    -- The same employee cannot be added twice to the same
    -- Travel Request.
    --
    -- Example of invalid data:
    --
    -- TR-100
    --   Employee 158 -> REQUESTER
    --   Employee 158 -> PARTICIPANT
    --
    -- An employee should have only one participant record.
    CONSTRAINT uq_travel_request_participants_employee
        UNIQUE (
                travel_request_id,
                employee_id
            ),


    CONSTRAINT ck_travel_request_participants_employee_no
        CHECK (
            BTRIM(employee_no_snapshot) <> ''
            ),


    CONSTRAINT ck_travel_request_participants_employee_name
        CHECK (
            BTRIM(employee_name_snapshot) <> ''
            ),


    CONSTRAINT ck_travel_request_participants_role
        CHECK (
            participant_role IN (
                                 'REQUESTER',
                                 'PARTICIPANT'
                )
            ),


    -- Removed participants must have a removal timestamp and
    -- vice versa.
    CONSTRAINT ck_travel_request_participants_removal
        CHECK (
            (
                removed_at IS NULL
                    AND removal_reason IS NULL
                )
                OR
            (
                removed_at IS NOT NULL
                )
            ),


    CONSTRAINT ck_travel_request_participants_version
        CHECK (
            version >= 0
            )
);


-- ============================================================
-- Indexes
-- ============================================================


-- Main relationship lookup:
-- Find all employees participating in a Travel Request.
CREATE INDEX idx_travel_request_participants_request
    ON travel_request_participants (
                                    travel_request_id
        );


-- Find all Travel Requests in which an employee participated.
--
-- Useful for:
--   Employee travel history
--   HR reports
--   Travel history
--   Expense history
CREATE INDEX idx_travel_request_participants_employee
    ON travel_request_participants (
                                    employee_id
        );


-- Useful when retrieving only active/traveling participants.
CREATE INDEX idx_travel_request_participants_active
    ON travel_request_participants (
                                    travel_request_id,
                                    is_travelling
        );


-- Useful for role-based lookups.
CREATE INDEX idx_travel_request_participants_role
    ON travel_request_participants (
                                    travel_request_id,
                                    participant_role
        );


-- Useful for grade-based reporting.
CREATE INDEX idx_travel_request_participants_grade
    ON travel_request_participants (
                                    grade_id_snapshot
        );


