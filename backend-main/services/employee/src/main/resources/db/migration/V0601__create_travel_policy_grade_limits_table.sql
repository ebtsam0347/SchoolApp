-- ============================================================
-- Travel Module
-- Table: travel_policy_grade_limits
--
-- Purpose:
-- Stores grade-specific travel entitlement limits for each
-- version of a company travel policy.
--
-- A policy version defines the overall policy period/rules,
-- while this table defines what a particular employee grade
-- is entitled to for a particular expense/benefit type.
--
-- Example:
--
-- Policy:
--   FACTORY_TRAVEL / Version 2
--
-- Grade E-4:
--   ACCOMMODATION -> 10000 PKR per night
--   BREAKFAST     ->   800 PKR per day
--   LUNCH         ->  1200 PKR per day
--   DINNER        ->  1500 PKR per day
--
-- This design intentionally avoids columns such as:
--   accommodation_limit
--   breakfast_limit
--   lunch_limit
--   dinner_limit
--
-- because new expense/entitlement types can be introduced
-- without changing the database schema.
-- ============================================================


CREATE TABLE travel_policy_grade_limits
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- --------------------------------------------------------
    -- Policy relationship
    -- --------------------------------------------------------

    -- The policy version to which this entitlement belongs.
    policy_version_id BIGINT         NOT NULL,

    -- --------------------------------------------------------
    -- Grade information
    -- --------------------------------------------------------

    -- Reference/identifier of the employee grade in the
    -- Employee/Master Data domain.
    --
    -- This is intentionally not a database foreign key if the
    -- grade is owned by another service/database.
    grade_id          BIGINT         NOT NULL,

    -- Grade code is stored as a snapshot/business identifier.
    -- Example: E-4
    grade_code        VARCHAR(50)    NOT NULL,

    -- Human-readable grade name.
    -- Example: Executive Manager
    --
    -- Keeping the name here helps preserve the policy definition
    -- as it was configured and avoids depending on a future
    -- renamed grade for historical reporting.
    grade_name        VARCHAR(150),

    -- --------------------------------------------------------
    -- Entitlement type
    -- --------------------------------------------------------

    -- Business code representing the entitlement/expense type.
    --
    -- Examples:
    --   ACCOMMODATION
    --   BREAKFAST
    --   LUNCH
    --   DINNER
    --   MEAL_TOTAL
    --   TA_TD
    --   FUEL
    --   TOLL
    --
    -- These codes should be managed consistently with the
    -- Master Data / Travel configuration used by the system.
    expense_type_code VARCHAR(50)    NOT NULL,

    -- Determines how the limit is applied.
    --
    -- PER_DAY
    -- PER_NIGHT
    -- PER_TRIP
    -- PER_CLAIM
    -- PER_KM
    -- FIXED
    --
    -- The exact calculation behavior is implemented in the
    -- Travel business logic, not in the database.
    limit_type        VARCHAR(30)    NOT NULL,

    -- --------------------------------------------------------
    -- Financial limit
    -- --------------------------------------------------------

    -- Maximum amount allowed for this grade and entitlement type.
    limit_amount      NUMERIC(15, 2) NOT NULL,

    -- Currency in which the limit is defined.
    -- Example: PKR
    currency_code     VARCHAR(3)        NOT NULL,

    -- --------------------------------------------------------
    -- Configuration
    -- --------------------------------------------------------

    -- Whether this entitlement rule is currently usable within
    -- this policy version.
    is_active         BOOLEAN        NOT NULL DEFAULT TRUE,

    -- Optional administrative explanation.
    remarks           TEXT,

    -- --------------------------------------------------------
    -- Audit fields
    -- --------------------------------------------------------

    created_at        TIMESTAMP    NOT NULL DEFAULT now(),
    created_by        VARCHAR(64)         NOT NULL,

    updated_at        TIMESTAMP    NOT NULL DEFAULT now(),
    updated_by        VARCHAR(64)         NOT NULL,
    ip_address        INET,

    -- Optimistic locking version.
    --
    -- This is a technical version of the database record.
    -- It is different from travel_policy_versions.version_no,
    -- which is the business version of the policy itself.
    version           BIGINT         NOT NULL DEFAULT 0,


    -- ========================================================
    -- Constraints
    -- ========================================================

    CONSTRAINT fk_travel_policy_grade_limits_policy_version
        FOREIGN KEY (policy_version_id)
            REFERENCES travel_policy_versions (id),

    -- A policy version should contain only one active definition
    -- for a particular grade and expense type.
    --
    -- This prevents:
    --
    -- E-4 + DINNER = 1500
    -- E-4 + DINNER = 2000
    --
    -- from accidentally existing in the same policy version.
    CONSTRAINT uq_travel_policy_grade_limits_rule
        UNIQUE (
                policy_version_id,
                grade_id,
                expense_type_code
            ),

    CONSTRAINT ck_travel_policy_grade_limits_grade_code
        CHECK (BTRIM(grade_code) <> ''),

    CONSTRAINT ck_travel_policy_grade_limits_expense_type
        CHECK (BTRIM(expense_type_code) <> ''),

    CONSTRAINT ck_travel_policy_grade_limits_limit_type
        CHECK (
            limit_type IN (
                           'PER_DAY',
                           'PER_NIGHT',
                           'PER_TRIP',
                           'PER_CLAIM',
                           'PER_KM',
                           'FIXED'
                )
            ),

    CONSTRAINT ck_travel_policy_grade_limits_limit_amount
        CHECK (limit_amount >= 0),

    CONSTRAINT ck_travel_policy_grade_limits_currency
        CHECK (
            BTRIM(currency_code) <> ''
            ),

    CONSTRAINT ck_travel_policy_grade_limits_version
        CHECK (version >= 0)
);


-- ============================================================
-- Indexes
-- ============================================================

-- Primary lookup:
-- Find all entitlement rules for a particular policy version.
CREATE INDEX idx_travel_policy_grade_limits_policy_version
    ON travel_policy_grade_limits (policy_version_id);


-- Find all rules for a particular grade under a policy.
CREATE INDEX idx_travel_policy_grade_limits_grade
    ON travel_policy_grade_limits (
                                   grade_id,
                                   policy_version_id
        );


-- Find a particular entitlement type within a policy.
CREATE INDEX idx_travel_policy_grade_limits_expense_type
    ON travel_policy_grade_limits (
                                   policy_version_id,
                                   expense_type_code
        );


-- Useful when retrieving only active entitlement rules.
CREATE INDEX idx_travel_policy_grade_limits_active
    ON travel_policy_grade_limits (
                                   policy_version_id,
                                   grade_id,
                                   is_active
        );


