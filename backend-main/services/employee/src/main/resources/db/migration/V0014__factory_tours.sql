create table factory_tours (
    id                      bigint generated by default as identity primary key,
    type                    varchar(16)  not null,
    status                  varchar(20)  not null default 'DRAFT',
    tour_date               date         not null,
    visitor_organization    varchar(128) not null,
    visitor_count           int          not null default 1,
    purpose                 text         not null,
    contact_person          varchar(128),
    contact_email           varchar(128),
    department_id           bigint,
    notes                   text,
    requested_by_user_id    bigint,
    approved_by_user_id     bigint,
    approved_at             timestamp,
    reject_reason           text,
    created_at              timestamp    not null default now(),
    updated_at              timestamp    not null default now(),
    created_by              varchar(64)  not null,
    updated_by              varchar(64)  not null,
    ip_address              inet
);

create index idx_factory_tours_status on factory_tours (status);
create index idx_factory_tours_date   on factory_tours (tour_date);
create index idx_factory_tours_type   on factory_tours (type);

