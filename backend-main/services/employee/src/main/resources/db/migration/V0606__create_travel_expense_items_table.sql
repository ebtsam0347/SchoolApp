-- ============================================================
-- Travel Module
-- Table: travel_expense_items
--
-- Purpose:
-- Stores individual actual expenses/claims incurred during
-- a Travel Request.
--
-- This table replaces the old "details" table.
--
-- One Travel Request can contain many expense items.
--
-- Example:
--
-- TR-2026-000125
--
--   Farhan
--      Hotel       9,000
--      Breakfast     700
--      Lunch       1,100
--      Dinner      1,400
--      Toll          500
--
-- Each expense is independently traceable to:
--
--   Travel Request
--   Participant
--   Expense Category
--   Applicable Entitlement
--   Policy Version
--
-- Important:
--
-- This table stores ACTUAL EXPENSES.
--
-- Entitlement table stores what was ALLOWED.
--
-- Therefore:
--
-- travel_request_entitlements
--          =
--       allowed
--
-- travel_expense_items
--          =
--       actual
--
-- The reimbursement/payable amount is calculated by the
-- business/service layer and must never blindly trust the
-- amount submitted by the frontend.
-- ============================================================


CREATE TABLE travel_expense_items
(
    id                            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,


    -- ========================================================
    -- Travel Request relationship
    -- ========================================================

    -- Travel Request under which this expense was incurred.
    travel_request_id             BIGINT         NOT NULL,

    -- Employee participant who incurred/claimed this expense.
    travel_request_participant_id BIGINT         NOT NULL,


    -- ========================================================
    -- Entitlement relationship
    -- ========================================================

    -- Applicable entitlement for this expense.
    --
    -- Example:
    --
    -- Dinner expense
    --      ↓
    -- DINNER entitlement
    --
    -- Accommodation expense
    --      ↓
    -- ACCOMMODATION entitlement
    --
    -- NULL is allowed for legitimate expenses that are not
    -- governed by a specific entitlement category, such as
    -- certain approved transportation/toll expenses.
    travel_request_entitlement_id BIGINT,


    -- ========================================================
    -- Expense classification
    -- ========================================================

    -- High-level business category.
    --
    -- Examples:
    --
    -- ACCOMMODATION
    -- MEAL
    -- TRANSPORTATION
    -- TOLL
    -- PARKING
    -- OTHER
    --
    -- This should use a stable business code.
    expense_category_code         VARCHAR(50)    NOT NULL,


    -- More specific expense type.
    --
    -- Examples:
    --
    -- HOTEL
    -- BREAKFAST
    -- LUNCH
    -- DINNER
    -- TAXI
    -- FUEL
    -- TOLL
    -- PARKING
    -- TRAIN_TICKET
    -- AIR_TICKET
    -- OTHER
    expense_subcategory_code      VARCHAR(50),


    -- Human-readable description supplied by the employee.
    --
    -- Example:
    --
    -- "Dinner at Lahore during factory visit"
    description                   TEXT,


    -- ========================================================
    -- Expense date
    -- ========================================================

    -- Date/time when the expense actually occurred.
    expense_at                    TIMESTAMP    NOT NULL,


    -- ========================================================
    -- Amount
    -- ========================================================

    -- Actual amount paid/incurred by the employee.
    claimed_amount                NUMERIC(15, 2) NOT NULL,


    -- Currency in which the expense was incurred.
    claimed_currency_code         VARCHAR(3)        NOT NULL,


    -- ========================================================
    -- Policy / entitlement evaluation
    -- ========================================================

    -- Maximum amount considered reimbursable by the system.
    --
    -- This is calculated by the backend from the applicable
    -- entitlement/policy.
    --
    -- Example:
    --
    -- Actual dinner = 1,800
    -- Allowed       = 1,500
    --
    -- reimbursable_amount = 1,500
    eligible_amount               NUMERIC(15, 2),


    -- Amount that exceeds the applicable entitlement or is
    -- otherwise non-reimbursable.
    --
    -- Example:
    --
    -- Claimed      = 1,800
    -- Eligible     = 1,500
    -- Non-eligible =   300
    non_reimbursable_amount       NUMERIC(15, 2),


    -- Amount finally approved for reimbursement.
    --
    -- This may differ from eligible_amount if an authorized
    -- reviewer rejects/adjusts part of the claim.
    approved_amount               NUMERIC(15, 2),


    -- Currency used for the eligible/approved amounts.
    --
    -- Normally equal to claimed_currency_code unless currency
    -- conversion is supported.
    settlement_currency_code      VARCHAR(3)        NOT NULL,


    -- ========================================================
    -- Foreign currency support
    -- ========================================================

    -- Exchange rate used when the claimed currency differs from
    -- the settlement currency.
    --
    -- Example:
    --
    -- Claimed = USD
    -- Settlement = PKR
    -- Exchange rate = 280
    exchange_rate                 NUMERIC(19, 8),


    -- Converted amount in settlement currency.
    converted_claimed_amount      NUMERIC(15, 2),


    -- ========================================================
    -- Receipt / supporting evidence
    -- ========================================================

    -- Indicates whether supporting evidence/receipt is required.
    receipt_required              BOOLEAN        NOT NULL DEFAULT TRUE,


    -- Indicates whether the required receipt/evidence has been
    -- supplied.
    receipt_attached              BOOLEAN        NOT NULL DEFAULT FALSE,


    -- External document/file identifier.
    --
    -- This should reference your file/document storage system
    -- rather than storing the physical file inside this table.
    receipt_document_id           VARCHAR(200),


    -- Receipt/invoice/reference number printed on the document.
    receipt_reference             VARCHAR(100),


    -- ========================================================
    -- Expense lifecycle
    -- ========================================================

    -- Expense processing status.
    --
    -- DRAFT
    -- SUBMITTED
    -- UNDER_REVIEW
    -- APPROVED
    -- PARTIALLY_APPROVED
    -- REJECTED
    -- PAID
    -- CANCELLED
    status                        VARCHAR(30)    NOT NULL DEFAULT 'DRAFT',


    -- Optional reason when the expense is rejected.
    rejection_reason              TEXT,


    -- ========================================================
    -- Verification
    -- ========================================================

    -- User/employee who verified/reviewed the expense.
    reviewed_by                   BIGINT,

    -- Timestamp of review.
    reviewed_at                   TIMESTAMP,


    -- ========================================================
    -- Payment information
    -- ========================================================

    -- Timestamp when this expense was included in a payment or
    -- settlement.
    paid_at                       TIMESTAMP,


    -- External payroll/finance reference when the amount is
    -- transferred to another financial system.
    payment_reference             VARCHAR(100),


    -- ========================================================
    -- Additional information
    -- ========================================================

    -- Optional employee comments.
    remarks                       TEXT,


    -- ========================================================
    -- Audit fields
    -- ========================================================

    created_at                    TIMESTAMP    NOT NULL DEFAULT now(),

    created_by                    VARCHAR(64)         NOT NULL,

    updated_at                    TIMESTAMP    NOT NULL DEFAULT now(),

    updated_by                    VARCHAR(64)         NOT NULL,
    ip_address                    INET,


    -- ========================================================
    -- Optimistic locking
    -- ========================================================

    version                       BIGINT         NOT NULL DEFAULT 0,


    -- ========================================================
    -- Foreign keys
    -- ========================================================

    CONSTRAINT fk_travel_expense_items_request
        FOREIGN KEY (travel_request_id)
            REFERENCES travel_requests (id)
            ON DELETE RESTRICT,


    CONSTRAINT fk_travel_expense_items_participant
        FOREIGN KEY (travel_request_participant_id)
            REFERENCES travel_request_participants (id)
            ON DELETE RESTRICT,


    CONSTRAINT fk_travel_expense_items_entitlement
        FOREIGN KEY (travel_request_entitlement_id)
            REFERENCES travel_request_entitlements (id)
            ON DELETE RESTRICT,


    -- ========================================================
    -- Amount constraints
    -- ========================================================

    CONSTRAINT ck_travel_expense_items_claimed_amount
        CHECK (
            claimed_amount >= 0
            ),


    CONSTRAINT ck_travel_expense_items_eligible_amount
        CHECK (
            eligible_amount IS NULL
                OR eligible_amount >= 0
            ),


    CONSTRAINT ck_travel_expense_items_non_reimbursable
        CHECK (
            non_reimbursable_amount IS NULL
                OR non_reimbursable_amount >= 0
            ),


    CONSTRAINT ck_travel_expense_items_approved_amount
        CHECK (
            approved_amount IS NULL
                OR approved_amount >= 0
            ),


    CONSTRAINT ck_travel_expense_items_converted_amount
        CHECK (
            converted_claimed_amount IS NULL
                OR converted_claimed_amount >= 0
            ),


    CONSTRAINT ck_travel_expense_items_exchange_rate
        CHECK (
            exchange_rate IS NULL
                OR exchange_rate > 0
            ),


    -- ========================================================
    -- Currency constraints
    -- ========================================================

    CONSTRAINT ck_travel_expense_items_claimed_currency
        CHECK (
            BTRIM(claimed_currency_code) <> ''
            ),


    CONSTRAINT ck_travel_expense_items_settlement_currency
        CHECK (
            BTRIM(settlement_currency_code) <> ''
            ),


    -- ========================================================
    -- Classification constraints
    -- ========================================================

    CONSTRAINT ck_travel_expense_items_category
        CHECK (
            BTRIM(expense_category_code) <> ''
            ),


    -- ========================================================
    -- Status constraints
    -- ========================================================

    CONSTRAINT ck_travel_expense_items_status
        CHECK (
            status IN (
                       'DRAFT',
                       'SUBMITTED',
                       'UNDER_REVIEW',
                       'APPROVED',
                       'PARTIALLY_APPROVED',
                       'REJECTED',
                       'PAID',
                       'CANCELLED'
                )
            ),


    -- ========================================================
    -- Receipt consistency
    -- ========================================================

    -- If receipt is marked as attached, a document identifier
    -- must exist.
    CONSTRAINT ck_travel_expense_items_receipt
        CHECK (
            receipt_attached = FALSE
                OR receipt_document_id IS NOT NULL
            ),


    -- ========================================================
    -- Review consistency
    -- ========================================================

    -- A review timestamp should have a reviewer.
    CONSTRAINT ck_travel_expense_items_review
        CHECK (
            reviewed_at IS NULL
                OR reviewed_by IS NOT NULL
            ),


    -- ========================================================
    -- Payment consistency
    -- ========================================================

    -- A payment timestamp should have a payment reference when
    -- an external financial system is involved. The reference
    -- remains nullable because some internal payment mechanisms
    -- may not provide one.
    CONSTRAINT ck_travel_expense_items_paid_amount
        CHECK (
            paid_at IS NULL
                OR approved_amount IS NOT NULL
            ),


    CONSTRAINT ck_travel_expense_items_version
        CHECK (
            version >= 0
            )
);


-- ============================================================
-- Indexes
-- ============================================================


-- Get all expenses belonging to a Travel Request.
CREATE INDEX idx_travel_expense_items_request
    ON travel_expense_items (
                             travel_request_id
        );


-- Get all expenses for a particular participant.
CREATE INDEX idx_travel_expense_items_participant
    ON travel_expense_items (
                             travel_request_participant_id
        );


-- Find all expenses consuming a particular entitlement.
CREATE INDEX idx_travel_expense_items_entitlement
    ON travel_expense_items (
                             travel_request_entitlement_id
        );


-- Useful for category-based expense reporting.
CREATE INDEX idx_travel_expense_items_category
    ON travel_expense_items (
                             expense_category_code
        );


-- Useful for subcategory reporting.
CREATE INDEX idx_travel_expense_items_subcategory
    ON travel_expense_items (
                             expense_subcategory_code
        );


-- Useful for date-based expense reporting.
CREATE INDEX idx_travel_expense_items_expense_at
    ON travel_expense_items (
                             expense_at
        );


-- Useful for expense processing queues.
CREATE INDEX idx_travel_expense_items_status
    ON travel_expense_items (
                             status
        );


-- Useful for receipt/document verification.
CREATE INDEX idx_travel_expense_items_receipt
    ON travel_expense_items (
                             receipt_document_id
        );


-- Useful for finance/payment reconciliation.
CREATE INDEX idx_travel_expense_items_payment_reference
    ON travel_expense_items (
                             payment_reference
        );


-- Useful for employee travel expense history.
CREATE INDEX idx_travel_expense_items_participant_status
    ON travel_expense_items (
                             travel_request_participant_id,
                             status
        );


