-- Table 1: belonging_master
CREATE TABLE belonging_master (
      id                      bigint generated by default as identity primary key,

      belonging_name          varchar(100) not null unique,
      authorized_employee_id  bigint not null references employees(id),

      active                  boolean not null default true,

      created_at              timestamptz not null default now(),
      updated_at              timestamptz not null default now(),
      created_by              varchar(64) not null,
      updated_by              varchar(64) not null,
      ip_address              inet
);

-- Table 2: belonging_issuance
CREATE TABLE belonging_issuance (
    id                          bigint generated by default as identity primary key,

    belonging_master_id         bigint not null references belonging_master(id),

    employee_id                 bigint not null references employees(id),

    asset_model                 varchar(100),
    asset_year                  smallint,
    asset_price                 decimal(15,2),

    issued_date                 date,
    expiry_date                 date,

    buy_back_perc_employee      decimal(5,2) check (buy_back_perc_employee between 0 and 100),

    buy_back_perc_employer      decimal(5,2) check (buy_back_perc_employer between 0 and 100),

    condition                   varchar(20) check (condition in ('NEW','OLD','USED')),

    activation_status           varchar(20) not null check (activation_status in ('ACTIVE','INACTIVE','RETURNED','LOST','DAMAGED')),

    activation_date             date not null,

    description                 varchar(500),

    clearance_status            varchar(20) check (clearance_status in ('PENDING','APPROVED','REJECTED')),

    clearance_id                varchar(50),
    clearance_date              date,

    created_at                  timestamptz not null default now(),
    updated_at                  timestamptz not null default now(),
    created_by                  varchar(64) not null,
    updated_by                  varchar(64) not null,
    ip_address                  inet,

    check (
        expiry_date is null
            or issued_date is null
            or expiry_date >= issued_date
        ),

    check (
        clearance_date is null
            or clearance_date >= activation_date
        )
);

-- Indexes

CREATE INDEX idx_belonging_issuance_employee
    ON belonging_issuance(employee_id);

CREATE INDEX idx_belonging_issuance_master
    ON belonging_issuance(belonging_master_id);

CREATE INDEX idx_belonging_issuance_activation_status
    ON belonging_issuance(activation_status);