-- ============================================================
-- Travel Module
-- Table: travel_fuel_policies
--
-- Purpose:
-- Master table of Transport-maintained fuel/petrol issuance
-- policies. Each row defines a fuel average (km per litre) used
-- to convert a Transport-approved travel distance into a petrol
-- quantity to be issued.
--
-- Example:
--   PERSONAL_10   Personal Vehicle (10 km/l)   fuel_average = 10.00
--   COMPANY_VEH   Company Vehicle              fuel_average = 0.00
--
-- fuel_average = 0.00 is a VALID, common row: it means the
-- company issues no petrol for that transport arrangement (e.g.
-- a company-fuelled vehicle). It is not an error state.
-- ============================================================


CREATE TABLE travel_fuel_policies
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Business identifier for the fuel policy.
    -- Example: PERSONAL_10, COMPANY_VEHICLE
    code           VARCHAR(50)    NOT NULL,

    -- Human-readable policy name.
    name           VARCHAR(200)   NOT NULL,

    -- Fuel average in kilometres per liter used to convert an
    -- approved travel distance into a petrol quantity:
    --
    --   petrolIssued = actualDistanceKm / fuel_average
    --
    -- Zero is valid and means no petrol is issued under this
    -- policy (e.g. a company-fueled vehicle).
    fuel_average   NUMERIC(12, 2) NOT NULL,

    -- Date from which this fuel policy becomes applicable.
    effective_from DATE           NOT NULL,

    -- Date until which this fuel policy remains applicable.
    -- NULL means there is currently no defined end date.
    effective_to   DATE,

    -- Whether this policy can currently be applied by Transport.
    is_active      BOOLEAN        NOT NULL DEFAULT TRUE,

    -- Standard audit fields.
    created_at     TIMESTAMP      NOT NULL DEFAULT now(),
    created_by     VARCHAR(64)    NOT NULL,

    updated_at     TIMESTAMP      NOT NULL DEFAULT now(),
    updated_by     VARCHAR(64)    NOT NULL,
    ip_address     INET,

    -- Optimistic locking version.
    version        BIGINT         NOT NULL DEFAULT 0,

    -- --------------------------------------------------------
    -- Constraints
    -- --------------------------------------------------------

    CONSTRAINT ck_travel_fuel_policies_code
        CHECK (BTRIM(code) <> ''),

    CONSTRAINT ck_travel_fuel_policies_name
        CHECK (BTRIM(name) <> ''),

    -- Zero is a valid, deliberate "no petrol issued" policy.
    CONSTRAINT ck_travel_fuel_policies_fuel_average
        CHECK (fuel_average >= 0),

    CONSTRAINT ck_travel_fuel_policies_effective_dates
        CHECK (
            effective_to IS NULL
                OR effective_to >= effective_from
            ),

    CONSTRAINT ck_travel_fuel_policies_version
        CHECK (version >= 0)
);


-- ============================================================
-- Indexes
-- ============================================================

-- Main lookup: Transport resolves a policy by its business code.
CREATE INDEX idx_travel_fuel_policies_code
    ON travel_fuel_policies (code);

-- Used when filtering to currently-usable policies.
CREATE INDEX idx_travel_fuel_policies_is_active
    ON travel_fuel_policies (is_active);

CREATE UNIQUE INDEX uq_travel_fuel_policy_active_code
    ON travel_fuel_policies (code) WHERE is_active = TRUE;

CREATE INDEX idx_travel_fuel_policies_lookup
    ON travel_fuel_policies (code, effective_from, effective_to);


