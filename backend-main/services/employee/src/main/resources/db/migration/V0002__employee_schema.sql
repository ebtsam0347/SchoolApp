-- employee-service schema. Lives in the `employee` Postgres schema (set
-- via spring.flyway.default-schema). Audit columns on every business
-- entity; bridge tables, system tables (saga_state, outbox) are exempt.
--
-- Forward references between tables (employees -> departments,
-- employees -> manager_id self-ref) are handled by creating tables in
-- the order they're referenced, then adding the FKs at the end where
-- the cycle would otherwise force us into deferred constraints.

-- ---------------------------------------------------------------------
-- Location catalogs.
-- ---------------------------------------------------------------------

create table provinces (
    id          bigint generated by default as identity primary key,
    code        varchar(16)  not null unique,
    name        varchar(64)  not null,
    active      boolean      not null default true,
    created_at  timestamptz  not null default now(),
    updated_at  timestamptz  not null default now(),
    created_by  varchar(64)  not null,
    updated_by  varchar(64)  not null,
    ip_address  inet
);

create table cities (
    id           bigint generated by default as identity primary key,
    province_id  bigint       not null references provinces(id),
    code         varchar(32)  not null unique,
    name         varchar(128) not null,
    active       boolean      not null default true,
    created_at   timestamptz  not null default now(),
    updated_at   timestamptz  not null default now(),
    created_by   varchar(64)  not null,
    updated_by   varchar(64)  not null,
    ip_address   inet
);

create index idx_cities_province on cities (province_id);

-- ---------------------------------------------------------------------
-- Org catalogs.
-- ---------------------------------------------------------------------

create table departments (
    id          bigint generated by default as identity primary key,
    code        varchar(32)  not null unique,
    name        varchar(128) not null,
    head_id     bigint,                          -- FK added after employees
    active      boolean      not null default true,
    created_at  timestamptz  not null default now(),
    updated_at  timestamptz  not null default now(),
    created_by  varchar(64)  not null,
    updated_by  varchar(64)  not null,
    ip_address  inet
);

create table sections (
    id            bigint generated by default as identity primary key,
    code          varchar(32)  not null unique,
    name          varchar(128) not null,
    department_id bigint       not null references departments(id),
    head_id       bigint,                        -- FK added after employees
    active        boolean      not null default true,
    created_at    timestamptz  not null default now(),
    updated_at    timestamptz  not null default now(),
    created_by    varchar(64)  not null,
    updated_by    varchar(64)  not null,
    ip_address    inet
);

create index idx_sections_department on sections (department_id);

create table designations (
    id          bigint generated by default as identity primary key,
    code        varchar(32)  not null unique,
    title       varchar(128) not null,
    active      boolean      not null default true,
    created_at  timestamptz  not null default now(),
    updated_at  timestamptz  not null default now(),
    created_by  varchar(64)  not null,
    updated_by  varchar(64)  not null,
    ip_address  inet
);

create table grades (
    id          bigint generated by default as identity primary key,
    code        varchar(32)  not null unique,
    name        varchar(128) not null,
    level       int          not null,
    description text,
    active      boolean      not null default true,
    created_at  timestamptz  not null default now(),
    updated_at  timestamptz  not null default now(),
    created_by  varchar(64)  not null,
    updated_by  varchar(64)  not null,
    ip_address  inet
);

-- ---------------------------------------------------------------------
-- Skill + qualification catalogs.
-- ---------------------------------------------------------------------

create table skills (
    id          bigint generated by default as identity primary key,
    code        varchar(32)  not null unique,
    name        varchar(128) not null,
    category    varchar(32),
    active      boolean      not null default true,
    created_at  timestamptz  not null default now(),
    updated_at  timestamptz  not null default now(),
    created_by  varchar(64)  not null,
    updated_by  varchar(64)  not null,
    ip_address  inet
);

create table qualifications (
    id          bigint generated by default as identity primary key,
    code        varchar(64)  not null unique,
    name        varchar(255) not null,
    level       varchar(32)  not null,
    active      boolean      not null default true,
    created_at  timestamptz  not null default now(),
    updated_at  timestamptz  not null default now(),
    created_by  varchar(64)  not null,
    updated_by  varchar(64)  not null,
    ip_address  inet
);

-- ---------------------------------------------------------------------
-- Employees (the central table).
-- ---------------------------------------------------------------------

create table employees (
    id                   bigint generated by default as identity primary key,
    user_id              bigint       unique,                  -- references auth.users.id (no FK across schemas)
    employee_code        varchar(32)  not null unique,
    full_name            varchar(128) not null,
    cnic                 varchar(15),
    cnic_issue_date      date,
    cnic_expiry_date     date,
    ntn                  varchar(32),
    insurance_number     varchar(64),
    ssc_number           varchar(64),
    eobi_number          varchar(32),
    date_of_birth        date,
    gender               varchar(16),
    marital_status       varchar(16),
    personal_email       varchar(255),
    work_email           varchar(255),
    phone                varchar(32),
    permanent_address    text,
    current_address      text,
    city_id              bigint       references cities(id),
    country              varchar(64)  default 'PK',
    joining_date         date         not null,
    confirmation_date    date,
    employment_status    varchar(16)  not null,
    employment_type      varchar(16),
    department_id        bigint       references departments(id),
    section_id           bigint       references sections(id),
    designation_id       bigint       references designations(id),
    grade_id             bigint       references grades(id),
    manager_id           bigint       references employees(id),
    profile_picture_key  varchar(512),
    created_at           timestamptz  not null default now(),
    updated_at           timestamptz  not null default now(),
    created_by           varchar(64)  not null,
    updated_by           varchar(64)  not null,
    ip_address           inet,
    constraint chk_employees_status check (
        employment_status in ('ACTIVE','ON_NOTICE','ON_LEAVE','SUSPENDED','TERMINATED')
    ),
    constraint chk_employees_type check (
        employment_type is null or employment_type in ('PERMANENT','CONTRACT','INTERN')
    ),
    constraint chk_cnic_dates check (
        cnic_issue_date is null or cnic_expiry_date is null or cnic_expiry_date > cnic_issue_date
    )
);

create index idx_employees_manager     on employees (manager_id);
create index idx_employees_department  on employees (department_id);
create index idx_employees_section     on employees (section_id);
create index idx_employees_designation on employees (designation_id);
create index idx_employees_grade       on employees (grade_id);
create index idx_employees_status      on employees (employment_status);
create index idx_employees_city        on employees (city_id);

-- Now we can wire the head_id FKs back to employees.
alter table departments add constraint fk_departments_head
    foreign key (head_id) references employees(id);
alter table sections add constraint fk_sections_head
    foreign key (head_id) references employees(id);

-- ---------------------------------------------------------------------
-- Employment lifecycle: contracts, history, exits, suspensions,
-- discipline.
-- ---------------------------------------------------------------------

create table employment_contracts (
    id              bigint generated by default as identity primary key,
    employee_id     bigint       not null references employees(id),
    contract_type   varchar(32)  not null,
    start_date      date         not null,
    end_date        date,
    status          varchar(16)  not null,
    probation_days  int,
    is_extended     boolean      not null default false,
    document_key    varchar(512),
    created_at      timestamptz  not null default now(),
    updated_at      timestamptz  not null default now(),
    created_by      varchar(64)  not null,
    updated_by      varchar(64)  not null,
    ip_address      inet,
    constraint chk_contract_type check (
        contract_type in ('PROBATION','PERMANENT','FIXED_TERM')
    ),
    constraint chk_contract_status check (
        status in ('ACTIVE','EXPIRED','TERMINATED')
    ),
    constraint chk_probation_days check (
        probation_days is null or probation_days in (30,60,90,120,180)
    ),
    constraint chk_probation_only_on_probation check (
        contract_type = 'PROBATION' or probation_days is null
    )
);

create index idx_contracts_employee
    on employment_contracts (employee_id, contract_type, status);
create index idx_contracts_probation_due
    on employment_contracts (end_date)
    where contract_type = 'PROBATION' and status = 'ACTIVE';

create table employee_history (
    id              bigint generated by default as identity primary key,
    employee_id     bigint       not null references employees(id),
    effective_from  date         not null,
    effective_to    date,
    department_id   bigint       references departments(id),
    section_id      bigint       references sections(id),
    designation_id  bigint       references designations(id),
    grade_id        bigint       references grades(id),
    manager_id      bigint       references employees(id),
    change_reason   varchar(32),
    notes           text,
    created_at      timestamptz  not null default now(),
    updated_at      timestamptz  not null default now(),
    created_by      varchar(64)  not null,
    updated_by      varchar(64)  not null,
    ip_address      inet,
    constraint chk_history_change_reason check (
        change_reason is null or change_reason in (
            'ONBOARD','TRANSFER','PROMOTION','DEMOTION',
            'DEPARTMENT_CHANGE','MANAGER_CHANGE','SECTION_CHANGE','EXIT'
        )
    )
);

create index idx_history_employee
    on employee_history (employee_id, effective_from desc);
create unique index uq_history_current
    on employee_history (employee_id)
    where effective_to is null;

create table employee_exits (
    id                 bigint generated by default as identity primary key,
    employee_id        bigint       unique not null references employees(id),
    exit_type          varchar(16)  not null,
    notice_start_date  date,
    last_working_day   date         not null,
    reason             varchar(64),
    notes              text,
    status             varchar(16)  not null,
    completed_at       timestamptz,
    withdrawn_at       timestamptz,
    withdrawn_reason   text,
    created_at         timestamptz  not null default now(),
    updated_at         timestamptz  not null default now(),
    created_by         varchar(64)  not null,
    updated_by         varchar(64)  not null,
    ip_address         inet,
    constraint chk_exit_type check (
        exit_type in ('RESIGNATION','TERMINATION','RETIREMENT')
    ),
    constraint chk_exit_status check (
        status in ('PENDING','COMPLETED','WITHDRAWN')
    )
);

create index idx_exits_status on employee_exits (status);

create table employee_suspensions (
    id              bigint generated by default as identity primary key,
    employee_id     bigint       not null references employees(id),
    start_date      date         not null,
    end_date        date,
    reason          text         not null,
    with_pay        boolean      not null,
    status          varchar(16)  not null,
    lifted_on       date,
    lifted_reason   text,
    created_at      timestamptz  not null default now(),
    updated_at      timestamptz  not null default now(),
    created_by      varchar(64)  not null,
    updated_by      varchar(64)  not null,
    ip_address      inet,
    constraint chk_suspension_status check (status in ('ACTIVE','LIFTED'))
);

create unique index uq_suspension_active
    on employee_suspensions (employee_id)
    where status = 'ACTIVE';
create index idx_suspensions_employee
    on employee_suspensions (employee_id, start_date desc);

create table disciplinary_actions (
    id              bigint generated by default as identity primary key,
    employee_id     bigint       not null references employees(id),
    level           varchar(24)  not null,
    category        varchar(24)  not null,
    incident_date   date,
    issued_on       date         not null,
    reason          text         not null,
    decision        varchar(16),
    decision_notes  text,
    closed_on       date,
    status          varchar(16)  not null,
    created_at      timestamptz  not null default now(),
    updated_at      timestamptz  not null default now(),
    created_by      varchar(64)  not null,
    updated_by      varchar(64)  not null,
    ip_address      inet,
    constraint chk_disc_level check (
        level in ('FIRST_WARNING','SECOND_WARNING','FINAL_WARNING')
    ),
    constraint chk_disc_category check (
        category in ('ATTENDANCE','MISCONDUCT','PERFORMANCE',
                     'INSUBORDINATION','POLICY_VIOLATION','OTHER')
    ),
    constraint chk_disc_decision check (
        decision is null or decision in ('UPHELD','WITHDRAWN')
    ),
    constraint chk_disc_status check (status in ('ISSUED','CLOSED'))
);

create index idx_disc_employee on disciplinary_actions (employee_id, issued_on desc);
create index idx_disc_open on disciplinary_actions (employee_id) where status = 'ISSUED';
create index idx_disc_counts on disciplinary_actions (level, decision, issued_on);

