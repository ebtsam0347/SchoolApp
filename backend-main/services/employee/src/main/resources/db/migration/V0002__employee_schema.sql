-- ---------------------------------------------------------------------
-- Saga state (system table — no audit columns).
-- ---------------------------------------------------------------------

create table saga_state (
    id            bigint generated by default as identity primary key,
    saga_type     varchar(64)  not null,
    business_key  varchar(128) not null,
    status        varchar(16)  not null,
    current_step  varchar(64),
    payload_json  jsonb,
    last_error    text,
    attempt       int          not null default 0,
    created_at    timestamptz  not null default now(),
    updated_at    timestamptz  not null default now(),
    constraint uq_saga_business unique (saga_type, business_key),
    constraint chk_saga_status check (status in ('RUNNING','DONE','FAILED','COMPENSATING'))
);

-- ---------------------------------------------------------------------
-- Per-year sequence for employee codes (FS-{YYYY}-{NNNN}). One row per
-- year; the service `select … for update`s it to allocate the next code.
-- ---------------------------------------------------------------------

create table employee_code_sequence (
    year       int    primary key,
    last_value int    not null default 0
);
