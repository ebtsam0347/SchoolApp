-- ============================================================
-- Travel Module
-- Table: travel_request_entitlements
--
-- Purpose:
-- Stores the actual entitlement snapshot applicable to a
-- participant for a specific Travel Request.
--
-- This table is intentionally separate from:
--
--   travel_policy_grade_limits
--
-- because policy configuration can change in the future while
-- historical Travel Requests must remain unchanged.
--
-- Example:
--
-- Policy v2:
--   E-4 Dinner = PKR 1,500
--
-- Travel Request TR-2026-000125:
--   Farhan / E-4
--
-- Entitlement snapshot:
--   Dinner = PKR 1,500
--
-- If Policy v3 later changes Dinner to PKR 2,000, the existing
-- Travel Request continues to use PKR 1,500.
--
--
-- One participant can have multiple entitlement records:
--
--   ACCOMMODATION
--   BREAKFAST
--   LUNCH
--   DINNER
--   OTHER_ALLOWED
--
-- The actual expense/claim amount is NOT stored here.
--
-- This table represents:
--
--     "What is this employee entitled to?"
--
-- while expense tables represent:
--
--     "What did this employee actually spend?"
-- ============================================================


CREATE TABLE travel_request_entitlements
(
    id                            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,


    -- ========================================================
    -- Request / participant relationship
    -- ========================================================

    -- Travel Request to which this entitlement belongs.
    travel_request_id             BIGINT         NOT NULL,

    -- Specific participant receiving the entitlement.
    travel_request_participant_id BIGINT         NOT NULL,


    -- ========================================================
    -- Policy reference
    -- ========================================================

    -- Exact policy version from which this entitlement was
    -- derived.
    --
    -- This is kept even though travel_requests also contains
    -- policy_version_id because keeping it here makes each
    -- entitlement independently traceable.
    policy_version_id             BIGINT         NOT NULL,


    -- ========================================================
    -- Policy entitlement reference
    -- ========================================================

    -- Reference to the policy-grade-limit record from which this
    -- entitlement was calculated/copied.
    --
    -- This creates a traceable relationship:
    --
    -- Policy Version
    --       ↓
    -- Grade Limit
    --       ↓
    -- Request Entitlement
    policy_grade_limit_id         BIGINT         NOT NULL,


    -- ========================================================
    -- Employee / grade snapshot
    -- ========================================================

    -- Employee identifier from Employee Service.
    --
    -- Kept here for efficient reporting and historical trace.
    employee_id                   BIGINT         NOT NULL,

    -- Grade identifier captured when entitlement was created.
    grade_id_snapshot             BIGINT,

    -- Grade business code.
    --
    -- Example:
    --   E-4
    grade_code_snapshot           VARCHAR(50),

    -- Grade name.
    --
    -- Example:
    --   Manager
    grade_name_snapshot           VARCHAR(150),


    -- ========================================================
    -- Entitlement category
    -- ========================================================

    -- Type of entitlement.
    --
    -- ACCOMMODATION
    -- BREAKFAST
    -- LUNCH
    -- DINNER
    -- OTHER
    --
    -- This is deliberately a code rather than separate columns
    -- such as:
    --
    --   accommodation_limit
    --   breakfast_limit
    --   lunch_limit
    --   dinner_limit
    --
    -- because the row-based approach is more extensible.
    entitlement_type_code         VARCHAR(50)    NOT NULL,


    -- ========================================================
    -- Entitlement calculation
    -- ========================================================

    -- Number of units/days/meals allowed.
    --
    -- Examples:
    --
    -- Accommodation:
    --   2 nights
    --
    -- Breakfast:
    --   3 meals
    --
    -- Lunch:
    --   3 meals
    --
    -- Dinner:
    --   3 meals
    quantity_allowed              NUMERIC(12, 3) NOT NULL DEFAULT 0,


    -- Maximum amount allowed per unit.
    --
    -- Example:
    --
    -- Dinner:
    --   1,500 PKR per meal
    --
    -- Accommodation:
    --   10,000 PKR per night
    unit_limit_amount             NUMERIC(15, 2),


    -- Total maximum amount allowed for this entitlement.
    --
    -- Example:
    --
    -- Dinner:
    --   3 meals × 1,500
    --   = 4,500
    --
    -- This value should be calculated by the backend.
    total_limit_amount            NUMERIC(15, 2),


    -- Currency used by the entitlement.
    currency_code                 VARCHAR(3)        NOT NULL,


    -- ========================================================
    -- Calculation basis
    -- ========================================================

    -- Explains how the quantity/limit was determined.
    --
    -- Examples:
    --
    -- POLICY
    -- POLICY_PER_DAY
    -- POLICY_PER_MEAL
    -- POLICY_PER_NIGHT
    -- MANUAL_ADJUSTMENT
    --
    -- This helps future developers and HR understand why a
    -- particular entitlement amount exists.
    calculation_basis_code        VARCHAR(50)    NOT NULL,


    -- Number of travel days used when calculating a
    -- day/night/meal based entitlement.
    --
    -- Example:
    --   3-day factory tour
    --
    -- Can be NULL for entitlement types that do not depend on
    -- travel duration.
    travel_days                   NUMERIC(12, 3),


    -- ========================================================
    -- Snapshot of policy value
    -- ========================================================

    -- Original policy amount copied at the time the entitlement
    -- was generated.
    --
    -- This provides an additional historical audit layer.
    policy_unit_limit_amount      NUMERIC(15, 2),


    -- ========================================================
    -- Lifecycle
    -- ========================================================

    -- Indicates whether this entitlement is currently active.
    --
    -- Normally TRUE.
    --
    -- If a request is legitimately modified/recalculated,
    -- historical entitlement rows can be retained and marked
    -- inactive rather than physically deleted.
    is_active                     BOOLEAN        NOT NULL DEFAULT TRUE,


    -- When this entitlement became applicable.
    effective_at                  TIMESTAMP    NOT NULL DEFAULT now(),


    -- Optional timestamp when this entitlement was superseded.
    superseded_at                 TIMESTAMP,


    -- Optional reason for superseding/recalculating the
    -- entitlement.
    superseded_reason             TEXT,


    -- ========================================================
    -- Audit fields
    -- ========================================================

    created_at                    TIMESTAMP    NOT NULL DEFAULT now(),

    created_by                    VARCHAR(64)         NOT NULL,

    updated_at                    TIMESTAMP    NOT NULL DEFAULT now(),

    updated_by                    VARCHAR(64)         NOT NULL,
    ip_address                    INET,


    -- ========================================================
    -- Optimistic locking
    -- ========================================================

    version                       BIGINT         NOT NULL DEFAULT 0,


    -- ========================================================
    -- Foreign keys
    -- ========================================================

    CONSTRAINT fk_travel_request_entitlements_request
        FOREIGN KEY (travel_request_id)
            REFERENCES travel_requests (id)
            ON DELETE RESTRICT,


    CONSTRAINT fk_travel_request_entitlements_participant
        FOREIGN KEY (travel_request_participant_id)
            REFERENCES travel_request_participants (id)
            ON DELETE RESTRICT,


    CONSTRAINT fk_travel_request_entitlements_policy
        FOREIGN KEY (policy_version_id)
            REFERENCES travel_policy_versions (id)
            ON DELETE RESTRICT,


    CONSTRAINT fk_travel_request_entitlements_policy_limit
        FOREIGN KEY (policy_grade_limit_id)
            REFERENCES travel_policy_grade_limits (id)
            ON DELETE RESTRICT,


    -- ========================================================
    -- Uniqueness
    -- ========================================================

    -- Only one active entitlement of a particular type should
    -- normally exist for one participant in one request.
    --
    -- Historical/superseded rows can exist because is_active
    -- participates in the uniqueness strategy through a
    -- partial unique index below.
    --
    -- Therefore, this table does NOT use a normal UNIQUE
    -- constraint for entitlement type.


    -- ========================================================
    -- Validation
    -- ========================================================

    CONSTRAINT ck_travel_request_entitlements_quantity
        CHECK (
            quantity_allowed >= 0
            ),


    CONSTRAINT ck_travel_request_entitlements_unit_limit
        CHECK (
            unit_limit_amount IS NULL
                OR unit_limit_amount >= 0
            ),


    CONSTRAINT ck_travel_request_entitlements_total_limit
        CHECK (
            total_limit_amount IS NULL
                OR total_limit_amount >= 0
            ),


    CONSTRAINT ck_travel_request_entitlements_policy_limit
        CHECK (
            policy_unit_limit_amount IS NULL
                OR policy_unit_limit_amount >= 0
            ),


    CONSTRAINT ck_travel_request_entitlements_travel_days
        CHECK (
            travel_days IS NULL
                OR travel_days >= 0
            ),


    CONSTRAINT ck_travel_request_entitlements_type
        CHECK (
            BTRIM(entitlement_type_code) <> ''
            ),


    CONSTRAINT ck_travel_request_entitlements_basis
        CHECK (
            BTRIM(calculation_basis_code) <> ''
            ),


    CONSTRAINT ck_travel_request_entitlements_currency
        CHECK (
            BTRIM(currency_code) <> ''
            ),


    -- If an entitlement has been superseded, the timestamp must
    -- be available.
    CONSTRAINT ck_travel_request_entitlements_superseded
        CHECK (
            superseded_at IS NULL
                OR superseded_at >= effective_at
            ),


    CONSTRAINT ck_travel_request_entitlements_version
        CHECK (
            version >= 0
            )
);


-- ============================================================
-- Partial unique index
-- ============================================================

-- Prevent duplicate ACTIVE entitlement categories for the same
-- participant in the same Travel Request.
--
-- Example:
--
-- Participant 100245
-- DINNER
-- active = TRUE
--
-- Only one active DINNER entitlement is allowed.
--
-- But an old superseded DINNER entitlement can remain in the
-- table for historical tracking.
CREATE UNIQUE INDEX uq_travel_request_entitlements_active_type
    ON travel_request_entitlements (
                                    travel_request_participant_id,
                                    entitlement_type_code
        ) WHERE is_active = TRUE;


-- ============================================================
-- Indexes
-- ============================================================


-- Get all entitlements for a Travel Request.
CREATE INDEX idx_travel_request_entitlements_request
    ON travel_request_entitlements (
                                    travel_request_id
        );


-- Get all entitlements for a participant.
CREATE INDEX idx_travel_request_entitlements_participant
    ON travel_request_entitlements (
                                    travel_request_participant_id
        );


-- Employee travel entitlement history.
CREATE INDEX idx_travel_request_entitlements_employee
    ON travel_request_entitlements (
                                    employee_id
        );


-- Find entitlements by type.
CREATE INDEX idx_travel_request_entitlements_type
    ON travel_request_entitlements (
                                    entitlement_type_code
        );


-- Trace entitlement back to the policy version.
CREATE INDEX idx_travel_request_entitlements_policy
    ON travel_request_entitlements (
                                    policy_version_id
        );


-- Trace entitlement back to the exact policy grade limit.
CREATE INDEX idx_travel_request_entitlements_policy_limit
    ON travel_request_entitlements (
                                    policy_grade_limit_id
        );


-- Useful for active entitlement queries.
CREATE INDEX idx_travel_request_entitlements_active
    ON travel_request_entitlements (
                                    travel_request_id,
                                    is_active
        );


-- Useful for effective/superseded historical reporting.
CREATE INDEX idx_travel_request_entitlements_effective
    ON travel_request_entitlements (
                                    effective_at
        );


