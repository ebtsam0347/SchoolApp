-- commons-approval canonical schema.
-- CREATE TABLE IF NOT EXISTS so this migration is idempotent for services
-- that already applied the attendance-local V0002/V0023 migrations.
-- Prefix V0510 keeps it in the commons V05xx range (out-of-order is
-- required for services that mix V000x and V05xx migrations).

-- Configurable approval chain catalog. HR edits these via /approval-workflows.
-- Each active row is one stage in the ordered chain for a request type.
-- Snapshotted onto approval_steps at submit — editing a chain never disturbs
-- in-flight requests.
--
-- Uses plain `timestamp` (not `timestamptz`) per project convention.
create table if not exists approval_workflow_stage (
    id                 bigint generated by default as identity primary key,
    request_type       varchar(24) not null,
    stage_no           int         not null,
    resolver_kind      varchar(16) not null,
    approve_permission varchar(64),
    label              varchar(48) not null,
    active             boolean     not null default true,
    created_at         timestamp   not null default now(),
    updated_at         timestamp   not null default now(),
    created_by         varchar(64) not null,
    updated_by         varchar(64) not null,
    ip_address         inet
);

-- At most one row per (type, stage_no) among the live chain.
create unique index if not exists uq_workflow_stage_active
    on approval_workflow_stage (request_type, stage_no) where active;

-- One step per stage per request. Snapshotted from the catalog at submit.
-- Uses `timestamptz` for decided_at and audit columns (historical alignment
-- with the original attendance V0002 migration).
create table if not exists approval_steps (
    id                 bigint generated by default as identity primary key,
    request_type       varchar(24)  not null,
    request_id         bigint       not null,
    stage_no           int          not null,
    resolver_kind      varchar(16)  not null,
    approve_permission varchar(64),
    label              varchar(48)  not null,
    assigned_to        bigint,
    status             varchar(16)  not null,
    decided_by         bigint,
    decided_at         timestamp,
    note               text,
    created_at         timestamp  not null default now(),
    updated_at         timestamp  not null default now(),
    created_by         varchar(64)  not null,
    updated_by         varchar(64)  not null,
    ip_address         inet
);

create index if not exists idx_steps_assignee_pending
    on approval_steps (request_type, assigned_to)
    where assigned_to is not null and status = 'PENDING';

create index if not exists idx_steps_roleonly_pending
    on approval_steps (request_type, status)
    where assigned_to is null and status = 'PENDING';

create index if not exists idx_steps_by_decider
    on approval_steps (decided_by, decided_at)
    where decided_by is not null;

-- Approval delegation. A manager may delegate their PENDING steps to another
-- user over a date range. request_types is null = all types.
create table if not exists approval_delegations (
    id             bigint generated by default as identity primary key,
    delegator_id   bigint       not null,
    delegate_id    bigint       not null,
    request_types  varchar(24)[],
    from_date      date         not null,
    to_date        date,
    reason         text,
    status         varchar(16)  not null default 'ACTIVE',
    revoked_at     timestamp,
    revoked_by     bigint,
    created_at     timestamp  not null default now(),
    updated_at     timestamp  not null default now(),
    created_by     varchar(64)  not null,
    updated_by     varchar(64)  not null,
    ip_address     inet
);

create index if not exists idx_delegations_delegate_active
    on approval_delegations (delegate_id, from_date, to_date)
    where status = 'ACTIVE';

create index if not exists idx_delegations_delegator
    on approval_delegations (delegator_id, status);
