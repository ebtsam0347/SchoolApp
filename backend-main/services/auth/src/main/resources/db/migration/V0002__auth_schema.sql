-- auth-service schema. Lives in the `auth` Postgres schema (set via
-- spring.flyway.default-schema). Audit columns on every business entity;
-- bridge tables (user_roles, role_permissions) and operational tables
-- (sessions, outbox) are exempt.

create table users (
    id              bigint generated by default as identity primary key,
    username        varchar(64)  not null unique,
    full_name       varchar(128) not null,
    email           varchar(255) unique,
    password_hash   varchar(72)  not null,
    status          varchar(16)  not null,
    must_change_pw  boolean      not null default false,
    employee_linked boolean      not null default false,
    last_login_at   timestamptz,
    failed_logins   int          not null default 0,
    locked_until    timestamptz,
    created_at      timestamptz  not null default now(),
    updated_at      timestamptz  not null default now(),
    created_by      varchar(64)  not null,
    updated_by      varchar(64)  not null,
    ip_address      inet
);

create index idx_users_email on users (email);

create table roles (
    id          bigint generated by default as identity primary key,
    code        varchar(64)  not null unique,
    name        varchar(128) not null,
    description text,
    created_at  timestamptz  not null default now(),
    updated_at  timestamptz  not null default now(),
    created_by  varchar(64)  not null,
    updated_by  varchar(64)  not null,
    ip_address  inet
);

create table permissions (
    id          bigint generated by default as identity primary key,
    code        varchar(128) not null unique,
    name        varchar(255) not null,
    created_at  timestamptz  not null default now(),
    updated_at  timestamptz  not null default now(),
    created_by  varchar(64)  not null,
    updated_by  varchar(64)  not null,
    ip_address  inet
);

create table role_permissions (
    role_id       bigint not null references roles(id) on delete cascade,
    permission_id bigint not null references permissions(id) on delete cascade,
    primary key (role_id, permission_id)
);

create table user_roles (
    user_id    bigint       not null references users(id) on delete cascade,
    role_id    bigint       not null references roles(id) on delete cascade,
    granted_by varchar(64),
    granted_at timestamptz  not null default now(),
    primary key (user_id, role_id)
);

create table sessions (
    id               bigint generated by default as identity primary key,
    user_id          bigint       not null references users(id),
    refresh_token_id varchar(64)  not null unique,
    device_label     varchar(128),
    user_agent       varchar(512),
    ip_address       inet,
    issued_at        timestamptz  not null default now(),
    last_seen_at     timestamptz  not null default now(),
    expires_at       timestamptz  not null,
    revoked_at       timestamptz,
    revoked_by       varchar(64),
    revoked_reason   varchar(32)
);

create index idx_sessions_user_active on sessions (user_id) where revoked_at is null;
