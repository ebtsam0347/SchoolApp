package com.forward.hrms.payroll.service;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.forward.hrms.commons.storage.ObjectStorage;
import com.forward.hrms.payroll.config.PayrollProperties;
import com.forward.hrms.payroll.entity.PayrollRun;
import com.forward.hrms.payroll.entity.Payslip;
import com.forward.hrms.payroll.entity.ReportJob;
import com.forward.hrms.payroll.repository.PayrollRunRepository;
import com.forward.hrms.payroll.repository.PayslipRepository;

import lombok.extern.slf4j.Slf4j;

import org.springframework.beans.factory.annotation.Qualifier;
import org.springframework.data.domain.Pageable;
import org.springframework.stereotype.Service;

import java.io.ByteArrayInputStream;
import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.InputStream;
import java.util.List;
import java.util.zip.Deflater;
import java.util.zip.ZipEntry;
import java.util.zip.ZipOutputStream;

/**
 * Pack every generated payslip PDF in a payroll run into a single ZIP.
 * Async because a 600-employee run is several seconds of MinIO fetches +
 * compression. Skips payslips whose {@code pdfObjectKey} is null —
 * those weren't generated by the run-finalize batch (perhaps the run is
 * still DRAFT, or the batch failed mid-way and was never retried).
 */
@Slf4j
@Service
public class PayslipsRunZipReportService implements ReportJobHandler {

    public static final String TYPE = "PAYSLIPS_RUN";

    private static final String OUTPUT_BUCKET = "reports";

    private final PayrollRunRepository runs;
    private final PayslipRepository payslips;
    private final ObjectStorage storage;
    private final PayrollProperties props;
    private final ObjectMapper json;

    public PayslipsRunZipReportService(PayrollRunRepository runs,
                                       PayslipRepository payslips,
                                       ObjectStorage storage,
                                       PayrollProperties props,
                                       @Qualifier("outboxObjectMapper") ObjectMapper json) {
        this.runs = runs;
        this.payslips = payslips;
        this.storage = storage;
        this.props = props;
        this.json = json;
    }

    @Override public String type() { return TYPE; }

    @Override
    public Output handle(ReportJob job) {
        long runId = parseRunId(job);
        PayrollRun run = runs.findById(runId).orElseThrow(() ->
                new IllegalStateException("payroll run not found: " + runId));
        List<Payslip> all = payslips.findAllByPayrollRunId(runId, Pageable.unpaged()).getContent();

        ByteArrayOutputStream out = new ByteArrayOutputStream(256 * 1024);
        int included = 0;
        int skipped = 0;
        try (ZipOutputStream zip = new ZipOutputStream(out)) {
            zip.setLevel(Deflater.BEST_SPEED);
            for (Payslip p : all) {
                if (p.getPdfObjectKey() == null) {
                    skipped++;
                    continue;
                }
                String entryName = "%s_%d-%02d.pdf".formatted(
                        p.getEmployeeCode(), p.getPeriodYear(), p.getPeriodMonth());
                zip.putNextEntry(new ZipEntry(entryName));
                try (InputStream in = storage.getObject(props.payslips().bucket(), p.getPdfObjectKey())) {
                    in.transferTo(zip);
                } catch (IOException ex) {
                    throw new IllegalStateException(
                            "Failed to read payslip object " + p.getPdfObjectKey() + " for payslip " + p.getId(), ex);
                }
                zip.closeEntry();
                included++;
            }
        } catch (IOException e) {
            throw new IllegalStateException("Payslip zip write failed for run " + runId, e);
        }

        if (included == 0) {
            throw new IllegalStateException(
                    "No payslip PDFs to include for run " + runId
                            + " (none have pdf_object_key set; finalize the run first). " + skipped + " skipped.");
        }

        byte[] bytes = out.toByteArray();
        String key = "payroll/payslips-run/%d/%d.zip".formatted(runId, job.getId());
        storage.upload(OUTPUT_BUCKET, key,
                new ByteArrayInputStream(bytes), bytes.length, "application/zip", null);
        log.info("Zipped {} payslip PDFs for run {} (skipped={}, {} bytes)",
                included, runId, skipped, bytes.length);
        return new Output(key, bytes.length);
    }

    private long parseRunId(ReportJob job) {
        try {
            JsonNode parsed = json.readTree(job.getParams());
            JsonNode id = parsed.get("payrollRunId");
            if (id == null || !id.canConvertToLong()) {
                throw new IllegalArgumentException(
                        "PAYSLIPS_RUN params missing payrollRunId (got " + job.getParams() + ")");
            }
            return id.asLong();
        } catch (IOException ex) {
            throw new IllegalArgumentException("PAYSLIPS_RUN params not parseable: " + job.getParams(), ex);
        }
    }
}
