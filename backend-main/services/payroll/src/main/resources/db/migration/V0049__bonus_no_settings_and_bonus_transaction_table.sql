create table bonus_no_settings (
    id                    bigint generated by default as identity primary key,
    fiscal_year_code      varchar(7)   not null references fiscal_years(code),
    bonus_no              int          not null,
    percentage_of_salary  numeric(5,2) not null,
    status                varchar(16)  not null,
    created_at            timestamp    not null default now(),
    updated_at            timestamp    not null default now(),
    created_by            varchar(64)  not null,
    updated_by            varchar(64)  not null,
    ip_address            inet,
    constraint uq_bonus_no_settings_fy_bonus unique (fiscal_year_code, bonus_no),
    constraint chk_bonus_no_settings_bonus_no check (bonus_no between 1 and 4),
    constraint chk_bonus_no_settings_percentage check (percentage_of_salary >= 0 and percentage_of_salary <= 100),
    constraint chk_bonus_no_settings_status check (status in ('DRAFT','LOCKED','COMPUTING','COMPUTED','APPROVED','POSTING','POSTED','FAILED','CANCELLED'))
);

create index idx_bonus_no_settings_fy
    on bonus_no_settings (fiscal_year_code);

create table bonus_transaction (
    id                               bigint generated by default as identity primary key,
    fiscal_year_code                 varchar(7)   not null,
    bonus_no                         int          not null,
    employee_id                      bigint       not null,
    employee_code                    varchar(32)  not null,
    date_of_joining                  date         not null,
    basic_salary                     numeric(15,2) not null,
    no_of_months                     int          not null,
    percentage_of_salary             numeric(5,2)  not null,
    percentage_salary_amount         numeric(15,2) not null,
    no_of_days                       int          not null,
    deduction_as_long_term_advance   numeric(15,2) not null default 0,
    rfd_advance_added                numeric(15,2) not null default 0,
    net_amount                       numeric(15,2) not null,
    payment_mode                     varchar(16)   not null,
    status                           varchar(20)   not null,
    paid_at                          timestamp,
    created_at                       timestamp     not null default now(),
    updated_at                       timestamp     not null default now(),
    created_by                       varchar(64)   not null,
    updated_by                       varchar(64)   not null,
    ip_address                       inet,
    constraint fk_bonus_transaction_setting
        foreign key (fiscal_year_code, bonus_no)
        references bonus_no_settings (fiscal_year_code, bonus_no),
    constraint chk_bonus_transaction_percentage check (
        percentage_of_salary >= 0 and percentage_of_salary <= 100
    ),
    constraint chk_bonus_transaction_fy_bonus_employee unique (fiscal_year_code, bonus_no, employee_id),
    constraint chk_bonus_transaction_basic_salary check (basic_salary >= 0),
    constraint chk_bonus_transaction_percentage_salary_amount check (percentage_salary_amount >= 0),
    constraint chk_bonus_transaction_deduction check (deduction_as_long_term_advance >= 0),
    constraint chk_bonus_transaction_status check (status in ('DRAFT', 'PAID','HELD','RELEASE_PENDING','RELEASED')),
    constraint chk_bonus_transaction_payment_mode check (payment_mode in ('TRANSFER', 'CASH'))
);

create index idx_bonus_transaction_fy_bonus
    on bonus_transaction (fiscal_year_code, bonus_no);

create index idx_bonus_transaction_fy_bonus_employee
    on bonus_transaction (fiscal_year_code, bonus_no, employee_id);

create index idx_bonus_transaction_fy_bonus_employee_code
    on bonus_transaction (fiscal_year_code, bonus_no, employee_code);

create index idx_bonus_transaction_fy_bonus_status
    on bonus_transaction (fiscal_year_code, bonus_no, status);
