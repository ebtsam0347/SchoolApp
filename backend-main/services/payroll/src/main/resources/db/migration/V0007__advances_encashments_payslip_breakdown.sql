-- Three additions surfaced by the legacy WebHRMS payroll comparison:
--   1. Advances — both permanent (long-term loan, deducted in monthly
--      installments) and short-term (single-month / few-month deduction).
--      Heavy use in PK manufacturing — 580K+ legacy rows. Two-stage
--      approval (HR then Accounts), kept as flat columns on the row
--      rather than via a generic approval_steps table since payroll
--      already uses flat status models elsewhere (off_cycle_payments,
--      bonus_events, etc).
--   2. Annual leave encashment — payment for unused annual leaves
--      accrued by the employee.
--   3. Day-count breakdown on payslips — the working/paid/absent/
--      holiday/sunday counts that employees see on their payslip card,
--      plus the existing lop_days.
--
-- Money columns are bigint paisa (the unit-by-type convention from
-- CLAUDE.md). Request codes follow the per-year sequence pattern.

-- ---------------------------------------------------------------------
-- Per-year sequence allocator for advance / encashment request codes.
-- Same shape as attendance.request_code_sequence — keyed on
-- (request_type, year), upsert + RETURNING.
-- ---------------------------------------------------------------------

create table payroll_request_code_sequence (
    request_type varchar(24) not null,
    year         int         not null,
    last_value   int         not null default 0,
    primary key (request_type, year)
);

-- ---------------------------------------------------------------------
-- Permanent advances — long-term loan against future salary, with
-- gratuity / bonus / annual-leave-encashment as collateral. Deducted
-- monthly until balance reaches zero.
-- ---------------------------------------------------------------------

create table permanent_advances (
    id                       bigint generated by default as identity primary key,
    request_code             varchar(20)  not null unique,                -- PA-YYYY-NNNN
    employee_id              bigint       not null,
    amount                   bigint       not null,                       -- paisa, principal
    monthly_deduction        bigint       not null,                       -- paisa, regular monthly installment
    bonus_offset             bigint       not null default 0,             -- paisa, taken against bonus when paid
    annual_leave_offset      bigint       not null default 0,             -- paisa, taken against annual-leave encashment
    gratuity_at_request      bigint,                                      -- paisa, snapshot collateral check
    receiving_date           date,                                        -- when employee actually got the cash
    description              text,
    status                   varchar(24)  not null,                       -- PENDING | HR_APPROVED | APPROVED | REJECTED | DISBURSED | CLOSED | CANCELLED
    hr_decided_by            bigint,
    hr_decided_at            timestamptz,
    hr_note                  text,
    accounts_decided_by      bigint,
    accounts_decided_at      timestamptz,
    accounts_note            text,
    rejection_reason         text,
    closed_at                timestamptz,                                 -- set when remaining balance hits zero
    created_at               timestamptz  not null default now(),
    updated_at               timestamptz  not null default now(),
    created_by               varchar(64)  not null,
    updated_by               varchar(64)  not null,
    ip_address               inet,
    constraint chk_perm_adv_status check (status in (
        'PENDING','HR_APPROVED','APPROVED','REJECTED','DISBURSED','CLOSED','CANCELLED')),
    constraint chk_perm_adv_amount check (amount > 0),
    constraint chk_perm_adv_monthly check (monthly_deduction > 0)
);

create index idx_perm_advances_employee on permanent_advances (employee_id, status);
create index idx_perm_advances_open
    on permanent_advances (employee_id)
    where status in ('DISBURSED');

-- One row per applied monthly deduction. Payroll run iterates open
-- advances, computes the deduction (capped at monthly_deduction or
-- remaining_balance, whichever is smaller), inserts a row here, and
-- writes a matching payslip_line. Closes the parent advance when
-- remaining_balance hits zero.
create table permanent_advance_deductions (
    id                        bigint generated by default as identity primary key,
    advance_id                bigint       not null references permanent_advances(id),
    payroll_run_id            bigint       references payroll_runs(id),   -- nullable for manual entries
    deducted_amount           bigint       not null,                      -- paisa
    bonus_deduction           bigint       not null default 0,            -- paisa, taken against bonus this period
    annual_leave_deduction    bigint       not null default 0,            -- paisa, taken against AL encashment
    remaining_balance         bigint       not null,                      -- paisa, after this deduction
    transaction_date          date         not null,
    description               text,
    created_at                timestamptz  not null default now(),
    updated_at                timestamptz  not null default now(),
    created_by                varchar(64)  not null,
    updated_by                varchar(64)  not null,
    ip_address                inet,
    constraint chk_perm_adv_ded_amount check (deducted_amount > 0),
    constraint chk_perm_adv_ded_balance check (remaining_balance >= 0)
);

create index idx_perm_adv_ded_advance on permanent_advance_deductions (advance_id, transaction_date desc);
create index idx_perm_adv_ded_run     on permanent_advance_deductions (payroll_run_id);

-- ---------------------------------------------------------------------
-- Short-term advances. Cash advances raised by a department head on
-- behalf of N employees, deducted in full from a single target month's
-- payroll. The batch row holds the approval workflow + totals; one
-- detail row per employee.
-- ---------------------------------------------------------------------

create table short_term_advance_batches (
    id                       bigint generated by default as identity primary key,
    request_code             varchar(20)  not null unique,                -- STA-YYYY-NNNN
    department_id            bigint,                                      -- catalog FK in employee-service; not enforced cross-schema
    section_id               bigint,
    target_year              int          not null,
    target_month             int          not null,                       -- 1..12, the payroll month to deduct in
    total_amount             bigint       not null default 0,             -- paisa, sum of detail rows
    total_employees          int          not null default 0,
    status                   varchar(24)  not null,                       -- PENDING | HR_APPROVED | APPROVED | REJECTED | DISBURSED | CLOSED | CANCELLED
    hr_decided_by            bigint,
    hr_decided_at            timestamptz,
    hr_note                  text,
    accounts_decided_by      bigint,
    accounts_decided_at      timestamptz,
    accounts_note            text,
    rejection_reason         text,
    notes                    text,
    created_at               timestamptz  not null default now(),
    updated_at               timestamptz  not null default now(),
    created_by               varchar(64)  not null,
    updated_by               varchar(64)  not null,
    ip_address               inet,
    constraint chk_sta_batch_status check (status in (
        'PENDING','HR_APPROVED','APPROVED','REJECTED','DISBURSED','CLOSED','CANCELLED')),
    constraint chk_sta_batch_month  check (target_month between 1 and 12)
);

create index idx_sta_batches_status on short_term_advance_batches (status, target_year, target_month);

create table short_term_advances (
    id              bigint generated by default as identity primary key,
    batch_id        bigint       not null references short_term_advance_batches(id) on delete cascade,
    employee_id     bigint       not null,
    amount          bigint       not null,                                -- paisa
    target_year     int          not null,                                -- denormalized from batch for direct query
    target_month    int          not null,
    status          varchar(16)  not null,                                -- PENDING | APPROVED | REJECTED | DEDUCTED
    rejection_reason text,
    deducted_in_run_id bigint    references payroll_runs(id),
    created_at      timestamptz  not null default now(),
    updated_at      timestamptz  not null default now(),
    created_by      varchar(64)  not null,
    updated_by      varchar(64)  not null,
    ip_address      inet,
    constraint chk_sta_status check (status in ('PENDING','APPROVED','REJECTED','DEDUCTED')),
    constraint chk_sta_amount check (amount > 0),
    constraint chk_sta_month  check (target_month between 1 and 12),
    constraint uq_sta_batch_employee unique (batch_id, employee_id)
);

create index idx_sta_employee_month on short_term_advances (employee_id, target_year, target_month);
create index idx_sta_pending_run    on short_term_advances (target_year, target_month) where status = 'APPROVED';

-- ---------------------------------------------------------------------
-- Annual leave encashment. When HR / payroll cashes out unused annual
-- leaves, one row per (employee, calculation period). Paid via a
-- payroll_run (or off_cycle_payments — payroll_run_id stays null then).
-- ---------------------------------------------------------------------

create table leave_encashments (
    id                  bigint generated by default as identity primary key,
    employee_id         bigint       not null,
    calculation_month   date         not null,                            -- 1st of the period start month
    period_in_months    int          not null,                            -- usually 12 (annual cycle)
    days_encashed       numeric(5, 2) not null,
    basic_salary        bigint       not null,                            -- paisa, snapshot used for the calc
    amount              bigint       not null,                            -- paisa, days_encashed * (basic_salary / 26)
    payment_status      varchar(16)  not null,                            -- PENDING | PAID | CANCELLED
    paid_at             timestamptz,
    payroll_run_id      bigint       references payroll_runs(id),         -- non-null when paid via a regular run
    description         text,
    created_at          timestamptz  not null default now(),
    updated_at          timestamptz  not null default now(),
    created_by          varchar(64)  not null,
    updated_by          varchar(64)  not null,
    ip_address          inet,
    constraint chk_le_status check (payment_status in ('PENDING','PAID','CANCELLED')),
    constraint chk_le_amount check (amount >= 0),
    constraint chk_le_days   check (days_encashed > 0),
    constraint chk_le_period check (period_in_months > 0),
    constraint uq_le_employee_period unique (employee_id, calculation_month)
);

create index idx_le_employee on leave_encashments (employee_id, calculation_month desc);
create index idx_le_run on leave_encashments (payroll_run_id) where payroll_run_id is not null;

-- ---------------------------------------------------------------------
-- Payslip day-count breakdown. Already on payslips: lop_days, ot_hours,
-- ot_amount. Adding the rest of the breakdown shown to employees on
-- their payslip card.
-- ---------------------------------------------------------------------

alter table payslips
    add column working_days       int,
    add column paid_days          numeric(5, 2),
    add column absent_days        numeric(5, 2),
    add column holidays_in_period int,
    add column sundays_in_period  int;
