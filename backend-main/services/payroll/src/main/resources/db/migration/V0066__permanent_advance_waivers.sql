-- HR can waive one month's permanent-advance installment for an employee
-- (from the payroll-run skip drawer) without touching the advance's
-- monthly_deduction. Compute then writes a 0 SALARY row to the ledger for
-- that month and deducts nothing; the next month deducts as usual. The
-- waiver is keyed by period, not run, so a reset + recompute keeps it.
create table permanent_advance_waivers (
    id            bigint generated by default as identity primary key,
    employee_id   bigint       not null,
    period_year   int          not null,
    period_month  int          not null,
    created_at    timestamp    not null,
    updated_at    timestamp    not null,
    created_by    varchar(64)  not null,
    updated_by    varchar(64)  not null,
    ip_address    inet,
    constraint uq_perm_adv_waiver unique (employee_id, period_year, period_month),
    constraint chk_perm_adv_waiver_month check (period_month between 1 and 12)
);

-- The waived month's ledger row deducts 0.
alter table permanent_advance_deductions drop constraint chk_perm_adv_ded_amount;
alter table permanent_advance_deductions
    add constraint chk_perm_adv_ded_amount check (deducted_amount >= 0);
