-- Bank catalog. Each row is one bank where the company holds an account
-- (the company's account_number lives on the catalog row — payroll runs
-- read it as the disbursement source). Employees pick their own bank
-- from the same catalog via employee_bank_details.bank_id; the employee's
-- own account number stays on employee_bank_details.account_number.
--
-- Keeping employee bank info as free-text bank_name was a pre-impl
-- placeholder; swap it for the FK now before any data lands.

create table banks (
    id              bigint generated by default as identity primary key,
    code            varchar(32)  not null unique,
    name            varchar(128) not null,
    branch          varchar(128),
    address         varchar(255),
    account_title   varchar(128),
    iban            varchar(34),
    account_number  varchar(64),
    active          boolean      not null default true,
    created_at      timestamptz  not null default now(),
    updated_at      timestamptz  not null default now(),
    created_by      varchar(64)  not null,
    updated_by      varchar(64)  not null,
    ip_address      inet
);

alter table employee_bank_details
    drop column bank_name;

alter table employee_bank_details
    add column bank_id bigint not null references banks(id);

create index idx_employee_bank_details_bank on employee_bank_details (bank_id);
