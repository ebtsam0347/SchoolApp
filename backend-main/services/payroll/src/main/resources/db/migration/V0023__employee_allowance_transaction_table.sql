create table allowance_run
(
    id                  bigint generated by default as identity primary key,
    fiscal_year_code    varchar(7)   not null references fiscal_years(code),
    allowance_year      int          not null,
    allowance_month     int          not null,
    status              varchar(16)  not null,
    computed_at         timestamptz,
    approved_at         timestamptz,
    posted_at           timestamptz,
    approved_by         bigint,
    notes               text,
    skipped_count       int not null default 0,
    progress_count      int not null default 0,
    total_count         int not null default 0,
    created_at          timestamptz not null default now(),
    updated_at          timestamptz not null default now(),
    created_by          varchar(64) not null,
    updated_by          varchar(64) not null,
    ip_address          inet,

    constraint uq_allowance_run_period
        unique (fiscal_year_code, allowance_year, allowance_month),

    constraint chk_run_status check (
        status in ('DRAFT','LOCKED','COMPUTING','COMPUTED','APPROVED','POSTING','POSTED','FAILED','CANCELLED')
        ),

    constraint chk_run_month check (allowance_month between 1 and 12)
);

create index idx_allowance_run_month_year
    on allowance_run (allowance_year, allowance_month);


create table allowance_transaction
(
    id                            bigint generated by default as identity primary key,
    allowance_run_id              bigint not null references allowance_run(id),
    employee_id                   bigint not null,
    employee_code                 varchar(32)  not null,
    allowance_year                int not null,
    allowance_month               int not null,
    fiscal_year_code              varchar(7) not null,
    grade                         varchar(5) not null,
    employee_salary_component_id  bigint not null references employee_salary_components(id),
    amount                        bigint not null,
    pdf_object_key                varchar(512),
    generated_at                  timestamptz,
    status                        varchar(20) not null default 'PAID',
    held_reason                   text,
    created_at                    timestamptz not null default now(),
    updated_at                    timestamptz not null default now(),
    created_by                    varchar(64) not null,
    updated_by                    varchar(64) not null,
    ip_address                    inet,

    constraint uq_allowance_txn_run_emp_component
        unique (allowance_run_id, employee_id, employee_salary_component_id),

    constraint chk_allowance_transaction_status check (
        status in ('DRAFT', 'PAID','HELD','RELEASE_PENDING','RELEASED')
        )
);

create index idx_allow_txn_run_emp
    on allowance_transaction (allowance_run_id, employee_id);

alter table allowance_transaction
    add constraint chk_allowance_transaction_month check (allowance_month between 1 and 12);

create index idx_allowance_transaction_employee_month
    on allowance_transaction (employee_id, allowance_month desc, allowance_year desc);