create table rfd_advance (
    id                 bigint generated by default as identity primary key,
    amount             numeric(15,2) not null,
    employee_id        bigint        not null,
    transaction_state  varchar(32)   not null,
    transaction_date   date          not null,
    created_at         timestamp     not null default now(),
    updated_at         timestamp     not null default now(),
    created_by         varchar(64)   not null,
    updated_by         varchar(64)   not null,
    ip_address         inet,
    constraint chk_rfd_advance_amount check (amount >= 0)
);

create index idx_rfd_advance_employee_state_date
    on rfd_advance (employee_id, transaction_state, transaction_date);

create index idx_rfd_advance_state_date
    on rfd_advance (transaction_state, transaction_date);
