-- Payslips are now born DRAFT and flip to PAID inside the post step.
-- Carrying PAID at compute time conflated "intent to pay" with "actually
-- paid" and made the lifecycle unreviewable. Backfill: payslips on runs
-- that haven't reached POSTED revert to DRAFT; everything on POSTED runs
-- stays where it is.

alter table payroll.payslips drop constraint chk_payslip_status;
alter table payroll.payslips
    add constraint chk_payslip_status check (
        status in ('DRAFT','PAID','HELD','RELEASE_PENDING','RELEASED')
    );

alter table payroll.payslips alter column status set default 'DRAFT';

update payroll.payslips ps set status = 'DRAFT'
where ps.status = 'PAID'
  and exists (
      select 1 from payroll.payroll_runs r
      where r.id = ps.payroll_run_id and r.status <> 'POSTED'
  );

-- Compute skip surfacing. Records the per-employee reason a row was
-- excluded from a run so HR can fix the data and retry just those
-- employees instead of resetting the whole run. Cascade on run delete
-- because skip rows belong to the attempt, not the employee.

create table payroll.payroll_run_skips (
    id                  bigint generated by default as identity primary key,
    payroll_run_id      bigint       not null references payroll.payroll_runs(id) on delete cascade,
    employee_id         bigint       not null,
    employee_code       varchar(32)  not null,
    employee_full_name  varchar(255) not null,
    error_code          varchar(64)  not null,
    message             varchar(1000) not null,
    created_at          timestamptz  not null default now(),
    constraint uq_payroll_run_skips_run_emp unique (payroll_run_id, employee_id)
);

create index idx_payroll_run_skips_run on payroll.payroll_run_skips (payroll_run_id);

alter table payroll.payroll_runs add column skipped_count int not null default 0;
