-- Async-report substrate. One row per long-running report request:
-- POST /reports/<name>/jobs inserts QUEUED, the @Scheduled poller in the
-- service picks it up, runs the report, uploads to MinIO, flips status to
-- READY (or FAILED). GET /reports/jobs/{id} reads this row; the download
-- endpoint redirects to a signed URL on output_key. Audit row is emitted
-- alongside; this table is the queue, not the audit log.
--
-- Generic — all owning services use the same shape (payroll first, then
-- attendance / employee / leave). The `type` column is the discriminator
-- the runner switches on; `params` is the type-specific filter blob.

create table report_jobs (
    id            bigint generated by default as identity primary key,
    type          varchar(64)  not null,
    params        jsonb        not null default '{}'::jsonb,
    status        varchar(16)  not null,            -- QUEUED | RUNNING | READY | FAILED
    requested_by  varchar(64)  not null,
    created_at    timestamp    not null,
    updated_at    timestamp    not null,
    started_at    timestamp,
    completed_at  timestamp,
    output_key    varchar(512),                     -- MinIO object key when READY
    output_size   bigint,
    error_code    varchar(64),
    error_message varchar(2000),
    created_by    varchar(64)  not null,
    updated_by    varchar(64)  not null,
    ip_address    inet
);

create index idx_report_jobs_status_created on report_jobs (status, created_at);
create index idx_report_jobs_type_created on report_jobs (type, created_at desc);
create index idx_report_jobs_requested_by_created on report_jobs (requested_by, created_at desc);
