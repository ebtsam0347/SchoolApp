values
    ('PERMANENT_ADVANCE',  1, 'PERMISSION', 'payroll.advance.hr',       'HR Approval',       'system', 'system'),
    ('PERMANENT_ADVANCE',  2, 'PERMISSION', 'payroll.advance.accounts', 'Accounts Approval', 'system', 'system'),
    ('SHORT_TERM_ADVANCE', 1, 'PERMISSION', 'payroll.advance.hr',       'HR Approval',       'system', 'system'),
    ('SHORT_TERM_ADVANCE', 2, 'PERMISSION', 'payroll.advance.accounts', 'Accounts Approval', 'system', 'system');

-- Backfill approval_steps for every existing row so in-flight/decided
-- advances keep their HR/Accounts decision history once the hand-rolled
-- columns are dropped below. Status mapping ports the exact stepsDto()
-- logic from PermanentAdvanceService/ShortTermAdvanceService into SQL.
insert into approval_steps
    (request_type, request_id, stage_no, resolver_kind, approve_permission, label,
     assigned_to, status, decided_by, decided_at, note, created_at, updated_at, created_by, updated_by)
select
    'PERMANENT_ADVANCE', id, 1, 'PERMISSION', 'payroll.advance.hr', 'HR Approval',
    null::bigint,
    case
        when status = 'REJECTED' and accounts_decided_at is null then 'REJECTED'
        -- status can only reach these values by having passed HR approval —
        -- trust status over hr_decided_at so a row whose decided_at somehow
        -- wasn't recorded doesn't wrongly resurface as still-PENDING.
        when status in ('HR_APPROVED', 'APPROVED', 'DISBURSED', 'CLOSED') or hr_decided_at is not null then 'APPROVED'
        when status = 'CANCELLED' then 'SKIPPED'
        else 'PENDING'
    end,
    hr_decided_by, hr_decided_at, hr_note,
    created_at, coalesce(hr_decided_at, created_at), 'migration', 'migration'
from permanent_advances
union all
select
    'PERMANENT_ADVANCE', id, 2, 'PERMISSION', 'payroll.advance.accounts', 'Accounts Approval',
    null::bigint,
    case
        when status = 'REJECTED' and accounts_decided_at is not null then 'REJECTED'
        when status in ('APPROVED', 'DISBURSED', 'CLOSED') or accounts_decided_at is not null then 'APPROVED'
        when (status = 'REJECTED' and accounts_decided_at is null) or status = 'CANCELLED' then 'SKIPPED'
        when status = 'HR_APPROVED' then 'PENDING'
        else 'NOT_YET'
    end,
    accounts_decided_by, accounts_decided_at, accounts_note,
    created_at, coalesce(accounts_decided_at, created_at), 'migration', 'migration'
from permanent_advances;

