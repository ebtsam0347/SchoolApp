-- Moves permanent-advance / short-term-advance-batch approvals onto the
-- shared commons-approval engine (same tables attendance/employee already
-- use). Payroll has neither approval_workflow_stage nor approval_steps yet,
-- and this migration (V0038) runs before commons-approval's own V0510, so
-- both tables are pre-created here `if not exists` — same technique as
-- employee's V0013__requisition_approval_workflow.sql. Shape matches
-- V0510__commons_approval_schema.sql + V0511's resolver_target column
-- so those later commons migrations no-op cleanly.

create table if not exists approval_workflow_stage (
    id                 bigint generated by default as identity primary key,
    request_type       varchar(24) not null,
    stage_no           int         not null,
    resolver_kind      varchar(16) not null,
    approve_permission varchar(64),
    resolver_target    varchar(64),
    label              varchar(48) not null,
    active             boolean     not null default true,
    created_at         timestamp   not null default now(),
    updated_at         timestamp   not null default now(),
    created_by         varchar(64) not null,
    updated_by         varchar(64) not null,
    ip_address         inet
);

create unique index if not exists uq_workflow_stage_active
    on approval_workflow_stage (request_type, stage_no) where active;

create table if not exists approval_steps (
    id                 bigint generated by default as identity primary key,
    request_type       varchar(24)  not null,
    request_id         bigint       not null,
    stage_no           int          not null,
    resolver_kind      varchar(16)  not null,
    approve_permission varchar(64),
    resolver_target    varchar(64),
    label              varchar(48)  not null,
    assigned_to        bigint,
    status             varchar(16)  not null,
    decided_by         bigint,
    decided_at         timestamp,
    note               text,
    created_at         timestamp  not null default now(),
    updated_at         timestamp  not null default now(),
    created_by         varchar(64)  not null,
    updated_by         varchar(64)  not null,
    ip_address         inet
);

create index if not exists idx_steps_assignee_pending
    on approval_steps (request_type, assigned_to)
    where assigned_to is not null and status = 'PENDING';

create index if not exists idx_steps_roleonly_pending
    on approval_steps (request_type, status)
    where assigned_to is null and status = 'PENDING';

create index if not exists idx_steps_by_decider
    on approval_steps (decided_by, decided_at)
    where decided_by is not null;

-- 2-stage chain, both PERMISSION-kind (advances aren't tied to org
-- hierarchy, so no MANAGER/DEPARTMENT_HEAD/GRADE stages needed).
insert into approval_workflow_stage
