-- payroll-service schema. Lives in the `payroll` Postgres schema.
-- Audit columns on every business entity; bridge tables, system tables
-- (saga_state, outbox) are exempt.
--
-- Money columns are stored as bigint paisa (the 2nd decimal of PKR).
-- No `_paisa` suffix on column names — the type tells you the unit.

-- ---------------------------------------------------------------------
-- System-level reference tables: fiscal year + statutory rates.
-- ---------------------------------------------------------------------

create table fiscal_years (
    code         varchar(7)   primary key,                      -- e.g. "2025-26"
    start_date   date         not null,                         -- typically Jul 1
    end_date     date         not null,                         -- typically Jun 30
    status       varchar(16)  not null,
    created_at   timestamptz  not null default now(),
    updated_at   timestamptz  not null default now(),
    created_by   varchar(64)  not null,
    updated_by   varchar(64)  not null,
    ip_address   inet,
    constraint chk_fy_status check (status in ('CLOSED','CURRENT','FUTURE')),
    constraint chk_fy_dates  check (end_date > start_date)
);

-- Exactly one row may have status='CURRENT'.
create unique index uq_fiscal_years_current
    on fiscal_years (status)
    where status = 'CURRENT';

create table statutory_config (
    id                                     bigint generated by default as identity primary key,
    effective_from                         date         not null,
    effective_to                           date,
    eobi_amount                            bigint       not null,
    pessi_rate_percent                     numeric(5,2) not null,
    pessi_salary_cap                       bigint       not null,
    gratuity_min_service_months            int          not null default 12,
    gratuity_partial_year_threshold_months int          not null default 6,
    notes                                  text,
    created_at                             timestamptz  not null default now(),
    updated_at                             timestamptz  not null default now(),
    created_by                             varchar(64)  not null,
    updated_by                             varchar(64)  not null,
    ip_address                             inet,
    constraint chk_stat_dates check (effective_to is null or effective_to > effective_from)
);

create index idx_statutory_effective on statutory_config (effective_from desc);

-- ---------------------------------------------------------------------
-- Salary component catalog. There is no salary structure / template:
-- every employee is `basic` plus a per-employee selection from this
-- catalog. All amounts are flat (no percentage, no formula).
-- ---------------------------------------------------------------------

create table salary_components (
    id              bigint generated by default as identity primary key,
    code            varchar(32)  not null unique,
    name            varchar(64)  not null,
    type            varchar(16)  not null,
    calc_type       varchar(16)  not null default 'FLAT',
    default_amount  bigint,
    display_order   int          not null default 0,
    active          boolean      not null default true,
    created_at      timestamptz  not null default now(),
    updated_at      timestamptz  not null default now(),
    created_by      varchar(64)  not null,
    updated_by      varchar(64)  not null,
    ip_address      inet,
    constraint chk_comp_type      check (type in ('EARNING','DEDUCTION')),
    constraint chk_comp_calc_type check (calc_type in ('FLAT','PER_DAY')),
    -- per-day deductions don't model anything real
    constraint chk_comp_per_day_only_earning
        check (calc_type = 'FLAT' or type = 'EARNING')
);

-- ---------------------------------------------------------------------
-- Per-employee salary tables. FK columns are plain bigint (no
-- @ManyToOne); the service layer looks up employees in employee-service
-- when validation requires it.
-- ---------------------------------------------------------------------

create table employee_salaries (
    id              bigint generated by default as identity primary key,
    employee_id     bigint       not null,
    basic           bigint       not null,
    effective_from  date         not null,
    effective_to    date,
    revision_reason text,
    created_at      timestamptz  not null default now(),
    updated_at      timestamptz  not null default now(),
    created_by      varchar(64)  not null,
    updated_by      varchar(64)  not null,
    ip_address      inet,
    constraint chk_salary_basic check (basic >= 0),
    constraint chk_salary_dates check (effective_to is null or effective_to >= effective_from)
);

create index idx_emp_salaries_history on employee_salaries (employee_id, effective_from desc);
create unique index uq_emp_salaries_current
    on employee_salaries (employee_id)
    where effective_to is null;

create table employee_salary_components (
    id              bigint generated by default as identity primary key,
    employee_id     bigint       not null,
    component_id    bigint       not null references salary_components(id),
    amount          bigint       not null,
    effective_from  date         not null,
    effective_to    date,
    notes           text,
    created_at      timestamptz  not null default now(),
    updated_at      timestamptz  not null default now(),
    created_by      varchar(64)  not null,
    updated_by      varchar(64)  not null,
    ip_address      inet,
    constraint chk_emp_comp_amount check (amount >= 0),
    constraint chk_emp_comp_dates  check (effective_to is null or effective_to >= effective_from)
);

create index idx_emp_comp_history     on employee_salary_components (employee_id, effective_from desc);
create index idx_emp_comp_current     on employee_salary_components (employee_id) where effective_to is null;
create index idx_emp_comp_component   on employee_salary_components (component_id);

-- ---------------------------------------------------------------------
-- Per-employee payroll settings + bank details.
-- ---------------------------------------------------------------------

create table employee_payroll_settings (
    id            bigint generated by default as identity primary key,
    employee_id   bigint       not null unique,
    hire_date     date         not null,
    eobi_enrolled boolean      not null default false,
    payment_mode  varchar(16)  not null default 'BANK_TRANSFER',
    created_at    timestamptz  not null default now(),
    updated_at    timestamptz  not null default now(),
    created_by    varchar(64)  not null,
    updated_by    varchar(64)  not null,
    ip_address    inet,
    constraint chk_payment_mode check (payment_mode in ('CASH','BANK_TRANSFER'))
);

create table employee_bank_details (
    id             bigint generated by default as identity primary key,
    employee_id    bigint       not null unique,
    bank_name      varchar(128) not null,
    branch         varchar(128),
    account_title  varchar(128) not null,
    iban           varchar(34)  not null,
    account_number varchar(64),
    created_at     timestamptz  not null default now(),
    updated_at     timestamptz  not null default now(),
    created_by     varchar(64)  not null,
    updated_by     varchar(64)  not null,
    ip_address     inet
);

-- ---------------------------------------------------------------------
-- Payroll runs + payslips.
-- ---------------------------------------------------------------------

create table payroll_runs (
    id                bigint generated by default as identity primary key,
    fiscal_year_code  varchar(7)   not null references fiscal_years(code),
    period_year       int          not null,
    period_month      int          not null,
    status            varchar(16)  not null,
    attendance_locked boolean      not null default false,
    computed_at       timestamptz,
    approved_at       timestamptz,
    posted_at         timestamptz,
    approved_by       bigint,
    notes             text,
    created_at        timestamptz  not null default now(),
    updated_at        timestamptz  not null default now(),
    created_by        varchar(64)  not null,
    updated_by        varchar(64)  not null,
    ip_address        inet,
    constraint uq_payroll_runs_period unique (period_year, period_month),
    constraint chk_run_status check (
        status in ('DRAFT','LOCKED','COMPUTING','COMPUTED','APPROVED','POSTING','POSTED','FAILED','CANCELLED')
    ),
    constraint chk_run_month check (period_month between 1 and 12)
);

create index idx_payroll_runs_fy on payroll_runs (fiscal_year_code);

create table payslips (
    id                  bigint generated by default as identity primary key,
    payroll_run_id      bigint       not null references payroll_runs(id),
    employee_id         bigint       not null,
    employee_code       varchar(32)  not null,
    basic               bigint       not null,
    allowances          bigint       not null,
    gross               bigint       not null,
    deductions          bigint       not null,
    tax                 bigint       not null,
    eobi                bigint       not null,
    pessi_employer      bigint       not null,
    net                 bigint       not null,
    lop_days            numeric(5,2) not null default 0,
    ot_hours            numeric(5,2) not null default 0,
    ot_amount           bigint       not null default 0,
    pdf_object_key      varchar(512),
    generated_at        timestamptz,
    status              varchar(20)  not null default 'PAID',
    held_reason         text,
    released_in_run_id  bigint references payroll_runs(id),
    created_at          timestamptz  not null default now(),
    updated_at          timestamptz  not null default now(),
    created_by          varchar(64)  not null,
    updated_by          varchar(64)  not null,
    ip_address          inet,
    constraint uq_payslips_run_employee unique (payroll_run_id, employee_id),
    constraint chk_payslip_status check (
        status in ('PAID','HELD','RELEASE_PENDING','RELEASED')
    )
);

create index idx_payslips_employee_generated
    on payslips (employee_id, generated_at desc);
create index idx_payslips_held
    on payslips (status)
    where status in ('HELD','RELEASE_PENDING');
create index idx_payslips_released_run
    on payslips (released_in_run_id)
    where released_in_run_id is not null;

create table payslip_lines (
    id            bigint generated by default as identity primary key,
    payslip_id    bigint       not null references payslips(id) on delete cascade,
    component_id  bigint       references salary_components(id),
    code          varchar(32)  not null,
    name          varchar(64)  not null,
    type          varchar(16)  not null,
    calc_type     varchar(16)  not null default 'FLAT',
    rate          bigint,
    days          int,
    amount        bigint       not null,
    display_order int          not null default 0,
    created_at    timestamptz  not null default now(),
    updated_at    timestamptz  not null default now(),
    created_by    varchar(64)  not null,
    updated_by    varchar(64)  not null,
    ip_address    inet,
    constraint chk_line_type      check (type in ('EARNING','DEDUCTION')),
    constraint chk_line_calc_type check (calc_type in ('FLAT','PER_DAY'))
);

create index idx_payslip_lines_payslip on payslip_lines (payslip_id, display_order);

-- ---------------------------------------------------------------------
-- Off-cycle payments (cash extras, special OT, ad-hoc bonuses, eid
-- bonus installment apply rows).
-- ---------------------------------------------------------------------

create table bonus_events (
    id                          bigint generated by default as identity primary key,
    fiscal_year_code            varchar(7)   not null references fiscal_years(code),
    name                        varchar(128) not null,
    event_type                  varchar(32)  not null,
    reference_date              date         not null,
    full_service_days_threshold int          not null default 365,
    status                      varchar(16)  not null,
    notes                       text,
    activated_at                timestamptz,
    activated_by                bigint,
    created_at                  timestamptz  not null default now(),
    updated_at                  timestamptz  not null default now(),
    created_by                  varchar(64)  not null,
    updated_by                  varchar(64)  not null,
    ip_address                  inet,
    constraint chk_bonus_event_type   check (event_type in ('EID_UL_FITR','EID_UL_ADHA','OTHER')),
    constraint chk_bonus_event_status check (status in ('DRAFT','ACTIVE','CLOSED'))
);

create index idx_bonus_events_fy on bonus_events (fiscal_year_code);
-- At most one event per Eid type per FY (HR can use OTHER for irregulars).
create unique index uq_bonus_events_fy_type
    on bonus_events (fiscal_year_code, event_type)
    where event_type in ('EID_UL_FITR','EID_UL_ADHA');

create table bonus_event_amounts (
    id              bigint generated by default as identity primary key,
    bonus_event_id  bigint       not null references bonus_events(id) on delete cascade,
    employee_id     bigint       not null,
    hire_date       date         not null,
    service_days    int          not null,
    basic_snapshot  bigint       not null,
    full_bonus      bigint       not null,
    created_at      timestamptz  not null default now(),
    updated_at      timestamptz  not null default now(),
    created_by      varchar(64)  not null,
    updated_by      varchar(64)  not null,
    ip_address      inet,
    constraint uq_bonus_event_amounts unique (bonus_event_id, employee_id)
);

create index idx_bonus_event_amounts_employee on bonus_event_amounts (employee_id);

create table bonus_installments (
    id              bigint generated by default as identity primary key,
    bonus_event_id  bigint       not null references bonus_events(id) on delete cascade,
    installment_no  int          not null,
    percentage      numeric(5,2) not null,
    paid_on         date         not null,
    status          varchar(16)  not null,
    applied_at      timestamptz,
    applied_by      bigint,
    created_at      timestamptz  not null default now(),
    updated_at      timestamptz  not null default now(),
    created_by      varchar(64)  not null,
    updated_by      varchar(64)  not null,
    ip_address      inet,
    constraint uq_bonus_installments unique (bonus_event_id, installment_no),
    constraint chk_bonus_installment_status check (status in ('DRAFT','APPLIED')),
    constraint chk_bonus_installment_pct    check (percentage > 0 and percentage <= 100)
);

create table off_cycle_payments (
    id                     bigint generated by default as identity primary key,
    employee_id            bigint       not null,
    paid_on                date         not null,
    amount                 bigint       not null,
    category               varchar(32)  not null,
    reason                 text         not null,
    payment_mode           varchar(16)  not null,
    reference_no           varchar(64),
    source_event_id        bigint       references bonus_events(id),
    source_installment_id  bigint       references bonus_installments(id),
    created_at             timestamptz  not null default now(),
    updated_at             timestamptz  not null default now(),
    created_by             varchar(64)  not null,
    updated_by             varchar(64)  not null,
    ip_address             inet,
    constraint chk_ocp_amount       check (amount > 0),
    constraint chk_ocp_category     check (category in ('EXTRA','SPECIAL_OT','BONUS','OTHER')),
    constraint chk_ocp_payment_mode check (payment_mode in ('CASH','BANK','OTHER')),
    constraint chk_ocp_source       check (
        (source_event_id is null and source_installment_id is null)
     or (source_event_id is not null and source_installment_id is not null)
    )
);

create index idx_ocp_employee   on off_cycle_payments (employee_id, paid_on desc);
create index idx_ocp_paid_on    on off_cycle_payments (paid_on);
create index idx_ocp_category   on off_cycle_payments (category);
create index idx_ocp_event      on off_cycle_payments (source_event_id);

-- ---------------------------------------------------------------------
-- Increment batches — bulk basic-salary revisions (annual cycle, mid-
-- year adjustments, one-off promotions).
-- ---------------------------------------------------------------------

create table increment_batches (
    id              bigint generated by default as identity primary key,
    name            varchar(128) not null,
    status          varchar(16)  not null,
    effective_from  date         not null,
    source_filename varchar(256),
    notes           text,
    applied_at      timestamptz,
    applied_by      bigint,
    created_at      timestamptz  not null default now(),
    updated_at      timestamptz  not null default now(),
    created_by      varchar(64)  not null,
    updated_by      varchar(64)  not null,
    ip_address      inet,
    constraint chk_inc_batch_status check (status in ('DRAFT','APPLIED','CANCELLED'))
);

create table increment_batch_lines (
    id              bigint generated by default as identity primary key,
    batch_id        bigint       not null references increment_batches(id) on delete cascade,
    employee_id     bigint       not null,
    old_basic       bigint       not null,
    new_basic       bigint       not null,
    old_income_tax  bigint,
    new_income_tax  bigint,
    effective_from  date,
    status          varchar(16)  not null,
    error_message   text,
    created_at      timestamptz  not null default now(),
    updated_at      timestamptz  not null default now(),
    created_by      varchar(64)  not null,
    updated_by      varchar(64)  not null,
    ip_address      inet,
    constraint uq_inc_batch_lines unique (batch_id, employee_id),
    constraint chk_inc_line_status check (status in ('VALID','ERROR','APPLIED'))
);

create index idx_inc_batch_lines_batch    on increment_batch_lines (batch_id);
create index idx_inc_batch_lines_employee on increment_batch_lines (employee_id, batch_id);
