-- Web Push (RFC 8030 / 8291) browser subscriptions — one row per browser
-- profile that pressed "Allow". `endpoint` is the push-service URL the
-- browser handed us and is globally unique, so a second user signing in on
-- the same (shared office) browser re-binds the row instead of adding one.
-- Rows are removed when the user turns push off or signs out, and when the
-- push service answers 404/410 (the browser dropped the subscription).

create table push_subscriptions (
    id          bigint generated by default as identity primary key,
    user_id     bigint        not null,
    endpoint    varchar(1024) not null,
    p256dh      varchar(128)  not null,   -- browser ECDH public key, base64url
    auth        varchar(64)   not null,   -- browser auth secret, base64url
    user_agent  varchar(512),
    -- audit
    created_at  timestamp     not null default now(),
    updated_at  timestamp     not null default now(),
    created_by  varchar(64)   not null,
    updated_by  varchar(64)   not null,
    ip_address  inet,
    constraint uq_push_subscriptions_endpoint unique (endpoint)
);

create index idx_push_subscriptions_user on push_subscriptions (user_id);
