-- notification-service schema. Lives in the `notification` Postgres schema
-- (set via spring.flyway.default-schema). See docs/services/notification.md.
--
-- notifications + notification_templates are business entities and carry
-- the standard audit columns. notification_preferences is a bridge
-- (per-user-per-type toggle) and is exempt.

create table notifications (
    id              bigint generated by default as identity primary key,
    user_id         bigint       not null,                    -- recipient
    type            varchar(64)  not null,                    -- e.g. LEAVE_APPLIED, PAYSLIP_READY
    title           varchar(255) not null,
    body            text,
    link            varchar(512),                             -- deep link path
    payload         jsonb,                                    -- entityType/entityId + summary
    category        varchar(32),                              -- APPROVAL | ANNOUNCEMENT | SYSTEM | PAYROLL
    priority        varchar(16)  not null default 'NORMAL',   -- LOW | NORMAL | HIGH
    read_at         timestamptz,
    -- audit
    created_at      timestamptz  not null default now(),
    updated_at      timestamptz  not null default now(),
    created_by      varchar(64)  not null,
    updated_by      varchar(64)  not null,
    ip_address      inet
);

-- bell feed
create index idx_notifications_user_created
    on notifications (user_id, created_at desc);

-- partial index for unread queries / unread-count
create index idx_notifications_user_unread
    on notifications (user_id)
    where read_at is null;

create table notification_templates (
    id          bigint generated by default as identity primary key,
    type        varchar(64)  not null unique,
    title_tpl   text         not null,                        -- "{{actorName}} approved your leave"
    body_tpl    text,
    link_tpl    varchar(512),                                 -- "/leaves/{{requestId}}"
    category    varchar(32),
    active      boolean      not null default true,
    -- audit
    created_at  timestamptz  not null default now(),
    updated_at  timestamptz  not null default now(),
    created_by  varchar(64)  not null,
    updated_by  varchar(64)  not null,
    ip_address  inet
);

-- bridge: per-user opt-out per type. No audit columns by convention.
create table notification_preferences (
    user_id  bigint       not null,
    type     varchar(64)  not null,
    enabled  boolean      not null default true,
    primary key (user_id, type)
);

-- Idempotent ingest of cross-service Kafka events. We additionally cache
-- the eventId in Redis with a TTL (cheap dedupe), but the table is the
-- durable backstop — the unique constraint guards against double inserts
-- that would still slip past Redis (e.g. cache eviction during a redrive).
create table notification_processed_events (
    event_id      varchar(64)  not null primary key,
    source_topic  varchar(64)  not null,
    event_type    varchar(64)  not null,
    processed_at  timestamptz  not null default now()
);
