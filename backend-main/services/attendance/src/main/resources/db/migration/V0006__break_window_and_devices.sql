-- Two changes from the legacy WebHRMS comparison:
--   1. Break is stored as a window (break_start_time / break_end_time)
--      instead of a duration. The duration is derived in code
--      (Shift.getBreakMinutes() etc). Same shape on attendance_records
--      and attendance_shift_overrides where the shift is snapshotted.
--   2. Biometric devices are catalogued. attendance_punches.device_id
--      goes from free-text varchar(64) to a bigint FK.

-- ---------------------------------------------------------------------
-- Break window on shifts + every place we snapshot it.
-- ---------------------------------------------------------------------

alter table shifts
    drop column break_minutes;
alter table shifts
    add column break_start_time time,
    add column break_end_time   time;

alter table attendance_records
    drop column shift_break_minutes;
alter table attendance_records
    add column shift_break_start_time time,
    add column shift_break_end_time   time;

alter table attendance_shift_overrides
    drop column shift_break_minutes;
alter table attendance_shift_overrides
    add column shift_break_start_time time not null,
    add column shift_break_end_time   time not null;

-- ---------------------------------------------------------------------
-- Devices catalog + FK swap on attendance_punches.
-- ---------------------------------------------------------------------

create table attendance_devices (
    id          bigint generated by default as identity primary key,
    code        varchar(32)  not null unique,
    name        varchar(128) not null,
    location    varchar(128),
    device_ip   inet,
    active      boolean      not null default true,
    created_at  timestamptz  not null default now(),
    updated_at  timestamptz  not null default now(),
    created_by  varchar(64)  not null,
    updated_by  varchar(64)  not null,
    ip_address  inet
);

alter table attendance_punches
    drop column device_id;
alter table attendance_punches
    add column device_id bigint references attendance_devices(id);

create index idx_punches_device
    on attendance_punches (device_id, punched_at)
    where device_id is not null;
