-- Device snapshots: HR-triggered "dump everything on this device" — the
-- service queues a SNAPSHOT_DEVICE sync task; the poller dials the
-- device, captures device_info / users / attendance, and posts the
-- payload back via /finalize. Stored as jsonb so the FE can render the
-- dump in a viewer or download it as JSON.
--
-- Sizing: ZK readers in this deployment hold ≤ 5k records and a few
-- hundred users; payloads stay well under 1 MB per snapshot. jsonb is
-- the right column type — text would skip the validate-on-write that
-- catches malformed payloads from a misbehaving poller.

create table attendance_device_snapshots (
    id            bigint      generated by default as identity primary key,
    device_id     bigint      not null references attendance_devices(id),
    sync_task_id  bigint      references attendance_device_sync_tasks(id),
    status        varchar(16) not null default 'PENDING',
    requested_by  varchar(64) not null,
    completed_at  timestamp,
    device_info   jsonb,
    users         jsonb,
    attendance    jsonb,
    user_count    int,
    record_count  int,
    error         text,
    created_at    timestamp   not null default current_timestamp,
    updated_at    timestamp   not null default current_timestamp,
    created_by    varchar(64) not null,
    updated_by    varchar(64) not null,
    ip_address    inet
);

-- "list snapshots for this device, newest first" — the FE list view.
create index idx_device_snapshots_device
    on attendance_device_snapshots (device_id, created_at desc);

-- Open-snapshot lookup (poller finalize hits this row, HR retries).
create index idx_device_snapshots_status
    on attendance_device_snapshots (status)
    where status = 'PENDING';
