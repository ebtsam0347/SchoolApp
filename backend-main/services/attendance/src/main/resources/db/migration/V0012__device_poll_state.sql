-- Move the attendance-poller's local state into the service so the
-- poller can be a stateless container. Two pieces:
--
--   1. attendance_device_poll_state — one row per device, holds the
--      high-water-mark timestamp the poller filters against. Replaces
--      ~/.attendance-poller/state.json on the poller side.
--
--   2. attendance_punch_unmatched — queue of biometric punches whose
--      (device_id, card_number) had no row in attendance_device_users
--      at ingest time. Replaces the poller's in-memory retry buffer.
--      A scheduled job in attendance-service replays them whenever a
--      bridge row catches up; rows past max_attempts are dropped + audited.

create table attendance_device_poll_state (
    device_id        bigint      primary key references attendance_devices(id) on delete cascade,
    last_punched_at  timestamp,
    created_at       timestamp   not null default current_timestamp,
    updated_at       timestamp   not null default current_timestamp,
    created_by       varchar(64) not null,
    updated_by       varchar(64) not null,
    ip_address       inet
);

create table attendance_punch_unmatched (
    id              bigint      generated by default as identity primary key,
    device_id       bigint      not null references attendance_devices(id) on delete cascade,
    card_number     varchar(32) not null,
    punched_at      timestamp   not null,
    attempts        int         not null default 0,
    first_seen_at   timestamp   not null default current_timestamp,
    last_attempt_at timestamp,
    created_at      timestamp   not null default current_timestamp,
    updated_at      timestamp   not null default current_timestamp,
    created_by      varchar(64) not null,
    updated_by      varchar(64) not null,
    ip_address      inet,
    unique (device_id, card_number, punched_at)
);

-- Replay job filters by card_number to find rows whose bridge entry
-- has just been added. Index supports that lookup; the unique key
-- already covers per-device pruning.
create index idx_punch_unmatched_card
    on attendance_punch_unmatched (card_number);
