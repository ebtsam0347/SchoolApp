-- attendance-service schema. Lives in the `attendance` Postgres schema
-- (set via spring.flyway.default-schema). Audit columns on every business
-- entity; bridge tables, system tables (saga_state, outbox) are exempt.
--
-- See docs/services/attendance.md for the per-table commentary; the
-- migration mirrors it line-by-line so reviewers can diff doc to DDL.

-- ---------------------------------------------------------------------
-- Shifts + per-employee assignments + operator overrides.
-- ---------------------------------------------------------------------

create table shifts (
    id                    bigint generated by default as identity primary key,
    code                  varchar(32)  not null unique,
    name                  varchar(64)  not null,
    start_time            time         not null,
    end_time              time         not null,
    break_minutes         int          not null default 60,
    grace_minutes         int          not null default 10,
    friday_extra_minutes  int          default 0,
    active                boolean      not null default true,
    created_at            timestamptz  not null default now(),
    updated_at            timestamptz  not null default now(),
    created_by            varchar(64)  not null,
    updated_by            varchar(64)  not null,
    ip_address            inet
);

create table employee_shifts (
    id              bigint generated by default as identity primary key,
    employee_id     bigint       not null,
    shift_id        bigint       not null references shifts(id),
    effective_from  date         not null,
    effective_to    date,
    created_at      timestamptz  not null default now(),
    updated_at      timestamptz  not null default now(),
    created_by      varchar(64)  not null,
    updated_by      varchar(64)  not null,
    ip_address      inet,
    unique (employee_id, effective_from)
);

create index idx_employee_shifts_employee on employee_shifts (employee_id, effective_from desc);

create table attendance_shift_overrides (
    id                  bigint generated by default as identity primary key,
    employee_id         bigint       not null,
    from_date           date         not null,
    to_date             date         not null,
    shift_start_time    time         not null,
    shift_end_time      time         not null,
    shift_break_minutes int          not null,
    shift_grace_minutes int          not null,
    reason              text,
    created_at          timestamptz  not null default now(),
    updated_at          timestamptz  not null default now(),
    created_by          varchar(64)  not null,
    updated_by          varchar(64)  not null,
    ip_address          inet,
    check (to_date >= from_date)
);

create index idx_shift_overrides_employee on attendance_shift_overrides (employee_id, from_date, to_date);

-- ---------------------------------------------------------------------
-- Punches + daily attendance projection.
-- ---------------------------------------------------------------------

create table attendance_punches (
    id              bigint generated by default as identity primary key,
    employee_id     bigint       not null,
    punched_at      timestamptz  not null,
    attendance_date date         not null,
    source          varchar(16)  not null,
    device_id       varchar(64),
    reason          text,
    created_at      timestamptz  not null default now(),
    updated_at      timestamptz  not null default now(),
    created_by      varchar(64)  not null,
    updated_by      varchar(64)  not null,
    ip_address      inet,
    unique (employee_id, punched_at)
);

create index idx_punches_emp_date on attendance_punches (employee_id, attendance_date, punched_at);

create table attendance_records (
    id                   bigint generated by default as identity primary key,
    employee_id          bigint       not null,
    attendance_date      date         not null,
    check_in             timestamptz,
    check_out            timestamptz,
    effective_shift      bigint       references shifts(id),
    shift_start_time     time,
    shift_end_time       time,
    shift_break_minutes  int,
    shift_grace_minutes  int,
    status               varchar(16)  not null,
    late_minutes         int          default 0,
    early_minutes        int          default 0,
    worked_minutes       int          default 0,
    ot_normal_minutes    int          default 0,
    ot_extra_minutes     int          default 0,
    ot_special_minutes   int          default 0,
    source               varchar(16),
    notes                text,
    created_at           timestamptz  not null default now(),
    updated_at           timestamptz  not null default now(),
    created_by           varchar(64)  not null,
    updated_by           varchar(64)  not null,
    ip_address           inet,
    unique (employee_id, attendance_date)
);

create index idx_records_date_status on attendance_records (attendance_date, status);

-- ---------------------------------------------------------------------
-- Holidays + leave catalog + balances.
-- ---------------------------------------------------------------------

create table holidays (
    id           bigint generated by default as identity primary key,
    holiday_date date         not null,
    name         varchar(128) not null,
    type         varchar(16)  not null,
    description  text,
    created_at   timestamptz  not null default now(),
    updated_at   timestamptz  not null default now(),
    created_by   varchar(64)  not null,
    updated_by   varchar(64)  not null,
    ip_address   inet,
    unique (holiday_date, type)
);

create index idx_holidays_date on holidays (holiday_date);

create table leave_types (
    id                 bigint generated by default as identity primary key,
    code               varchar(32)  not null unique,
    name               varchar(64)  not null,
    paid               boolean      not null default true,
    default_per_year   numeric(5,2) not null,
    accrual_rule       varchar(16)  not null,
    carry_forward_max  numeric(5,2) default 0,
    requires_approval  boolean      not null default true,
    active             boolean      not null default true,
    created_at         timestamptz  not null default now(),
    updated_at         timestamptz  not null default now(),
    created_by         varchar(64)  not null,
    updated_by         varchar(64)  not null,
    ip_address         inet
);

create table leave_balances (
    id             bigint generated by default as identity primary key,
    employee_id    bigint       not null,
    leave_type_id  bigint       not null references leave_types(id),
    year           int          not null,
    allocated      numeric(5,2) not null default 0,
    used           numeric(5,2) not null default 0,
    pending        numeric(5,2) not null default 0,
    carried        numeric(5,2) not null default 0,
    created_at     timestamptz  not null default now(),
    updated_at     timestamptz  not null default now(),
    created_by     varchar(64)  not null,
    updated_by     varchar(64)  not null,
    ip_address     inet,
    unique (employee_id, leave_type_id, year)
);

-- ---------------------------------------------------------------------
-- Leave requests + per-day rows.
-- ---------------------------------------------------------------------

create table leave_requests (
    id             bigint generated by default as identity primary key,
    employee_id    bigint       not null,
    leave_type_id  bigint       not null references leave_types(id),
    from_date      date         not null,
    to_date        date         not null,
    half_day       boolean      not null default false,
    half_day_part  varchar(8),
    days           numeric(5,2) not null,
    reason         text,
    status         varchar(16)  not null,
    created_at     timestamptz  not null default now(),
    updated_at     timestamptz  not null default now(),
    created_by     varchar(64)  not null,
    updated_by     varchar(64)  not null,
    ip_address     inet
);

create index idx_leaves_emp_status on leave_requests (employee_id, status);

create table leave_request_days (
    id                bigint generated by default as identity primary key,
    leave_request_id  bigint       not null references leave_requests(id),
    attendance_date   date         not null,
    status            varchar(16)  not null,
    decided_by        bigint,
    decided_at        timestamptz,
    decided_at_stage  int,
    rejection_reason  text,
    created_at        timestamptz  not null default now(),
    updated_at        timestamptz  not null default now(),
    created_by        varchar(64)  not null,
    updated_by        varchar(64)  not null,
    ip_address        inet,
    unique (leave_request_id, attendance_date)
);

create index idx_leave_days_request on leave_request_days (leave_request_id, status);
create index idx_leave_days_approved on leave_request_days (attendance_date, status) where status = 'APPROVED';

-- ---------------------------------------------------------------------
-- Overtime requests.
-- ---------------------------------------------------------------------

create table overtime_requests (
    id              bigint generated by default as identity primary key,
    employee_id     bigint       not null,
    attendance_date date         not null,
    reason          text,
    bulk_batch_id   uuid,
    status          varchar(16)  not null,
    created_at      timestamptz  not null default now(),
    updated_at      timestamptz  not null default now(),
    created_by      varchar(64)  not null,
    updated_by      varchar(64)  not null,
    ip_address      inet
);

create index idx_overtime_emp_date on overtime_requests (employee_id, attendance_date, status);
create index idx_overtime_batch on overtime_requests (bulk_batch_id) where bulk_batch_id is not null;

-- ---------------------------------------------------------------------
-- Regularization requests.
-- ---------------------------------------------------------------------

create table regularization_requests (
    id                  bigint generated by default as identity primary key,
    employee_id         bigint       not null,
    attendance_date     date         not null,
    requested_check_in  timestamptz,
    requested_check_out timestamptz,
    reason              text         not null,
    status              varchar(16)  not null,
    created_at          timestamptz  not null default now(),
    updated_at          timestamptz  not null default now(),
    created_by          varchar(64)  not null,
    updated_by          varchar(64)  not null,
    ip_address          inet,
    check (requested_check_in is not null or requested_check_out is not null)
);

create index idx_regularizations_emp on regularization_requests (employee_id, attendance_date, status);

-- ---------------------------------------------------------------------
-- Multi-stage approval chain (shared by leave / overtime / regularization)
-- + dynamic delegation of approval authority.
-- ---------------------------------------------------------------------

create table approval_steps (
    id            bigint generated by default as identity primary key,
    request_type  varchar(24)  not null,
    request_id    bigint       not null,
    stage_no      int          not null,
    stage_role    varchar(32)  not null,
    assigned_to   bigint,
    status        varchar(16)  not null,
    decided_by    bigint,
    decided_at    timestamptz,
    note          text,
    created_at    timestamptz  not null default now(),
    updated_at    timestamptz  not null default now(),
    created_by    varchar(64)  not null,
    updated_by    varchar(64)  not null,
    ip_address    inet,
    unique (request_type, request_id, stage_no)
);

create index idx_steps_assignee_pending on approval_steps (assigned_to, status) where status = 'PENDING';
create index idx_steps_role_pending on approval_steps (stage_role, status) where status = 'PENDING';

create table approval_delegations (
    id             bigint generated by default as identity primary key,
    delegator_id   bigint       not null,
    delegate_id    bigint       not null,
    request_types  varchar(24)[],
    from_date      date         not null,
    to_date        date,
    reason         text,
    status         varchar(16)  not null,
    revoked_at     timestamptz,
    revoked_by     bigint,
    created_at     timestamptz  not null default now(),
    updated_at     timestamptz  not null default now(),
    created_by     varchar(64)  not null,
    updated_by     varchar(64)  not null,
    ip_address     inet,
    check (delegator_id <> delegate_id),
    check (to_date is null or to_date >= from_date)
);

create index idx_delegations_delegate_active on approval_delegations (delegate_id, status) where status = 'ACTIVE';
create index idx_delegations_delegator_active on approval_delegations (delegator_id, status) where status = 'ACTIVE';
