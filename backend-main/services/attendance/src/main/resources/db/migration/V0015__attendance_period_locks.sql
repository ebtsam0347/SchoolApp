-- Period locks: a row here means "attendance for (year, month) is frozen
-- for payroll". The presence of the row IS the lock — there is no boolean
-- to toggle. POST /attendance/periods/lock upserts; POST /unlock deletes.
--
-- Enforcement (refusing punch / leave / regularization writes against a
-- locked period) is intentionally NOT in this migration. The lock row is
-- the audit anchor today; per-table enforcement is a follow-up that can
-- gate on existsByPeriodYearAndPeriodMonth without schema changes.

create table attendance_period_locks (
    id           bigint      generated by default as identity primary key,
    period_year  int         not null,
    period_month int         not null,
    locked_at    timestamp   not null default current_timestamp,
    locked_by    varchar(64) not null,
    created_at   timestamp   not null default current_timestamp,
    updated_at   timestamp   not null default current_timestamp,
    created_by   varchar(64) not null,
    updated_by   varchar(64) not null,
    ip_address   inet,
    constraint uq_attendance_period_locks unique (period_year, period_month),
    constraint chk_attendance_period_lock_month check (period_month between 1 and 12)
);
