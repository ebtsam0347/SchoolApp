-- Device sync: extend attendance_devices, add bridge / template / queue
-- tables for the attendance-poller sidecar (see docs/services/attendance.md
-- §3, §7 "Devices & device sync", §9). The poller is the only thing in the
-- system that speaks the ZK protocol to a reader; everything in this
-- migration sits on the Java side and gives the poller a place to claim
-- work, store captured templates, and report device health.

alter table attendance_devices
    add column comm_port     int          not null default 4370,
    add column comm_password int          not null default 0,
    add column is_enrollment boolean      not null default false,
    add column status        varchar(16)  not null default 'UNKNOWN',
    add column last_seen_at  timestamptz;

-- Bridge: which employees should exist on which devices. card_number is
-- denormalized from the employee record at the moment the assignment is
-- made; it's the value the device stores as user_id (see CLAUDE.md
-- "card_number = device user_id" decision and the §7 rule). On a card
-- change in employee-service, the bridge row is re-snapshotted by the
-- employee.updated consumer (queues UPSERT_USER with oldCardNumber).
create table attendance_device_users (
    id              bigint generated by default as identity primary key,
    device_id       bigint      not null references attendance_devices(id),
    employee_id     bigint      not null,
    card_number     varchar(32) not null,
    privilege       smallint    not null default 0,
    has_fingerprint boolean     not null default false,
    has_face        boolean     not null default false,
    synced_at       timestamptz,
    created_at      timestamptz not null default now(),
    updated_at      timestamptz not null default now(),
    created_by      varchar(64) not null,
    updated_by      varchar(64) not null,
    ip_address      inet,
    unique (device_id, employee_id)
);

create index idx_device_users_employee
    on attendance_device_users (employee_id);
create index idx_device_users_device_synced
    on attendance_device_users (device_id, synced_at);

-- Central biometric template store. One row per (employee, kind, finger).
-- Bytes are stored once and replicated to every device the employee is
-- enrolled on via a PUSH_TEMPLATE sync task. Bytea (not S3) — small
-- payloads (~500B fingerprint, ~10KB face), accessed transactionally
-- with the queue. template_format is the firmware-reported format code;
-- the poller checks it against the target device on every push and fails
-- the task non-retryably on mismatch (see §7, "Template format
-- compatibility").
create table attendance_employee_templates (
    id                 bigint      generated by default as identity primary key,
    employee_id        bigint      not null,
    kind               varchar(16) not null,
    finger_id          smallint,
    template           bytea       not null,
    template_format    smallint    not null,
    captured_device_id bigint      not null references attendance_devices(id),
    captured_at        timestamptz not null default now(),
    created_at         timestamptz not null default now(),
    updated_at         timestamptz not null default now(),
    created_by         varchar(64) not null,
    updated_by         varchar(64) not null,
    ip_address         inet,
    unique (employee_id, kind, finger_id)
);

create index idx_templates_employee
    on attendance_employee_templates (employee_id);

-- Outbox-style queue drained by attendance-poller. The poller polls
-- GET /devices/{id}/sync-tasks/next (atomic claim via FOR UPDATE SKIP
-- LOCKED), executes the task via pyzk, and reports back via
-- /complete or /fail. On fail, attempts increments and scheduled_for
-- gets exponential backoff (min(60s × 2^attempts, 1h)). After
-- hrms.attendance.device-sync.max-attempts (default 5) the row stays
-- FAILED and HR retries explicitly.
--
-- payload jsonb shape per task_type:
--   UPSERT_USER:    { cardNumber, name, privilege, oldCardNumber? }
--                   oldCardNumber set on a card change so the poller
--                   deletes the old id alongside upserting the new.
--   DELETE_USER:    { cardNumber }
--   PUSH_TEMPLATE:  { cardNumber, templateId, kind, fingerId }
--                   templateId points at attendance_employee_templates;
--                   poller fetches bytes via GET /templates/{id}.
create table attendance_device_sync_tasks (
    id             bigint      generated by default as identity primary key,
    device_id      bigint      not null references attendance_devices(id),
    employee_id    bigint      not null,
    task_type      varchar(24) not null,
    payload        jsonb       not null,
    status         varchar(16) not null default 'PENDING',
    attempts       int         not null default 0,
    last_error     text,
    scheduled_for  timestamptz not null default now(),
    claimed_at     timestamptz,
    completed_at   timestamptz,
    created_at     timestamptz not null default now(),
    updated_at     timestamptz not null default now(),
    created_by     varchar(64) not null,
    updated_by     varchar(64) not null,
    ip_address     inet
);

-- The poller's claim query: "next N rows for this device that are due."
-- Partial index keeps it tight against the active set rather than the
-- full historical log of completed tasks.
create index idx_sync_tasks_claim
    on attendance_device_sync_tasks (device_id, scheduled_for)
    where status in ('PENDING', 'IN_PROGRESS');

-- HR view: "what failed for this employee, across devices?"
create index idx_sync_tasks_failed
    on attendance_device_sync_tasks (employee_id)
    where status = 'FAILED';
