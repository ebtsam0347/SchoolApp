-- Non-attendance device events (canteen, access log). Devices typed
-- CANTEEN / ACCESS_LOG in attendance_devices still emit ZK punches; we
-- persist them here instead of attendance_punches so they don't feed
-- shift resolution, the attendance recompute, or the punch_recorded
-- outbox event. employee_id is resolved at ingest from the raw
-- employee_code via attendance_employees and may be null if the snapshot
-- doesn't know that code yet — no replay queue, the row is the record.

create table device_event_logs (
    id              bigint generated by default as identity primary key,
    device_id       bigint      not null references attendance_devices(id),
    employee_code   varchar(64) not null,
    employee_id     bigint,
    punched_at      timestamp   not null,
    device_type     varchar(16) not null,

    created_at      timestamp   not null default now(),
    updated_at      timestamp   not null default now(),
    created_by      varchar(64) not null,
    updated_by      varchar(64) not null,
    ip_address      inet,

    unique (device_id, employee_code, punched_at)
);

create index device_event_logs_device_punched_at_idx
    on device_event_logs (device_id, punched_at desc);

create index device_event_logs_employee_punched_at_idx
    on device_event_logs (employee_id, punched_at desc)
    where employee_id is not null;
