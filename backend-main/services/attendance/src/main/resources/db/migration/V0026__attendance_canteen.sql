-- Canteen (meal) attendance. Port of the legacy WebHRMS `PayRoll_meal`
-- table, trimmed to the columns the new UI actually uses: who ate, on
-- what date, at what time, from which device, and how many meals that
-- entry covers. The legacy day/month/year columns are derivable from
-- attendance_date; card_no / device_no / login_name_id / updatedBy_id
-- are covered by employee_id and the uniform audit columns.
--
-- This is deliberately NOT device_event_logs. That table is the raw,
-- device-sourced CANTEEN punch feed that payroll's grade-conditional
-- canteen deduction aggregates over; this one is the canteen clerk's
-- editable register (manual entry, edit, delete) and is the surface the
-- canteen role works with.
--
-- employee_id is the employee-schema row id (no cross-schema FK);
-- attendance_employees is the local mirror the service validates
-- against.

create table attendance_canteen (
    id              bigint      generated by default as identity primary key,
    employee_id     bigint      not null,
    attendance_date date        not null,
    attendance_time time        not null,
    -- Null on manual clerk entries; reserved for the canteen device
    -- poller (not built yet), which will stamp the terminal's IP.
    device_ip       varchar(45),
    count           int         not null default 1,

    created_at      timestamp   not null default current_timestamp,
    updated_at      timestamp   not null default current_timestamp,
    created_by      varchar(64) not null,
    updated_by      varchar(64) not null,
    ip_address      inet,

    constraint uq_attendance_canteen_employee_at unique (employee_id, attendance_date),
    constraint chk_attendance_canteen_count check (count > 0)
);

-- "Today's canteen attendance" and the date-range listing.
create index attendance_canteen_date_idx
    on attendance_canteen (attendance_date desc, attendance_time desc);

-- Per-employee + date-range listing.
create index attendance_canteen_employee_date_idx
    on attendance_canteen (employee_id, attendance_date desc);
