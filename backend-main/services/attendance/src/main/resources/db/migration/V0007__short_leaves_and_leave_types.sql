-- Short leave requests — sub-day leaves (employee leaves work for X
-- minutes during the workday with HR approval). Distinct from
-- regularization (forgot-to-punch) and from leave_requests (full or
-- half day). Reuses approval_steps + request_code_sequence (prefix SL).
--
-- Also extends the leave_types catalog with the PK manufacturing types
-- surfaced by the legacy WebHRMS migration:
--   - rename SICK → M1 / "Sick Leave" (8 days, matching legacy M1)
--   - new M2 / "Medical Leave" (180 days, long-term medical)
--   - new SPECIAL, FACTORY_DUTY, REST_DAY
--   - bump UNPAID quota to 30

create table short_leave_requests (
    id            bigint generated by default as identity primary key,
    request_code  varchar(20)  not null unique,
    employee_id   bigint       not null,
    leave_date    date         not null,
    start_time    time         not null,
    end_time      time         not null,
    reason        text,
    status        varchar(16)  not null,
    created_at    timestamptz  not null default now(),
    updated_at    timestamptz  not null default now(),
    created_by    varchar(64)  not null,
    updated_by    varchar(64)  not null,
    ip_address    inet,
    constraint chk_short_leave_window check (end_time > start_time)
);

create index idx_short_leaves_emp_status on short_leave_requests (employee_id, status);
create index idx_short_leaves_emp_date   on short_leave_requests (employee_id, leave_date desc);

