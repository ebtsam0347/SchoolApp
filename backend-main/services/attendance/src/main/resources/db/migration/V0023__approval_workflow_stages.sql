-- Configurable approval workflow chains. Replaces the hard-coded
-- WORKFLOW_CHAINS map in ApprovalService: HR maintains the ordered set of
-- stages per request type via /approval-workflows. Each stage resolves its
-- approver one of two ways:
--   MANAGER    — snapshot the submitter's manager (a delegate may stand in)
--   PERMISSION — role-only pool; anyone holding `approve_permission` acts
-- approval_steps snapshot resolver_kind / approve_permission / label at
-- submit, so editing a chain never disturbs in-flight requests.
--
-- New table uses plain `timestamp` per the project timestamp rule; the
-- pre-existing approval_steps below stays on its legacy `timestamptz`.

create table approval_workflow_stage (
    id                 bigint generated by default as identity primary key,
    request_type       varchar(24) not null,
    stage_no           int         not null,
    resolver_kind      varchar(16) not null,
    approve_permission varchar(64),
    label              varchar(48) not null,
    active             boolean     not null default true,
    created_at         timestamp   not null default now(),
    updated_at         timestamp   not null default now(),
    created_by         varchar(64) not null,
    updated_by         varchar(64) not null,
    ip_address         inet
);

-- At most one row per (type, stage_no) among the live chain.
create unique index uq_workflow_stage_active
    on approval_workflow_stage (request_type, stage_no) where active;

-- Seed today's behavior unchanged: 2-stage MANAGER -> HR for every type.
insert into approval_workflow_stage
    (request_type, stage_no, resolver_kind, approve_permission, label, created_by, updated_by)
select t.request_type, s.stage_no, s.resolver_kind, s.approve_permission, s.label, 'system', 'system'
from (values
        ('LEAVE'), ('SHORT_LEAVE'), ('OVERTIME'), ('REGULARIZATION')
     ) as t(request_type)
cross join (values
        (1, 'MANAGER',    null,                    'MANAGER'),
        (2, 'PERMISSION', 'attendance.hr.approve', 'HR')
     ) as s(stage_no, resolver_kind, approve_permission, label);

-- ---------------------------------------------------------------------
-- approval_steps: snapshot the resolution fields onto each step so the
-- runtime (openChain / canAct / per-day gating / events) reads the step,
-- not the catalog. Backfill from the old stage_role, then drop it.
-- ---------------------------------------------------------------------
alter table approval_steps add column resolver_kind      varchar(16);
alter table approval_steps add column approve_permission varchar(64);
alter table approval_steps add column label              varchar(48);

update approval_steps
   set resolver_kind      = case when stage_role = 'MANAGER' then 'MANAGER' else 'PERMISSION' end,
       approve_permission = case when stage_role = 'HR' then 'attendance.hr.approve' else null end,
       label              = stage_role;

alter table approval_steps alter column resolver_kind set not null;
alter table approval_steps alter column label         set not null;

drop index if exists idx_steps_role_pending;
create index idx_steps_roleonly_pending on approval_steps (request_type, status)
    where assigned_to is null and status = 'PENDING';

alter table approval_steps drop column stage_role;
