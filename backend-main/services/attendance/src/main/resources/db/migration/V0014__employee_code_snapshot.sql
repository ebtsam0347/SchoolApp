-- Punch matching reshape:
--
-- Decision: the device's user_id field IS the employees.employee_code.
-- The per-device card_number denormalization on attendance_device_users
-- was the wrong shape — it implied a card could differ across devices,
-- when in fact the same employee_code is what every device stores.
--
-- After this migration:
--   * attendance_employees holds (employee_id, employee_code, full_name)
--     denormalized from the employee schema via employee.created /
--     employee.updated events. Punch ingest looks up the employee from
--     this snapshot by employee_code — no per-device bridge join.
--   * attendance_device_users.card_number is dropped. The bridge keeps
--     its remaining role: "this employee is enrolled on this device"
--     plus has_fingerprint / has_face / synced_at.
--   * attendance_punch_unmatched.card_number is renamed to employee_code
--     for clarity — the column has always stored the device-side
--     identifier, which we now name correctly.

-- 1. Snapshot table populated by the employee.* event consumer.
--    Uses the project-wide bigint identity PK plus a unique on
--    employee_id so the upstream row id stays a stable foreign key.
create table attendance_employees (
    id            bigint      generated by default as identity primary key,
    employee_id   bigint      not null unique,
    employee_code varchar(32) not null unique,
    full_name     varchar(128) not null,
    created_at    timestamp   not null default current_timestamp,
    updated_at    timestamp   not null default current_timestamp,
    created_by    varchar(64) not null,
    updated_by    varchar(64) not null,
    ip_address    inet
);

create index idx_attendance_employees_code
    on attendance_employees (employee_code);

-- 2. One-shot backfill from the employee schema. Cross-schema reads at
--    runtime are forbidden; this is a migration-time bootstrap only,
--    matching the same trade-off the rest of the project makes.
insert into attendance_employees (employee_id, employee_code, full_name, created_by, updated_by)
select id, employee_code, full_name, 'system-init', 'system-init'
from employee.employees
on conflict (employee_id) do nothing;

-- 3. Drop the per-device card_number denormalization.
alter table attendance_device_users
    drop column card_number;

-- 4. Rename the unmatched-queue column for clarity. The unique
--    constraint key is the same triple, just with a clearer column name.
alter table attendance_punch_unmatched
    rename column card_number to employee_code;

alter table attendance_punch_unmatched
    rename constraint attendance_punch_unmatched_device_id_card_number_punched_at_key
    to uk_punch_unmatched_device_employee_code_at;

drop index if exists idx_punch_unmatched_card;
create index idx_punch_unmatched_employee_code
    on attendance_punch_unmatched (employee_code);
