-- chat-service schema. Lives in the `chat` Postgres schema (set via
-- spring.flyway.default-schema). See docs/services/chat.md.
--
-- Business entities (conversations, messages, message_attachments) carry
-- the standard audit columns. Bridges (conversation_members,
-- message_mentions, conversation_reads, message_deliveries) skip audit
-- columns by project convention.
--
-- All FKs to other services' rows (user_id, mentioned_user, etc.) are
-- plain bigint columns, not @ManyToOne — there is no `users` table in
-- this schema. Identity is owned by auth-service.

create table conversations (
    id              bigint generated by default as identity primary key,
    type            varchar(16)  not null,           -- DM | GROUP | BROADCAST
    title           varchar(200),                    -- null for DM
    created_by_user bigint       not null,
    last_message_id bigint,                          -- denormalized for "list my conversations" sort; nullable
    last_message_at timestamptz,
    -- DM uniqueness key: 'min(uid):max(uid)' — populated only for DMs.
    -- The partial unique index below makes get-or-create races safe.
    dm_key          varchar(40),
    -- audit
    created_at      timestamptz  not null default now(),
    updated_at      timestamptz  not null default now(),
    created_by      varchar(64)  not null,
    updated_by      varchar(64)  not null,
    ip_address      inet
);

create index idx_conversations_last_message_at
    on conversations (last_message_at desc nulls last);

create unique index uk_conversations_dm_key
    on conversations (dm_key) where type = 'DM';

-- Exactly one BROADCAST row org-wide (v1). The constant `((1))` makes
-- the index match every BROADCAST row at the same value, so a unique
-- constraint allows only one such row.
create unique index uk_conversations_one_broadcast
    on conversations ((1)) where type = 'BROADCAST';

-- Membership bridge — no audit columns.
create table conversation_members (
    conversation_id bigint       not null references conversations(id),
    user_id         bigint       not null,
    role            varchar(16)  not null default 'MEMBER',  -- MEMBER | OWNER
    joined_at       timestamptz  not null default now(),
    muted           boolean      not null default false,
    primary key (conversation_id, user_id)
);
create index idx_members_user on conversation_members (user_id);

create table messages (
    id              bigint generated by default as identity primary key,
    conversation_id bigint       not null references conversations(id),
    sender_user_id  bigint       not null,
    body            text         not null,                  -- empty string allowed if attachment-only
    body_tsv        tsvector,                               -- maintained by trigger
    edited_at       timestamptz,
    deleted_at      timestamptz,                            -- soft delete
    deleted_by_user bigint,
    delete_reason   varchar(32),                            -- SELF | ADMIN
    -- audit
    created_at      timestamptz  not null default now(),
    updated_at      timestamptz  not null default now(),
    created_by      varchar(64)  not null,
    updated_by      varchar(64)  not null,
    ip_address      inet
);

-- Timeline read: latest-first, per conversation.
create index idx_messages_conv_id_desc on messages (conversation_id, id desc);
-- Search index — built up by tsvector trigger.
create index idx_messages_body_tsv on messages using gin (body_tsv);

create function chat_messages_tsv_trigger() returns trigger as $$
begin
    new.body_tsv := to_tsvector('simple', coalesce(new.body, ''));
    return new;
end
$$ language plpgsql;
create trigger trg_messages_tsv before insert or update of body
    on messages for each row execute function chat_messages_tsv_trigger();

-- Attachments (one message can have N; size + content-type cap enforced
-- in service before persisting, after MinIO stat() confirms the upload).
create table message_attachments (
    id              bigint generated by default as identity primary key,
    message_id      bigint       not null references messages(id),
    object_key      varchar(512) not null,
    content_type    varchar(128) not null,
    size_bytes      bigint       not null,
    original_name   varchar(255) not null,
    -- audit
    created_at      timestamptz  not null default now(),
    updated_at      timestamptz  not null default now(),
    created_by      varchar(64)  not null,
    updated_by      varchar(64)  not null,
    ip_address      inet
);
create index idx_attachments_message on message_attachments (message_id);

-- @mentions — server stores the mentioned user ids (client sends them;
-- server validates each is a member). Bridge — no audit cols.
create table message_mentions (
    message_id     bigint not null references messages(id),
    mentioned_user bigint not null,
    primary key (message_id, mentioned_user)
);
create index idx_mentions_user on message_mentions (mentioned_user);

-- Per-(conversation,user) read cursor. Bridge — no audit cols. Unread
-- count for a user = count(*) of messages with id > last_read_message_id
-- and sender_user_id <> userId, in conversations they're a member of.
create table conversation_reads (
    conversation_id      bigint     not null references conversations(id),
    user_id              bigint     not null,
    last_read_message_id bigint     not null default 0,
    updated_at           timestamptz not null default now(),
    primary key (conversation_id, user_id)
);

-- Per-recipient delivery acks. Inserted by BFF after successful SSE
-- forward of a chat.message event. Drives the sender's ✓✓ "delivered"
-- indicator. Bridge — no audit cols.
create table message_deliveries (
    message_id   bigint     not null references messages(id),
    user_id      bigint     not null,
    delivered_at timestamptz not null default now(),
    primary key (message_id, user_id)
);
create index idx_deliveries_user on message_deliveries (user_id);
