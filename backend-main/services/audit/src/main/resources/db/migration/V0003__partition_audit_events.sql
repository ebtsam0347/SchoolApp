-- §6.6 — declarative monthly partitioning on audit_events(occurred_at).
--
-- Driver: HR retention is 4 years (docs/policy.md #9). Monthly partitions
-- let the daily maintenance job DROP partitions older than 48 months in
-- O(1) catalog ops instead of issuing wide DELETEs that would bloat the
-- table and the indexes. Insert path is unchanged for the application —
-- Postgres routes rows to the correct partition transparently.
--
-- Postgres rules that shape the migration:
--   1. A unique constraint on a partitioned table MUST include the
--      partition key. So PK becomes (id, occurred_at) and the event_id
--      uniqueness becomes (event_id, occurred_at). This still gives us
--      the dedupe guarantee we need: the producer's envelope sets both
--      event_id and occurred_at deterministically, so any duplicate
--      delivery has the same pair.
--   2. ALTER TABLE … PARTITION BY is not supported. We rename the old
--      table aside, create a new partitioned shell, copy rows in, drop
--      the legacy table.
--   3. Identity columns are supported on partitioned tables in PG ≥ 11.
--      We reseed the sequence past max(id) post-copy so future inserts
--      never collide.

alter table audit_events rename to audit_events_legacy;

-- Postgres' RENAME TABLE leaves index names alone, so the legacy
-- table's indexes still occupy the names we want for the new
-- partitioned parent. Drop them — the legacy table is going away at
-- the end of the migration anyway and we never query it again.
drop index if exists idx_audit_events_entity;
drop index if exists idx_audit_events_actor;
drop index if exists idx_audit_events_correlation;
drop index if exists idx_audit_events_timeline;

create table audit_events (
    id              bigint generated by default as identity,
    event_id        varchar(64)  not null,
    source_service  varchar(32)  not null,
    entity_type     varchar(64)  not null,
    entity_id       varchar(64)  not null,
    action          varchar(64)  not null,
    actor_user_id   bigint,
    actor_username  varchar(64),
    actor_label     varchar(128),
    before_json     jsonb,
    after_json      jsonb,
    changes         jsonb,
    metadata        jsonb,
    correlation_id  varchar(64)  not null,
    ip_address      inet,
    user_visible    boolean      not null default false,
    message         text,
    occurred_at     timestamp    not null,
    ingested_at     timestamp    not null default now(),
    primary key (id, occurred_at),
    constraint uq_audit_events_event_id unique (event_id, occurred_at)
) partition by range (occurred_at);

-- Indexes declared on the parent are propagated to every partition (PG ≥ 11).
create index idx_audit_events_entity
    on audit_events (entity_type, entity_id, occurred_at desc);

create index idx_audit_events_actor
    on audit_events (actor_user_id, occurred_at desc);

create index idx_audit_events_correlation
    on audit_events (correlation_id);

create index idx_audit_events_timeline
    on audit_events (entity_type, entity_id, occurred_at desc)
    where user_visible = true;

-- Pre-create monthly partitions: from the oldest existing row (or
-- current month if the table was empty) through current month + 2
-- months ahead. The maintenance job (AuditPartitionService) extends
-- this window forward daily.
do $$
declare
    start_month date;
    end_month   date;
    cur_month   date;
    part_name   text;
begin
    select coalesce(date_trunc('month', min(occurred_at))::date,
                    date_trunc('month', current_date)::date)
      into start_month
      from audit_events_legacy;
    end_month := (date_trunc('month', current_date) + interval '2 months')::date;
    cur_month := start_month;
    while cur_month <= end_month loop
        part_name := format('audit_events_%s', to_char(cur_month, 'YYYYMM'));
        execute format(
            'create table if not exists %I partition of audit_events
              for values from (%L) to (%L)',
            part_name,
            cur_month,
            (cur_month + interval '1 month')::date);
        cur_month := (cur_month + interval '1 month')::date;
    end loop;
end$$;

-- Default partition: catches rows whose occurred_at falls outside the
-- pre-created range. Without this, an out-of-range insert would fail.
-- The maintenance job logs (and surfaces via metric) any rows that
-- land here so we can backfill a partition retroactively if needed.
create table audit_events_default partition of audit_events default;

-- Copy from legacy. Identity column is overridden to preserve ids so
-- existing references (e.g. links the FE rendered with audit-event
-- ids in URLs) keep working.
insert into audit_events (
    id, event_id, source_service, entity_type, entity_id, action,
    actor_user_id, actor_username, actor_label,
    before_json, after_json, changes, metadata,
    correlation_id, ip_address, user_visible, message,
    occurred_at, ingested_at)
overriding system value
select
    id, event_id, source_service, entity_type, entity_id, action,
    actor_user_id, actor_username, actor_label,
    before_json, after_json, changes, metadata,
    correlation_id, ip_address, user_visible, message,
    occurred_at, ingested_at
from audit_events_legacy;

-- Bump the identity sequence past the highest carried-over id.
select setval(
    pg_get_serial_sequence('audit.audit_events', 'id'),
    coalesce((select max(id) from audit_events), 0) + 1,
    false);

drop table audit_events_legacy;
