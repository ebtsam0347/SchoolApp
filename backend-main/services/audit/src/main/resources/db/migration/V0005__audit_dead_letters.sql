-- Durable parking for audit envelopes that fail parse/validation at
-- ingest. Before this migration the SKIPPED branch of AuditIngestService
-- only logged + ack'd, so a producer-side bug silently dropped events
-- past Kafka retention (see 7f5d8c3 — every audit event across every
-- service was lost for an unknown window).
--
-- Consumer writes a row here in the same code path that used to return
-- SKIPPED, then ack's. Operator triages via /admin/audit/dead-letters,
-- replays after the producer is fixed, or discards.
--
-- Not partitioned and no audit columns: this is a system table, not a
-- business entity. Steady-state size is ~0; rows exist only while a bug
-- is open. Idempotent re-delivery is handled at replay time by
-- audit_events' (event_id, occurred_at) unique index — duplicates
-- collapse there, not here.

create table audit_dead_letters (
    id              bigint generated by default as identity primary key,
    source_service  varchar(32)  not null,
    topic           varchar(64)  not null,
    kafka_partition integer      not null,
    kafka_offset    bigint       not null,
    kafka_key       varchar(255),
    raw_payload     text         not null,
    reason          varchar(64)  not null,
    reason_detail   text,
    received_at     timestamp    not null default now(),
    last_replay_at  timestamp,
    replay_attempts integer      not null default 0
);

-- Triage view: "what's still parked from auth in the last hour?"
create index idx_audit_dead_letters_source_received
    on audit_dead_letters (source_service, received_at desc);

-- Group by reason for the alert + dashboard ("how many MALFORMED_JSON
-- vs UNPARSEABLE_OCCURRED_AT this morning").
create index idx_audit_dead_letters_reason
    on audit_dead_letters (reason);

-- Same caps as audit_events. A misbehaving producer shouldn't be able
-- to wedge the dead-letter table either.
alter table audit_dead_letters
    add constraint chk_audit_dead_letters_payload_size
    check (octet_length(raw_payload) < 1048576);

alter table audit_dead_letters
    add constraint chk_audit_dead_letters_detail_length
    check (reason_detail is null or length(reason_detail) <= 4000);
