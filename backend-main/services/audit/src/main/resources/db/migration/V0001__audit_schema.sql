-- audit-service schema. Lives in the `audit` Postgres schema (set via
-- spring.flyway.default-schema). audit_events is itself the audit table —
-- it does not carry the standard created_by/updated_by columns; its own
-- fields cover that role.
--
-- Append-only. No update/delete except via retention policy. Idempotent
-- ingest is enforced by a unique constraint on event_id (the envelope id
-- generated at the emitting service).

create table audit_events (
    id              bigint generated by default as identity primary key,
    event_id        varchar(64)  not null unique,
    source_service  varchar(32)  not null,
    entity_type     varchar(64)  not null,
    entity_id       varchar(64)  not null,
    action          varchar(64)  not null,
    actor_user_id   bigint,
    actor_username  varchar(64),
    actor_label     varchar(128),
    before_json     jsonb,
    after_json      jsonb,
    changes         jsonb,
    metadata        jsonb,
    correlation_id  varchar(64)  not null,
    ip_address      inet,
    user_visible    boolean      not null default false,
    message         text,
    occurred_at     timestamptz  not null,
    ingested_at     timestamptz  not null default now()
);

create index idx_audit_events_entity
    on audit_events (entity_type, entity_id, occurred_at desc);

create index idx_audit_events_actor
    on audit_events (actor_user_id, occurred_at desc);

create index idx_audit_events_correlation
    on audit_events (correlation_id);

create index idx_audit_events_timeline
    on audit_events (entity_type, entity_id, occurred_at desc)
    where user_visible = true;
